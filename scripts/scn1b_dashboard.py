def _generate_patients():
    """Generate 41 synthetic SCN1B GEFS+/Dravet-like/Brugada patients with realistic parameters."""
    rng = random.Random(42)
    categories = [
        ("SCN1B-AD-LOF-truncating-GEFS+-classic", 40),
        ("SCN1B-de-novo-LOF-Dravet-like-DEE", 25),
        ("SCN1B-missense-mild-GEFS+-febrile-only", 20),
        ("SCN1B-Brugada-cardiac-overlap", 8),
        ("SCN1B-negative-phenocopy-SCN1A-SCN2A-GABRA1-KCNQ2", 7),
    ]
    patients = []
    pid = 1
    for cat, pct in categories:
        n = round(41 * pct / 100)
        is_gefs_ad = "GEFS+-classic" in cat
        is_dravet = "Dravet-like" in cat
        is_mild = "febrile-only" in cat
        is_brugada = "Brugada" in cat
        is_phenocopy = "phenocopy" in cat
        for _ in range(n):
            if pid > 41:
                break
            # Onset months
            if is_dravet:
                onset_m = rng.randint(4, 14)
            elif is_mild:
                onset_m = rng.randint(6, 24)
            elif is_gefs_ad:
                onset_m = rng.randint(8, 36)
            elif is_brugada:
                onset_m = rng.randint(12, 48)
            else:
                onset_m = rng.randint(6, 30)

            # Clinical flags
            gefs_plus = not is_dravet and not is_phenocopy and rng.random() < 0.88
            dravet_like = is_dravet and rng.random() < 0.90
            brugada_ecg = (is_brugada and rng.random() < 0.90) or (not is_phenocopy and rng.random() < 0.12)
            drug_resistant = is_dravet and rng.random() < 0.70
            on_kd = drug_resistant and rng.random() < 0.45
            on_vpa = (is_dravet or is_gefs_ad) and rng.random() < 0.78
            polg_tested = "Y" if rng.random() < 0.80 else "N"
            west_syndrome = is_dravet and rng.random() < 0.22
            on_stp = is_dravet and rng.random() < 0.60
            on_ffa = drug_resistant and rng.random() < 0.30

            patients.append({
                "id": f"SCN1B-{pid:02d}",
                "category": cat,
                "onset_months": onset_m,
                "gefs_plus": gefs_plus,
                "dravet_like": dravet_like,
                "brugada_ecg": brugada_ecg,
                "drug_resistant": drug_resistant,
                "on_kd": on_kd,
                "on_vpa": on_vpa,
                "polg_tested": polg_tested,
                "west_syndrome": west_syndrome,
                "on_stp": on_stp,
                "on_ffa": on_ffa,
            })
            pid += 1
    return patients


