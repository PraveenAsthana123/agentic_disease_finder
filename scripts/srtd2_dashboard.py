import random
import math

SEED = 409
N    = 40   # 40-patient educational cohort

rng  = random.Random(SEED)

# ── helpers ──────────────────────────────────────────────────────────────────
def _pct(n, total=N):
    return round(n / total * 100)

def _split(total, *fractions):
    buckets = [round(total * f) for f in fractions]
    diff = total - sum(buckets)
    buckets[0] += diff
    return buckets

# ── patient-level data (fixed seed) ──────────────────────────────────────────
patients = []
ethnicities = [
    ('Middle Eastern / North African', 0.35),   # consanguineous — homozygous WD4/5 missense
    ('European',                        0.28),   # compound het — WD7/8 missense + truncating
    ('South Asian',                     0.18),   # hypomorphic WD11/12 — CED2
    ('East Asian',                      0.10),
    ('Latin American',                  0.06),
    ('Other / Unknown',                 0.03),
]
eth_pool = []
for eth, frac in ethnicities:
    eth_pool.extend([eth] * round(frac * N))
while len(eth_pool) < N:
    eth_pool.append('Other / Unknown')
rng.shuffle(eth_pool)

allele_classes = [
    'Homozygous WD4/5 missense (WDR19/IFT144 contact surface)',
    'Compound het: WD7/8 missense + truncating (TTC21B-dock disrupted)',
    'Biallelic truncating (null/null — SRPS spectrum)',
    'Compound het: WD3/4 missense + WD8/9 missense (dual-face disruption)',
    'Hypomorphic WD11/12 missense (IFT43-face — CED2 dominant)',
]
allele_weights = [0.26, 0.24, 0.20, 0.16, 0.14]

for i in range(N):
    eth    = eth_pool[i]
    allele = rng.choices(allele_classes, weights=allele_weights)[0]
    sex    = rng.choice(['M', 'F'])

    # Thorax severity
    thorax_map = {
        'Biallelic truncating (null/null — SRPS spectrum)':                      (0.80, 0.14, 0.06),
        'Homozygous WD4/5 missense (WDR19/IFT144 contact surface)':             (0.38, 0.40, 0.22),
        'Compound het: WD7/8 missense + truncating (TTC21B-dock disrupted)':    (0.55, 0.30, 0.15),
        'Compound het: WD3/4 missense + WD8/9 missense (dual-face disruption)': (0.48, 0.34, 0.18),
        'Hypomorphic WD11/12 missense (IFT43-face — CED2 dominant)':            (0.08, 0.26, 0.66),
    }
    tw = thorax_map[allele]
    thorax = rng.choices(
        ['Severe (neonatal ventilation)', 'Moderate (CPAP/BiPAP)', 'Mild (nasal O2/none)'],
        weights=tw
    )[0]

    # CED2 ectodermal features (hypomorphic WD11/12 → CED2)
    ced2 = allele == 'Hypomorphic WD11/12 missense (IFT43-face — CED2 dominant)'
    ced2_features = []
    if ced2:
        if rng.random() < 0.85: ced2_features.append('Sparse hair / hypotrichosis')
        if rng.random() < 0.78: ced2_features.append('Hypodontia / oligodontia')
        if rng.random() < 0.65: ced2_features.append('Narrow forehead / frontal bossing')
        if rng.random() < 0.60: ced2_features.append('Brachydactyly (shortened digits)')
        if rng.random() < 0.50: ced2_features.append('Nail dysplasia')

    # Polydactyly (40–45%; postaxial dominant)
    poly_prob = 0.68 if 'truncating' in allele.lower() else 0.32 if ced2 else 0.43
    poly      = rng.random() < poly_prob
    poly_type = rng.choices(
        ['Postaxial (hands+feet)', 'Both postaxial + preaxial', 'Preaxial only'],
        weights=[0.72, 0.22, 0.06]
    )[0] if poly else None

    # Ciliary EM — IFT-A class: short stubby (not club/bulging tip, not variable)
    if 'truncating' in allele.lower() and 'null/null' in allele:
        em_pattern = rng.choices(
            ['Short stubby (IFT-A class)', 'Absent / rudimentary (null allele)'],
            weights=[0.55, 0.45]
        )[0]
    elif ced2:
        em_pattern = rng.choices(
            ['Short stubby (IFT-A class)', 'Near-normal (hypomorphic — ectodermal cilia only)'],
            weights=[0.30, 0.70]
        )[0]
    else:
        em_pattern = rng.choices(
            ['Short stubby (IFT-A class)', 'Short stubby + transition zone accumulation'],
            weights=[0.80, 0.20]
        )[0]

    # Retinal (10–15%; rod-cone; lower than IFT-A peers WDR19/IFT140; no retinal-only allele)
    ret_prob = 0.05 if ced2 else 0.12
    retinal  = rng.random() < ret_prob
    ret_type = rng.choices(
        ['Rod-cone dystrophy', 'Mild photoreceptor degeneration'],
        weights=[0.65, 0.35]
    )[0] if retinal else None

    # CED2 — primary presentation without thoracic disease
    ced2_only = ced2 and rng.random() < 0.42

    # Renal (20–30%: TIN / ESRD / cysts)
    renal_prob = 0.40 if 'truncating' in allele.lower() else 0.10 if ced2 else 0.22
    renal_any  = rng.random() < renal_prob
    renal_type = rng.choices(
        ['Tubulointerstitial nephritis (TIN)', 'Renal cysts (structural)', 'ESRD requiring transplant'],
        weights=[0.52, 0.32, 0.16]
    )[0] if renal_any else None

    # CHF / hepatic (5–8%)
    chf = rng.random() < 0.06

    # VEPTR / MAGEC
    veptr = thorax in ['Moderate (CPAP/BiPAP)', 'Mild (nasal O2/none)'] and (not ced2_only) and rng.random() < 0.84

    # Renal transplant
    tx = renal_type == 'ESRD requiring transplant' and rng.random() < 0.72

    # Age at diagnosis
    if ced2_only:
        age_dx_cat = rng.choices(
            ['0–1 yr (neonatal)', '2–5 yr (infant)', '6–10 yr (child)', '11–18 yr (teen-adult)'],
            weights=[0.05, 0.25, 0.42, 0.28]
        )[0]
    else:
        age_dx_cat = rng.choices(
            ['0–1 yr (neonatal/prenatal)', '2–5 yr (infant)', '6–10 yr (child)', '11–16 yr (teen)'],
            weights=[0.68, 0.20, 0.08, 0.04]
        )[0]

    # Misdiagnosis (high — IFT-A short-stubby EM undifferentiated)
    if not ced2_only and rng.random() < 0.52:
        mis = rng.choices(
            ['SRTD5 / WDR19 (most common IFT-A SRTD)', 'SRTD9 / IFT140 (IFT-A short stubby)',
             'SRTD3 / DYNC2H1 (most common SRTD overall)', 'SRTD7 / WDR35 (IFT-A — direct IFT140 partner)'],
            weights=[0.36, 0.28, 0.20, 0.16]
        )[0]
    elif ced2_only and rng.random() < 0.62:
        mis = 'Ectodermal dysplasia / Ellis-van Creveld (CED2 without thoracic disease)'
    else:
        mis = None

    # Perinatal death
    perinatal_death = allele == 'Biallelic truncating (null/null — SRPS spectrum)' and rng.random() < 0.38

    patients.append({
        'id': i, 'sex': sex, 'eth': eth, 'allele': allele,
        'thorax': thorax, 'poly': poly, 'poly_type': poly_type,
        'em_pattern': em_pattern,
        'retinal': retinal, 'ret_type': ret_type,
        'ced2': ced2, 'ced2_features': ced2_features, 'ced2_only': ced2_only,
        'renal_any': renal_any, 'renal_type': renal_type,
        'chf': chf, 'veptr': veptr, 'tx': tx,
        'age_dx_cat': age_dx_cat, 'misdiagnosis': mis,
        'perinatal_death': perinatal_death,
    })

# ── aggregate statistics ──────────────────────────────────────────────────────
_poly_n        = sum(1 for p in patients if p['poly'])
_renal_n       = sum(1 for p in patients if p['renal_any'])
_retinal_n     = sum(1 for p in patients if p['retinal'])
_ced2_n        = sum(1 for p in patients if p['ced2'])
