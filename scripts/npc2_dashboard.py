def _patients():
    """Generate a reproducible 40-patient NPC2 cohort.
    NPC2 skews more towards early infantile/perinatal due to pulmonary disease
    causing earlier mortality and diagnosis."""
    types = [
        ("Perinatal/Neonatal (PAP + Hepatic)", 0.10, (0.0, 0.5)),
        ("Early Infantile (PAP-dominant)", 0.30, (0.5, 2.0)),
        ("Late Infantile Neurological", 0.38, (2.0, 6.0)),
        ("Juvenile Neurological", 0.18, (6.0, 15.0)),
        ("Adult Neurological", 0.04, (15.0, 30.0)),
    ]
    patients = []
    counts = [4, 12, 15, 7, 2]   # sums to 40; more infantile than NPC1
    pid = 1
    for (tname, _, age_range), cnt in zip(types, counts):
        for _ in range(cnt):
            age = round(random.uniform(*age_range), 1)
            seizure = random.random() < 0.55  # slightly lower than NPC1 (early mortality)
            vsgp = random.random() < 0.93
            cataplexy = random.random() < 0.70
            ataxia = random.random() < 0.85
            pap = tname in ("Perinatal/Neonatal (PAP + Hepatic)", "Early Infantile (PAP-dominant)") \
                  or random.random() < 0.25
            patients.append({
                "id": pid, "type": tname, "onset_age": age,
                "seizure": seizure, "vsgp": vsgp, "cataplexy": cataplexy,
                "ataxia": ataxia, "pap": pap,
                "on_miglustat": random.random() < 0.40,
                "on_vpa": random.random() < 0.65 if seizure else False,
                "on_lev": random.random() < 0.50 if seizure else False,
            })
            pid += 1
    return patients


