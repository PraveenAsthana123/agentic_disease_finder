"""
GNAO1 Encephalopathy — DEE17 / Ohtahara Syndrome / G-protein Alpha-O1 / GOF-LOF Dual
======================================================================================
41-patient cohort · GNAO1 (16q13) · De novo dominant · Congenital / Early-infantile onset DEE

GNAO1 BIOLOGY:
GNAO1 (Guanine Nucleotide-binding protein G(o) subunit Alpha-1, 16q13) encodes Gαo,
the most abundant G-protein alpha subunit in the central nervous system (comprising
~1% of total membrane protein in the brain). Gαo is the primary alpha subunit of
Go-type heterotrimeric G-proteins (Gαβγ), which are:
  (a) Presynaptic inhibitors: Gαo couples to Gi/o-coupled GPCRs (GABA-B, μ-opioid,
      mGluR2/3, dopamine D2/D4, serotonin 5-HT1, α2-adrenergic, adenosine A1) to
      inhibit adenylyl cyclase and mediate presynaptic inhibition.
  (b) Voltage-gated Ca2+ channel modulators: Gβγ released upon Gαo activation
      → voltage-dependent inhibition of N-type (Cav2.2) and P/Q-type (Cav2.1) VGCCs
      → reduces presynaptic Ca2+ → reduces neurotransmitter release.
  (c) GIRK activators: Gβγ also activates G-protein-coupled inwardly rectifying K+
      channels (GIRK/Kir3) → hyperpolarisation → reduced excitability.
  (d) Developmental roles: Gαo signals downstream of Wnt, Frizzled, and LGR4 during
      cerebellar development and synaptic pruning (Gαo activates dishevelled/DVL).

GNAO1 DUAL MECHANISM (GOF vs LOF — critical for treatment decisions):
  GOF (Gain-of-Function, ~56% of pathogenic variants):
    - Constitutively active Gαo → persistent Gβγ release → chronic VGCC inhibition
      → presynaptic neurotransmitter release severely reduced (GABA + glutamate)
    - Paradox: despite being a "inhibitory" G-protein, GOF → global synaptic depression
      → compensatory upregulation of post-synaptic NMDA/AMPA → network hyperexcitability
      + severe movement disorder (hyperkinetic dyskinesias)
    - Hallmark: HYPERKINETIC movement disorder (choreoathetosis, ballism) + refractory epilepsy
    - MRI: frequently normal or subtle volume loss
    - EEG: burst-suppression in neonates → evolving multifocal / hypsarrhythmia
    - Key GOF variants: Arg209Cys (R209C), Arg209His (R209H), Glu246Lys (E246K),
      Glu246Val (E246V), Ile184Ser (I184S)

  LOF (Loss-of-Function, ~44%):
    - Haploinsufficiency / reduced Gαo → impaired presynaptic GABA-B/GIRK signalling
      → reduced hyperpolarisation → increased presynaptic Ca2+ entry → increased
      neurotransmitter release → cortical hyperexcitability → predominantly epilepsy
    - Hallmark: predominantly EPILEPSY phenotype with milder or absent movement disorder
    - MRI: cortical malformations in some (simplified gyral pattern, frontal pachygyria)
    - EEG: hypsarrhythmia / infantile spasms; focal multifocal spikes
    - Key LOF variants: frameshift, nonsense, splice-site; some missense Thr/Ala core

GNAO1 SYNDROME SPECTRUM:
  1. OHTAHARA SYNDROME (OS) / DEE-GNAO1 — 58%:
     Onset first weeks of life → tonic spasms → burst-suppression EEG.
     GOF-predominant. Most severe; 35% mortality by age 2.
  2. WEST SYNDROME (IS + Hypsarrhythmia) — 42%:
     Onset 3-8 months → infantile spasms → hypsarrhythmia.
     Both GOF and LOF.
  3. LENNOX-GASTAUT TRANSITION — 35% evolve from OS/IS.
  4. MOVEMENT DISORDER (MD) WITHOUT PROMINENT EPILEPSY — 18%:
     Mostly GOF; severe hyperkinetic choreoathetosis but seizures manageable.

CONTRAINDICATIONS IN GNAO1 ENCEPHALOPATHY:
  1. VALPROATE IN GNAO1-OHTAHARA (relative CI, not absolute):
     OS/burst-suppression neonates often receive VPA; no specific GNAO1 toxicity BUT
     POLG co-variants must be excluded first (POLG on background not infrequent in
     severe DEEs). VPA hepatotoxicity risk mandates POLG testing before VPA.
  2. TIAGABINE (ABSOLUTE CI):
     GAT-1 inhibitor → excess synaptic GABA → in severely dysmature cortex (GNAO1-GOF)
     → non-convulsive SE. Same mechanism as FOXG1 CI.
  3. LAMOTRIGINE IN OHTAHARA/GOF (avoid first-line):
     LTG is a sodium-channel blocker; tonic spasms of Ohtahara respond poorly to
     NaV blockers. In some GOF patients with predominantly tonic/hypermotor seizures,
     LTG may aggravate. Use with caution; prefer broad-spectrum agents.
  4. PALLIDAL DEEP BRAIN STIMULATION (PALLIDAL DBS) — CONTRAINDICATED in GOF:
     Gpi/GPi DBS is used for hyperkinetic movement disorders generally, but in
     GNAO1-GOF the constitutively active Gαo has already disrupted pallidal circuitry
     in an unusual way — pallidotomy/DBS may paradoxically worsen seizure burden.
     Thalamic DBS (VIM nucleus) is investigational; consult specialist centre only.
  5. PHENOBARBITONE MONOTHERAPY LONG-TERM:
     PB increases GABA-A receptor activity initially but drives receptor downregulation
     chronically — in GNAO1-GOF where presynaptic GABA release is already impaired,
     additional post-synaptic GABA-A downregulation worsens net inhibition deficit.
  6. CARBONIC ANHYDRASE INHIBITORS (ACETAZOLAMIDE) — use with caution in GOF:
     Acetazolamide/Topiramate (CAI mechanism) can worsen metabolic acidosis in
     already nutritionally-compromised children on KD; monitor pH and bicarbonate.

PRECISION TREATMENTS:
  - CARBAMAZEPINE (CBZ) for MOVEMENT DISORDER (NOT seizures):
    Paradoxically, CBZ at low doses (5-10 mg/kg/day) can REDUCE hyperkinetic
    movement disorder in GNAO1-GOF via its mechanism on voltage-gated Na+ channels
    in the basal ganglia — reduces burst firing. IMPORTANT: CBZ does NOT reliably
    control the epilepsy component (may worsen absence/myoclonic elements).
    CBZ = specific GNAO1 movement disorder treatment, distinct from its epilepsy role.
  - QUINIDINE (investigational):
    Quinidine blocks constitutively active Gαo-coupled GIRK channels; in vitro rescue
    of GNAO1-GOF documented (Feng 2017 Sci Transl Med). Small patient series show
    movement disorder improvement. OFF-LABEL; QTc monitoring mandatory.
  - VIGABATRIN + ACTH for West syndrome component (same Level A evidence as other DEE).
  - KD (Ketogenic Diet): mechanistically sound — β-OHB and acetone modulate synaptic
    transmission independently of G-protein pathway.
  - CLONAZEPAM for movement disorder: GABA-B + GABA-A modulation; useful adjunct.
"""

