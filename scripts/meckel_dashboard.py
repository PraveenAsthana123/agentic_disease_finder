def _build_cohort() -> list:
    rng = random.Random(_SEED)

    ethnicities_pool = _ETHNICITIES[:]
    rng.shuffle(ethnicities_pool)
    ethnicities_pool = (ethnicities_pool * 2)[:_N]

    cohort = []
    for i in range(_N):
        # Maternal age (pregnancy age at diagnosis)
        maternal_age = rng.randint(22, 42)
        # Fetal sex (if determinable — some MKS not sexed due to genital ambiguity)
        fetal_sex = rng.choices(["Male", "Female", "Indeterminate/not reported"], weights=[45, 45, 10], k=1)[0]
        gene = rng.choice(_GENES)
        encephalocele = rng.choice(_ENCEPHALOCELE_TYPES)
        renal = rng.choice(_RENAL_FINDINGS)
        polydactyly = rng.choice(_POLYDACTYLY_TYPES)

        is_tmem67 = "TMEM67" in gene
        is_tmem216 = "TMEM216" in gene
        is_cc2d2a = "CC2D2A" in gene

        # Hepatic — prominent in TMEM67/CC2D2A
        if is_tmem67 or is_cc2d2a:
            hepatic = rng.choices(_HEPATIC_FINDINGS, weights=[40, 30, 5, 15, 10], k=1)[0]
        else:
            hepatic = rng.choices(_HEPATIC_FINDINGS, weights=[15, 10, 50, 5, 20], k=1)[0]
        has_hepatic_chf = "Normal" not in hepatic

        additional = rng.choice(_ADDITIONAL_DEFECTS)
        ga_dx = rng.choice(_GESTATIONAL_AGE_DIAGNOSIS)
        outcome = rng.choice(_OUTCOMES)
        prior_dx = rng.choice(_PRIOR_DIAGNOSES_FETAL)
        ethnicity = ethnicities_pool[i]

        # Consanguinity — more common in Middle Eastern / Pakistani
        consanguineous_pops = ["Middle Eastern", "Pakistani", "Turkish", "Lebanese", "Saudi Arabian",
                               "Iranian", "Yemeni", "Moroccan", "Algerian", "Tunisian"]
        is_consanguineous = ethnicity in consanguineous_pops and rng.random() < 0.65

        # Holoprosencephaly — TMEM216-prominent
        has_hpe = is_tmem216 and rng.random() < 0.70

        # Situs inversus
        has_situs_inv = "Situs inversus" in additional

        # Pulmonary hypoplasia (nearly universal if kidneys large + oligohydramnios)
        has_pulm_hypo = rng.random() < 0.88

        # Cardiac defect
        has_cardiac = "Cardiac" in additional or "VSD" in additional or rng.random() < 0.20

        # Potter sequence
        has_potter = "Potter" in renal or rng.random() < 0.55

        # PGT-M planned
        pgt_planned = rng.choices([True, False], weights=[65, 35], k=1)[0]

        # GA at delivery/death
        if "TOPF" in outcome:
            ga_delivery = rng.randint(18, 24)
        elif "Intrauterine" in outcome or "Stillbirth" in outcome:
            ga_delivery = rng.randint(26, 36)
        else:
            ga_delivery = rng.randint(36, 40)  # live born (rare)

        # Prior affected pregnancy
        prior_affected_preg = rng.choices([True, False], weights=[30, 70], k=1)[0]

        cohort.append({
            "id":                     i + 1,
            "maternal_age":           maternal_age,
            "fetal_sex":              fetal_sex,
            "gene":                   gene,
            "encephalocele_type":     encephalocele,
            "renal_finding":          renal,
            "polydactyly_type":       polydactyly,
            "hepatic_finding":        hepatic,
            "additional_defects":     additional,
            "gestational_age_at_dx":  ga_dx,
            "gestational_age_delivery": ga_delivery,
            "outcome":                outcome,
            "prior_differential_dx":  prior_dx,
            "ethnicity":              ethnicity,
            "consanguineous":         is_consanguineous,
            "has_hepatic_chf":        has_hepatic_chf,
            "has_holoprosencephaly":  has_hpe,
            "has_situs_inversus":     has_situs_inv,
            "has_pulm_hypoplasia":    has_pulm_hypo,
            "has_cardiac_defect":     has_cardiac,
            "has_potter_sequence":    has_potter,
            "pgt_m_planned":          pgt_planned,
            "prior_affected_preg":    prior_affected_preg,
        })
    return cohort


