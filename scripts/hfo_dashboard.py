def overview() -> dict:
    """KPI overview for the HFO dashboard."""
    patients = _rows(
        "SELECT p.patient_id, p.confidence, d.epilepsy_type "
        "FROM analyses p "
        "LEFT JOIN patient_demographics d ON p.patient_id = d.patient_id "
        "ORDER BY p.patient_id"
    )

    # Deduplicate by patient_id (keep max confidence per patient)
    by_patient: dict[str, dict] = {}
    for r in patients:
        pid = r["patient_id"]
        if pid not in by_patient or r["confidence"] > by_patient[pid]["confidence"]:
            by_patient[pid] = r

    patient_list = list(by_patient.values())
    n_patients   = len(patient_list)

    total_ripple_events = 0
    total_fr_events     = 0
    soz_patients        = 0
    high_fr_patients    = 0

    per_patient_kpis = []
    for p in patient_list:
        seed = _patient_seed(p["patient_id"])
        conf = p["confidence"] or 0.5
        # Average across all 19 electrodes
        electrode_data = [_electrode_hfo_rate(e, seed, conf) for e in ELECTRODES_10_20]
        avg_ripple = round(sum(e["ripple_rate"] for e in electrode_data) / len(electrode_data), 2)
        avg_fr     = round(sum(e["fr_rate"] for e in electrode_data) / len(electrode_data), 2)
        n_soz      = sum(1 for e in electrode_data if e["soz_likely"])
        top_elec   = max(electrode_data, key=lambda x: x["total_rate"])["electrode"]

        # Scale to total events over a 30-minute recording session
        session_min = 30
        ripple_events = int(avg_ripple * session_min * 19)
        fr_events     = int(avg_fr * session_min * 19)

        total_ripple_events += ripple_events
        total_fr_events     += fr_events
        if n_soz >= 2:
            soz_patients += 1
        if avg_fr > 1.5:
            high_fr_patients += 1

        per_patient_kpis.append({
            "patient_id":    p["patient_id"],
            "epilepsy_type": p["epilepsy_type"] or "Unclassified",
            "confidence":    round(conf, 3),
            "avg_ripple_rate":  avg_ripple,
            "avg_fr_rate":      avg_fr,
            "soz_channels":     n_soz,
            "top_electrode":    top_elec,
            "ripple_events_30m": ripple_events,
            "fr_events_30m":    fr_events,
        })

    # Aggregate band distribution
    avg_ripple_all = round(sum(p["avg_ripple_rate"] for p in per_patient_kpis) / max(n_patients, 1), 2)
    avg_fr_all     = round(sum(p["avg_fr_rate"] for p in per_patient_kpis) / max(n_patients, 1), 2)

    # SOZ channels by region across cohort
    region_soz_counts: dict[str, int] = defaultdict(int)
    for p in patient_list:
        seed = _patient_seed(p["patient_id"])
        conf = p["confidence"] or 0.5
        for e in ELECTRODES_10_20:
            ed = _electrode_hfo_rate(e, seed, conf)
            if ed["soz_likely"]:
                region_soz_counts[ed["region"]] += 1

    return {
        "n_patients":             n_patients,
        "n_analyses":             len(patients),
        "total_ripple_events":    total_ripple_events,
        "total_fr_events":        total_fr_events,
        "avg_ripple_rate_cohort": avg_ripple_all,
        "avg_fr_rate_cohort":     avg_fr_all,
        "soz_patients":           soz_patients,
        "soz_patients_pct":       round(soz_patients / max(n_patients, 1) * 100, 1),
        "high_fr_patients":       high_fr_patients,
        "high_fr_pct":            round(high_fr_patients / max(n_patients, 1) * 100, 1),
        "per_patient_kpis":       sorted(per_patient_kpis, key=lambda x: -x["avg_fr_rate"])[:20],
        "region_soz_counts":      dict(region_soz_counts),
        "detection_methods":      DETECTION_METHODS,
        "aed_hfo_response":       AED_HFO_RESPONSE,
    }


def breakdown() -> dict:
    """Per-electrode HFO breakdown with SOZ mapping for each patient."""
    patients = _rows(
        "SELECT DISTINCT p.patient_id, MAX(p.confidence) as confidence "
        "FROM analyses p GROUP BY p.patient_id"
    )

    electrode_cohort: dict[str, dict] = {e: {"ripple_rates": [], "fr_rates": []} for e in ELECTRODES_10_20}

    per_patient_profiles = []
    for p in patients[:20]:   # cap at 20 for payload size
        seed = _patient_seed(p["patient_id"])
        conf = p["confidence"] or 0.5
        electrode_data = [_electrode_hfo_rate(e, seed, conf) for e in ELECTRODES_10_20]

        # Accumulate cohort stats
        for ed in electrode_data:
            electrode_cohort[ed["electrode"]]["ripple_rates"].append(ed["ripple_rate"])
            electrode_cohort[ed["electrode"]]["fr_rates"].append(ed["fr_rate"])

        soz_channels = [ed["electrode"] for ed in electrode_data if ed["soz_likely"]]
        per_patient_profiles.append({
            "patient_id":   p["patient_id"],
            "confidence":   round(conf, 3),
            "electrode_map": electrode_data,
            "soz_channels": soz_channels,
            "n_soz":        len(soz_channels),
            "peak_electrode": max(electrode_data, key=lambda x: x["total_rate"])["electrode"],
            "peak_total_rate": max(ed["total_rate"] for ed in electrode_data),
        })

    # Cohort-average per electrode
    electrode_averages = []
    for e in ELECTRODES_10_20:
        rr = electrode_cohort[e]["ripple_rates"]
        fr = electrode_cohort[e]["fr_rates"]
        avg_r = round(sum(rr) / len(rr), 2) if rr else 0
        avg_f = round(sum(fr) / len(fr), 2) if fr else 0
        electrode_averages.append({
            "electrode":      e,
            "region":         ELECTRODE_REGIONS.get(e, "Unknown"),
            "avg_ripple":     avg_r,
            "avg_fr":         avg_f,
            "avg_total":      round(avg_r + avg_f, 2),
            "soz_pct":        round(sum(1 for r in rr if r > 10.0) / max(len(rr), 1) * 100, 1),
        })

    # HFO band distribution histogram (binned ripple rates across cohort)
    all_ripple_rates = []
    all_fr_rates     = []
    for p in patients:
        seed = _patient_seed(p["patient_id"])
        conf = p["confidence"] or 0.5
        for e in ELECTRODES_10_20:
            ed = _electrode_hfo_rate(e, seed, conf)
            all_ripple_rates.append(ed["ripple_rate"])
            all_fr_rates.append(ed["fr_rate"])

    def _hist(values, n_bins=10, mn=0, mx=30):
        bin_w = (mx - mn) / n_bins
        bins = [0] * n_bins
        labels = []
        for i in range(n_bins):
            labels.append(f"{mn + i*bin_w:.0f}–{mn + (i+1)*bin_w:.0f}")
        for v in values:
            idx = min(int((v - mn) / bin_w), n_bins - 1)
            if 0 <= idx < n_bins:
                bins[idx] += 1
        return [{"range": labels[i], "count": bins[i]} for i in range(n_bins)]

    # Pre-ictal vs interictal HFO rate comparison (deterministic simulation)
    preictal_vs_interictal = []
    for p in patients[:15]:
        seed = _patient_seed(p["patient_id"])
        conf = p["confidence"] or 0.5
        interictal_ripple = _hfo_rate(seed, conf * 0.6, "Ripples")
        preictal_ripple   = _hfo_rate(seed, min(conf * 1.3, 0.99), "Ripples")
        interictal_fr     = _hfo_rate(seed, conf * 0.6, "Fast Ripples")
        preictal_fr       = _hfo_rate(seed, min(conf * 1.3, 0.99), "Fast Ripples")
        preictal_vs_interictal.append({
            "patient_id":         p["patient_id"],
            "interictal_ripple":  interictal_ripple,
            "preictal_ripple":    preictal_ripple,
            "interictal_fr":      interictal_fr,
            "preictal_fr":        preictal_fr,
            "ripple_ratio":       round(preictal_ripple / max(interictal_ripple, 0.1), 2),
            "fr_ratio":           round(preictal_fr / max(interictal_fr, 0.1), 2),
        })

    return {
        "per_patient_profiles":    per_patient_profiles,
        "electrode_averages":      sorted(electrode_averages, key=lambda x: -x["avg_total"]),
        "ripple_histogram":        _hist(all_ripple_rates, n_bins=10, mn=0, mx=30),
        "fr_histogram":            _hist(all_fr_rates, n_bins=8, mn=0, mx=9),
        "preictal_vs_interictal":  preictal_vs_interictal,
    }


