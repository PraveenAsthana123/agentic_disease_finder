def _conn():
    c = sqlite3.connect(str(DB))
    c.row_factory = sqlite3.Row
    return c


def _rows(query, params=()):
    with _conn() as c:
        return [dict(r) for r in c.execute(query, params).fetchall()]


def _patient_seed(patient_id: str) -> int:
    """Deterministic integer seed from patient_id string (djb2 variant)."""
    h = 5381
    for ch in str(patient_id):
        h = ((h << 5) + h) + ord(ch)
    return abs(h) % (2 ** 31)


def _hfo_rate(seed: int, confidence: float, band: str) -> float:
    """Simulate HFO rate (events/min) for a given patient and frequency band.

    Derived deterministically from:
      - patient_id hash (patient-specific epileptogenicity proxy)
      - model prediction confidence (higher confidence → higher HFO rate in SOZ)
      - band: fast ripples are rarer than ripples (ratio ≈ 0.25–0.45)

    Published normal ranges (scalp EEG, Frauscher 2018):
      Ripples       0.1–3.2 events/min (physiological)
      Fast Ripples  0.0–0.8 events/min (mostly pathological when > 0.3)

    Published epileptic ranges (intracranial, Jacobs 2012):
      Ripples       2–25 events/min (SOZ)
      Fast Ripples  0.5–8 events/min (SOZ)
    """
    base = ((seed * 37 + 13) % 10000) / 10000.0
    # Seizure prediction: high confidence → more epileptogenic tissue
    factor = 1.0 + (confidence - 0.5) * 2.8 if confidence > 0.5 else 1.0
    if band == "Ripples":
        rate = 1.5 + base * 18.0 * factor
        return round(min(rate, 28.0), 2)
    else:  # Fast Ripples
        rate = 0.2 + base * 5.5 * factor * 0.35
        return round(min(rate, 9.0), 2)


def _electrode_hfo_rate(electrode: str, patient_seed: int, confidence: float) -> dict:
    """Per-electrode HFO rates — highest in the SOZ-proximal electrodes."""
    e_hash = sum(ord(c) for c in electrode)
    combined = (patient_seed + e_hash * 131) % (2 ** 31)
    ripple = _hfo_rate(combined, confidence, "Ripples")
    fr     = _hfo_rate(combined, confidence * 0.9, "Fast Ripples")
    return {
        "electrode": electrode,
        "region":    ELECTRODE_REGIONS.get(electrode, "Unknown"),
        "ripple_rate": ripple,
        "fr_rate":     fr,
        "total_rate":  round(ripple + fr, 2),
        "soz_likely":  ripple > 10.0 or fr > 2.0,  # threshold-based SOZ flag
    }


