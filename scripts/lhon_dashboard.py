# ── RNG ─────────────────────────────────────────────────────────────────────

def _rng() -> random.Random:
    """Seeded RNG for reproducible 40-patient LHON cohort (seed-583)."""
    return random.Random(SEED)


# ── cohort builder ──────────────────────────────────────────────────────────

def _build_cohort(rng: random.Random) -> list[dict]:
    """Generate a 40-patient LHON cohort (seed-583)."""
    MUTATION_POOL = [
        "m.11778G>A-MT-ND4-p.R340H",
        "m.3460G>A-MT-ND1-p.A52T",
        "m.14484T>C-MT-ND6-p.M64V",
    ]
    MUTATION_WEIGHTS = [0.70, 0.15, 0.15]

    # Recovery rates by mutation
    RECOVERY_RATE = {
        "m.11778G>A-MT-ND4-p.R340H": 0.04,
        "m.3460G>A-MT-ND1-p.A52T": 0.22,
        "m.14484T>C-MT-ND6-p.M64V": 0.50,
    }

    ONSET_PHASE = ["acute", "subacute", "established", "chronic-atrophy"]
    ONSET_WEIGHTS = [0.15, 0.35, 0.30, 0.20]

    patients = []
    for i in range(N_PATIENTS):
        mutation = rng.choices(MUTATION_POOL, weights=MUTATION_WEIGHTS, k=1)[0]
        male = rng.random() < 0.82  # 80-90% male

        # Age at onset: peak 15-35 years, mean ~25
        onset_age = round(rng.gauss(25, 8), 1)
        onset_age = max(10.0, min(60.0, onset_age))

        # Heteroplasmy: ~15% heteroplasmic
        heteroplasmic = rng.random() < 0.15
        heteroplasmy_pct = round(rng.uniform(40, 90), 1) if heteroplasmic else 100.0

        # VA at nadir (logMAR equivalents, converted to Snellen-like fraction)
        va_nadir = rng.choices(
            ["CF", "HM", "<6/60", "6/60", "6/36", "6/24", "6/18"],
            weights=[0.20, 0.15, 0.25, 0.20, 0.10, 0.06, 0.04],
            k=1
        )[0]

        # Spontaneous recovery (mutation-specific)
        recovered = rng.random() < RECOVERY_RATE[mutation]
        va_current = rng.choices(
            ["6/18", "6/24", "6/36", "6/60", "<6/60", "CF", "HM"],
            weights=[0.12, 0.08, 0.10, 0.20, 0.25, 0.15, 0.10],
            k=1
        )[0] if not recovered else rng.choices(
            ["6/18", "6/12", "6/9", "6/24"],
            weights=[0.35, 0.25, 0.20, 0.20],
            k=1
        )[0]

        # Onset phase
        phase = rng.choices(ONSET_PHASE, weights=ONSET_WEIGHTS, k=1)[0]

        # Second-eye sequential vs simultaneous
        sequential = rng.random() < 0.97

        # Idebenone use
        on_idebenone = rng.random() < 0.55

        # Tobacco exposure (carrier risk factor)
        tobacco = rng.random() < 0.45  # elevated vs general pop

        # Dx delay (years)
        dx_delay = round(rng.gauss(1.2, 0.8), 1)
        dx_delay = max(0.1, min(6.0, dx_delay))

        # Peripapillary telangiectasia (acute/subacute phase)
        telangiectasia = (phase in ("acute", "subacute")) and (rng.random() < 0.65)

        patients.append({
            "id": f"LHON-P{i+1:02d}",
            "mutation": mutation,
            "sex": "M" if male else "F",
            "age_onset_years": onset_age,
            "heteroplasmic": heteroplasmic,
            "heteroplasmy_pct": heteroplasmy_pct,
            "va_nadir": va_nadir,
            "va_current": va_current,
            "recovered": recovered,
            "phase": phase,
            "sequential_bilateral": sequential,
            "on_idebenone": on_idebenone,
            "tobacco_history": tobacco,
            "dx_delay_yr": dx_delay,
            "peripapillary_telangiectasia": telangiectasia,
        })
    return patients


