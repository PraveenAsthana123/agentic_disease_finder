"""LHON — Leber Hereditary Optic Neuropathy.

Mitochondrial DNA Complex I Disease — maternal inheritance:
  Leber Hereditary Optic Neuropathy
  OMIM Disease #535000
  Primary mutations: MT-ND4 m.11778G>A (*), MT-ND1 m.3460G>A, MT-ND6 m.14484T>C

LHON is caused by point mutations in mitochondrial DNA-encoded subunits of respiratory
Complex I (NADH-ubiquinone oxidoreductase). Three 'primary' LHON mutations account for
~95% of cases worldwide:
  m.11778G>A (MT-ND4, p.R340H) — ~70% worldwide; worst prognosis; <4% spontaneous recovery
  m.3460G>A  (MT-ND1, p.A52T)  — ~15%; intermediate prognosis; ~22% spontaneous recovery
  m.14484T>C (MT-ND6, p.M64V)  — ~15%; best prognosis; ~50% spontaneous partial recovery

PATHOPHYSIOLOGY (Complex I defect → RGC degeneration):
All three mutations impair Complex I (NADH:ubiquinone oxidoreductase), the 45-subunit
entry point of the mitochondrial electron transport chain. mtDNA-encoded subunits (ND1,
ND2, ND3, ND4, ND4L, ND5, ND6) form the membrane arm. LHON mutations reduce Complex I
catalytic activity by 25-80%, increase superoxide generation, and impair ATP synthesis.
Retinal ganglion cells (RGCs) and their small-calibre unmyelinated axons at the optic
disc have the highest mitochondrial density in the nervous system — they are exquisitely
sensitive to bioenergetic failure. The pericentral macular RGC bundle (P-cells serving
central vision) is preferentially affected, explaining the centrocaecal scotoma.

CLINICAL PRESENTATION (examination high-yield):
  1. Subacute painless central visual loss — peak over days to 6 weeks; bilateral but
     typically SEQUENTIAL (second eye follows 6–8 weeks later in 97% of patients);
     simultaneous bilateral onset in ~3%; first eye acuity at nadir typically <6/60
  2. Sex bias — 80-90% of AFFECTED individuals are male despite maternal inheritance;
     underlying modifier: X-linked modifier locus Xq21 (DDP1/TIMM8A region) and
     possibly oestrogen-mediated mitochondrial protection in female carriers
  3. Centrocaecal scotoma — dense central + paracentral scotoma connecting to blind spot;
     isopter contraction on Goldmann perimetry; pattern-reversal VEP: delayed P100 → absent
  4. Red-green dyschromatopsia — Ishihara/HRR testing; CONTRAST with OPA1/ADOA
     tritanopia (blue-yellow); early and out-of-proportion to acuity
  5. Peripapillary telangiectatic microangiopathy — ACUTE phase; circumpapillary
     capillary dilation + pseudoedema of optic disc; ABSENT on FFA (no leak — KEY DDx
     from true disc oedema/papilloedema/NAION); fibres swell → sectoral OD blurring
  6. OCT RNFL — acute: swelling of RNFL (especially superior and inferior arcuates);
     chronic: thinning (temporal > superior > nasal; temporal thinning EARLIEST in ADOA)
  7. Optic atrophy — permanent; temporal pallor → global pallor; end-stage identical to
     other hereditary optic neuropathies; DDx from OPA1 requires genetics/family history

SPONTANEOUS RECOVERY:
  MT-ND6 m.14484T>C: ~50% recover to 6/18 or better (BEST prognosis)
  MT-ND1 m.3460G>A:  ~22% recover to 6/18 or better
  MT-ND4 m.11778G>A: <4% recover meaningfully (WORST prognosis)
Recovery occurs 6–18 months after onset; after 18 months recovery is rare.

TREATMENT — IDEBENONE (RAXONE/SANTHERA):
  900 mg/day in 3 divided doses; short-chain CoQ10 analogue; bypasses Complex I block
  by shuttling electrons from Complex I to cytochrome c via Complex III directly;
  Level B evidence (RHODOS trial, Klopstock 2011 Brain): significant visual acuity
  improvement in patients who were discordant (had visual loss but fellow eye not yet
  affected) — the discordant cohort is the most actionable; start EARLY (within 6 months
  of onset) for maximum benefit; approved EU (EMA) 2015 for LHON; NOT FDA-approved (US)
  Side effects: minimal; transient GI upset; no hepatotoxicity; no mito-toxicity

GENE THERAPY — LENADOGENE NOLPARVOVEC (LUMEVOQ, GenSight Biologics):
  Intravitreal AAV2 vector carrying wild-type MT-ND4 cDNA; allotopic expression
  (nucleus-encoded MT-ND4 imported via MTS); EU conditional approval 2021 for LHON
  m.11778G>A; RESCUE trial (Vignal-Clermont 2021 NEJM): bilateral effect after
  unilateral injection (treated + contralateral eye both improved); ongoing long-term
  studies; NOT available in Canada/USA outside compassionate use

CARRIER STATE:
  Female carriers: homoplasmic m.11778G>A → carrier; penetrance in females ~10-15%;
  males with mutation → penetrance 50-60%; incomplete penetrance means most MALE
  carriers in a LHON family DO NOT lose vision; risk factors for conversion: tobacco,
  alcohol, nutritional (B1, B12 deficiency), high BMI, physical deconditioning

KEY FACTS (EXAM / PRESCRIBING HIGHEST-YIELD):
  1. TOBACCO = ABSOLUTE CONTRAINDICATION — tobacco CN/acrolein/CO directly amplify
     Complex I dysfunction; LHON carriers: tobacco is the single most important
     modifiable risk factor for conversion; LHON-affected: tobacco dramatically worsens
     prognosis; both carriers and affected must never smoke; second-hand exposure risk
  2. ETHAMBUTOL = ABSOLUTE CONTRAINDICATION — copper-dependent inhibition of
     mitochondrial Complex IV in optic nerve; LHON RGCs already at bioenergetic threshold;
     ethambutol → fulminant irreversible visual loss; TB alternative: RIF+INH+PZA ±
     streptomycin; NEVER in LHON diagnosis or carrier state
  3. LINEZOLID = ABSOLUTE CONTRAINDICATION — inhibits mitochondrial 23S rRNA → blocks
     OXPHOS subunit synthesis; reversible if caught early but permanent if prolonged;
     alternative: daptomycin, tedizolid, co-trimoxazole, rifampicin (MRSA)
  4. ALCOHOL = AVOID — acetaldehyde inhibits Complex I + depletes mitochondrial GSH;
     episodic heavy alcohol → seizure-like visual blurring in carriers; alcohol cessation
     MANDATORY in affected individuals; abstinence advised in male carriers
  5. AMIODARONE = AVOID — drug-induced optic neuropathy in general population;
     synergistic toxicity with LHON Complex I deficiency; if cardiology-imperative:
     ophthalmology q3-month monitoring
  6. IDEBENONE TIMING — must be started EARLY; within 6 months of onset for maximum
     rescue of spared RGCs; after 18 months, most RGC loss is irreversible; late
     treatment still worthwhile for neuroprotection in second eye / fellow eye
  7. DISCORDANT PATIENTS = HIGHEST IDEBENONE BENEFIT — RHODOS trial subgroup: patients
     who still had useful vision in one eye at start of treatment showed the most
     significant idebenone benefit vs placebo; discordant state = therapeutic window
  8. GENE THERAPY TARGET — m.11778G>A patients are eligible for lenadogene nolparvovec
     (EU conditional approval); allotopic expression bypasses the mitochondrial genetic
     bottleneck; discuss referral to specialist LHON centre if within 1 year of onset
  9. MATERNAL INHERITANCE — all children of an affected MOTHER are mtDNA carriers (100%
     maternal transmission); fathers do NOT transmit LHON to children (paternal mtDNA
     eliminated post-fertilisation); KEY DDx from OPA1 ADOA (AD, 50% risk regardless
     of parent sex); genetic counselling for maternal relatives essential
 10. INCOMPLETE PENETRANCE — 50-60% of males with primary LHON mutation develop disease
     (lifetime); 10-15% of females; risk stratification: tobacco use, alcohol, BMI,
     B vitamin status, strenuous anaerobic exercise (triggers)
 11. MT-ND6 m.14484T>C PROGNOSIS — the most important prognostic distinguisher: 50%
     spontaneous recovery to 6/18 or better; inform patients of mutation-specific
     prognosis at diagnosis; m.11778G>A: counsel for permanent visual impairment
 12. VISUAL AIDS & REHABILITATION — low-vision assessment EARLY; magnification aids,
     tinted lenses (blue-light filtering may reduce glare), CCTV/electronic magnifiers,
     smartphone accessibility; LHON-specific support: Blind Veterans UK, LHON Society
 13. DRIVING — DVLA/DMV: visual acuity <6/12 (20/40) → MANDATORY reporting/cessation;
     most LHON patients below driving standard; visual field testing at diagnosis
 14. HETEROPLASMY — most LHON mutations are HOMOPLASMIC (100% mutant mtDNA) in blood;
     ~15% have heteroplasmy (mixture of wild-type + mutant); heteroplasmic thresholds:
     >60% mutant → typically pathogenic; <60% → reduced penetrance; mtDNA
     heteroplasmy can differ between tissues (muscle vs blood vs urine)
 15. COENZYME Q10 SUPPLEMENTATION — Level C evidence; 300-600 mg ubiquinol-10 (reduced
     form preferred); no harm; may slow progression; combine with idebenone cautiously
     (theoretical competition for same acceptor site — generally co-prescribed in practice)

LHON MOLECULAR BIOLOGY:
MT-ND4 (459 aa; mitochondrial genome position 10,760-12,137): Subunit ND4 of
NADH-ubiquinone oxidoreductase (Complex I); the membrane arm antiporter module;
m.11778G>A converts Arg-340 to His (p.R340H) in a highly conserved transmembrane
helix; p.R340H disrupts a key proton-translocating arginine in the ND4 antiporter
module → impairs ubiquinone reduction at the membrane/matrix interface → electrons
are diverted to superoxide → reduces ΔΨm → ATP deficit in RGC axons.

MT-ND1 (318 aa; positions 3,307-4,262): m.3460G>A = p.A52T; affects the ND1
interface with the quinone-binding domain of Complex I; moderate activity reduction
(~25%) explains intermediate penetrance/better prognosis vs ND4.

MT-ND6 (174 aa; positions 14,149-14,673; MINORITY STRAND encoded): m.14484T>C =
p.M64V; mildest Complex I defect of the three primaries; structural modelling
shows p.M64V at ND6 transmembrane helix 2 — milder disruption of ND2/ND3/ND6
subcomplex → explains 50% spontaneous recovery in ND6-LHON.
"""
