def _build_cohort():
    rng = random.Random(_SEED)
    cohort = []
    for i in range(_N):
        mutation = rng.choice(_MUTATIONS)
        ethnicity = _ETHNICITIES[i % len(_ETHNICITIES)]
        retinal = rng.choice(_RETINAL_STATUSES)
        renal = rng.choice(_RENAL_STATUSES)
        hearing = rng.choice(_HEARING_STATUSES)
        cognitive = rng.choice(_COGNITIVE_STATUSES)
        cardiac = rng.choice(_CARDIAC_STATUSES)
        misdiag = rng.choice(_MISDIAGNOSES)

        has_polydactyly   = rng.random() < 0.70
        has_anosmia       = rng.random() < 0.65
        consanguinity     = rng.random() < 0.30
        has_dm            = rng.random() < 0.50

        if has_dm:
            diabetes_st = rng.choice(_DIABETES_STATUSES[3:])
            hba1c = round(rng.uniform(7.0, 11.5), 1)
        else:
            diabetes_st = rng.choice(_DIABETES_STATUSES[:3])
            hba1c = round(rng.uniform(5.0, 6.8), 1)

        # C-peptide: PRESERVED (insulin resistance; not apoptosis)
        c_peptide = round(rng.uniform(0.80, 2.20), 2)

        bmi = round(rng.uniform(28.0, 54.0), 1)
        age_at_dx = rng.randint(6, 28)

        # Legal blindness flag
        legal_blind = "Legal blindness" in retinal
        has_renal_cyst = "cyst" in renal.lower() or "dysplasia" in renal.lower() or "clubbing" in renal.lower() or "horseshoe" in renal.lower()
        has_ckd = "CKD" in renal
        has_learning_dis = "learning disability" in cognitive.lower() or "borderline" in cognitive.lower()
        has_congenital_hd = "ASD" in cardiac or "VSD" in cardiac or "Bicuspid" in cardiac

        cohort.append({
            "id":             f"BBS-{i+1:03d}",
            "mutation":       mutation,
            "ethnicity":      ethnicity,
            "retinal_status": retinal,
            "renal_status":   renal,
            "hearing_status": hearing,
            "cognitive_status": cognitive,
            "cardiac_status": cardiac,
            "diabetes_status": diabetes_st,
            "prior_misdiagnosis": misdiag,
            "has_polydactyly": has_polydactyly,
            "has_anosmia":    has_anosmia,
            "consanguinity":  consanguinity,
            "has_dm":         has_dm,
            "hba1c":          hba1c,
            "c_peptide_nmol_L": c_peptide,
            "bmi":            bmi,
            "age_at_dx":      age_at_dx,
            "legal_blind":    legal_blind,
            "has_renal_cyst": has_renal_cyst,
            "has_ckd":        has_ckd,
            "has_learning_dis": has_learning_dis,
            "has_congenital_hd": has_congenital_hd,
        })
    return cohort


