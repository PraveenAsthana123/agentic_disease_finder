"""
Bardet-Biedl Syndrome (BBS1 — BBSome ciliopathy)
================================================================================
Gene       : BBS1 (Bardet-Biedl Syndrome 1 Protein)
Chromosome : 11q13.2
OMIM Gene  : *209901
OMIM Dis.  : #209900 (Bardet-Biedl Syndrome 1)
Inheritance: Autosomal Recessive — biallelic LOF; tri-allelic inheritance (rare);
             consanguinity common; ~1/125,000–160,000 prevalence (Newfoundland/Kuwait
             higher); BBS1 accounts for ~25% of all BBS globally

Mechanism
---------
BBS1 encodes a 593-amino-acid core BBSome subunit (BBS1/BBS2/BBS4/BBS5/BBS7/BBS8/BBS9
/BBIP10). The BBSome is a multi-protein complex that coats ciliary vesicles and
regulates intraflagellar transport (IFT) of cargo — signalling receptors, ion channels,
and structural proteins — along the ciliary axoneme.

BBS1 role in BBSome:
  • BBS1 is the cargo-recognition subunit; its beta-propeller/coiled-coil domain recruits
    G-protein-coupled receptors (GPCRs), leptin receptor (LepR), somatostatin receptor
    (SSTR3), and melanin-concentrating hormone receptor (MCHR1) into the cilium
  • Without BBS1, these receptors fail to localise to cilia → impaired signal sensing
  • BBSome also regulates IFT-B complex (anterograde, kinesin-II) and IFT-A (retrograde)
    for structural protein trafficking to the cilium tip

BBS1 biallelic LOF → BBSome dysfunction → ciliary signalling failure:
  • Photoreceptors: rod-cone degeneration (rods FIRST — night blindness; then cones);
    NOT cone-rod as in Alström (where cones degenerate first)
  • Hypothalamus: leptin receptor mis-trafficking → satiety failure → hyperphagia → obesity
  • Renal tubular cells: structural cilia defect → renal cysts / dysplasia / anomalies
  • CNS: brain cilia (neuronal cilia) → cognitive impairment / learning disability
  • Digits: limb bud cilia (SHH signalling) → post-axial polydactyly (extra digits)
  • Gonadal: ciliary signalling in germ cells → hypogonadism; cryptorchidism; infertility
  • Olfactory: olfactory cilia dysfunction → anosmia/hyposmia (frequent)
  • Cardiac: mild congenital heart disease (5–10%); NOT the severe infantile DCM of Alström

BBS Cardinal Features (primary — all 6 required for classic diagnosis):
  1. Rod-cone retinal dystrophy (rod-first; night blindness → progressive blindness)
  2. Post-axial polydactyly (pre- or post-axial; extra digits hands/feet; ~70%)
  3. Obesity (truncal hyperphagia; leptin resistance; BMI 30–56)
  4. Learning disability / cognitive impairment (mild–moderate; not severe)
  5. Renal anomalies (cysts, calyceal clubbing, horseshoe kidney; not nephropathy as Alström)
  6. Hypogonadism (males: cryptorchidism, small genitalia; females: irregular menses, hypogenitalism)

BBS Secondary Features (> 3 for diagnosis without all 6 primary):
  • Anosmia / hyposmia (olfactory cilia)
  • Ataxia / poor coordination
  • Speech delay / language impairment
  • Left–right asymmetry defects (situs inversus — rare)
  • Diabetes mellitus (insulin resistance, T2D-like; ~50%)
  • Congenital heart disease (ASD, VSD — 5–10%)
  • Short stature (GH axis)
  • Hepatic fibrosis (cholestasis; rarer than Alström)
  • Dental crowding; brachydactyly

Diabetes Pattern in BBS:
  • T2D-like insulin resistance (~50% of BBS patients by 4th decade)
  • C-peptide PRESERVED (insulin resistance; NOT beta-cell apoptosis)
  • Mechanism: leptin receptor ciliary mis-trafficking → hypothalamic satiety failure →
    hyperphagia → obesity → peripheral insulin resistance
  • Management: metformin first-line; GLP-1RA (obesity + insulin resistance);
    SGLT2i; insulin only late/exhaustion
  • NOT autoimmune (antibodies always negative)
  • DM less universal than Alström (50% vs ~80%); onset later (3rd–4th decade)

Key Clinical Differences: BBS vs Alström
------------------------------------------
BBS (BBS1):         Polydactyly YES · Rod-FIRST (night blindness 1st) · Cognitive YES
                    Renal CYSTS/anomalies · NO severe DCM · Learning disability YES
                    Anosmia YES · Tri-allelic genetics possible
Alström (ALMS1):    Polydactyly NO · Cone-FIRST (photophobia/nystagmus) · Cognitive NORMAL
                    Renal tubular nephropathy (structural OK early) · Infantile DCM YES
                    Anosmia rare · Strictly biallelic

Key Mutations (BBS1 biallelic LOF)
-------------------------------------
* M390R (c.1169T>G): founder missense; exon 12; ~70% of BBS1 alleles in European cohorts;
  impairs BBS1 protein–BBS7 interaction → BBSome assembly failure
* Y222C (c.665A>G): exon 8 missense; reduced BBS1 stability
* R228* (c.682C>T): exon 8 truncating; complete LOF; common compound heterozygous partner
* L518* (c.1553T>A): exon 14 truncating; Northern European
* c.1303C>T (p.Gln435*): exon 12 truncating; compound heterozygous with M390R (common)
* IVS12+1G>A: splice site; intron 12; European
* Del exon5-6 (large deletion): copy number variant; detected by MLPA
* p.Arg160Gln (c.479G>A): exon 5 missense; BBSome binding interface; Kuwaiti enriched

Diagnostics
-----------
• BBS gene panel (≥ 24 genes): BBS1, BBS2, ARL6 (BBS3), BBS4-10, MKKS (BBS6),
  TRIM32 (BBS11), MKS1 (BBS13), CEP290 (BBS14) — next-gen panel mandatory (phenocopy risk)
• ERG (electroretinogram): rod-cone pattern (rod amplitude extinguished before cones);
  distinguishes from Alström (cone-rod ERG pattern)
• Renal ultrasound: cysts, clubbed calyces, horseshoe kidney; annual surveillance
• Ophthalmology: OCT (retinal thinning); visual fields (ring scotoma early); fundus photo
• Skeletal: X-ray hands/feet (polydactyly — confirm post-axial; assess for surgical planning)
• Cognitive: neuropsychological assessment; IQ (mild-mod learning disability)
• Olfaction: University of Pennsylvania Smell Identification Test (UPSIT)
• Metabolic: fasting glucose; HbA1c; fasting insulin; C-peptide; lipid profile; TG
• Renal function: urine protein/creatinine ratio; eGFR; serum creatinine annually
• Hormonal: testosterone/FSH/LH (males); oestradiol (females); pelvic USS (PCOS pattern)
• Cardiac: echocardiogram at diagnosis (congenital HDs); repeat if symptomatic
• CNS: brain MRI (rare structural anomalies — hippocampal malformations)
• Tri-allelic genotype: if phenotype severe + 2 BBS1 variants + 1 second-gene variant
  → extend panel to exclude tri-allelic BBS (requires analysis of 3+ BBS genes)

Management (multi-system; no disease-modifying Rx as of 2026)
--------------------------------------------------------------
• Retinal: low-vision aids; ERG baseline + annual; avoid strong light exposure; genetics
  counselling for gene therapy trials (CRISPR-Cas9 BBSome trials ongoing)
• Obesity: intensive dietary intervention; GLP-1RA (liraglutide/semaglutide); metformin;
  bariatric surgery considered (BMI ≥ 40 in adults with comorbidities)
• Renal: annual USS + urine ACR + eGFR; nephrology referral if cysts or proteinuria;
  ACE-I/ARB for proteinuria; avoid nephrotoxic drugs
• Diabetes: metformin first-line; GLP-1RA; SGLT2i (renal + metabolic dual benefit);
  insulin if HbA1c > 9% uncontrolled
• Polydactyly: surgical correction in early childhood (functional + cosmetic)
• Cognitive: early educational support; speech therapy; occupational therapy
• Hypogonadism: testosterone replacement (males, after growth complete);
  oestrogen/progesterone (females, induction of puberty if pubertal failure)
• Anosmia: safety counselling (gas, fire, food spoilage)
• Cardiac: standard HF therapy (HF confirmed by echo); cardiology review
• Hepatic: annual LFTs; fibrates if hypertriglyceridaemia; hepatology if fibrosis
• Genetic counselling: 25% sibling recurrence (AR); tri-allelic counselling; carrier testing;
  preimplantation genetic diagnosis available

Registry / Organisations
-------------------------
BBS UK Patient Registry; Global BBS Registry (UK Biobank BBS cohort);
BBS Foundation (USA); EuroBBS (European research consortium)
"""

