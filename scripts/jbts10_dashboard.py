"""
OFD1 Joubert Syndrome Type 10 (JBTS10) — X-Linked / Centriolar Satellite / RP23 Allelic / OFD1 Syndrome
=========================================================================================================
Primary Gene : OFD1 (*300170) — Xp22.2; 1012 aa; Oral-Facial-Digital Syndrome Type 1 Protein.
               OFD1 is a CENTRIOLAR SATELLITE protein — localises to cytoplasmic foci (satellites)
               surrounding the centrosome / basal body. It is required for:
               (1) Controlled centriole elongation (removes excess centriolar material),
               (2) Transition zone (TZ) assembly initiation, and
               (3) Ciliogenesis (primary cilia formation in all tissues).
               OFD1 domains: LisH (aa 31-63; homodimerisation) + CC1 (aa 64-200; satellite targeting) +
               CC2 (aa 200-400) + CC3 (aa 400-600) + CC4 (aa 600-800) + CC5 (aa 800-1012).
               OFD1 loss → failure of ciliogenesis → Hedgehog pathway failure → Molar Tooth Sign (MTS),
               cerebellar vermis hypoplasia; retinal photoreceptor connecting cilium dysfunction → RP23.

⚠ X-LINKED INHERITANCE — JBTS10 IS UNIQUE AMONG JBTS TYPES:
   All other characterised JBTS types (JBTS3–JBTS9) are AUTOSOMAL RECESSIVE.
   JBTS10 is X-LINKED — OFD1 is on Xp22.2.
   Hemizygous males with loss-of-function OFD1 variants → JBTS10 (live birth, MTS, severe ciliopathy).
   Heterozygous females with the same variant → OFD1 SYNDROME (#311200): oral-facial-digital features
     (oral hamartomas, tongue nodules/lobulation, supernumerary/absent teeth, gingival hamartomas,
      hypertelorism, broad nasal bridge, digital anomalies, polydactyly, syndactyly) ± CNS anomalies.
   OFD1 syndrome is X-linked DOMINANT — females survive (OFD1 syndrome); males with severe null
     alleles usually die in utero (X-linked lethality). Males who survive to birth have JBTS10
     phenotype — typically via hypomorphic/mosaic variants or variants that escape lethality.

⚠ RP23 ALLELIC AXIS — OFD1 RETINAL ISOFORM:
   Specific OFD1 variants (particularly in exons 9-11 of the shorter retinal isoform) → Retinitis
   Pigmentosa 23 (RP23; OMIM #300424) without brain malformation. These variants disrupt the retinal
   OFD1 isoform but preserve sufficient ciliogenesis in non-retinal tissues. JBTS10 patients have high
   retinal disease burden (~55% rod-cone dystrophy) because ciliogenesis failure in photoreceptor
   connecting cilia = convergence of MTS + RP phenotypes.
   DIAGNOSTIC RULE: Any X-linked RP with family history of OFD-like features in carrier females →
   sequence OFD1 (exons 9-11 retinal isoform + full gene).

⚠ OFD1 POLYDACTYLY — UNIQUE X-LINKED JSOFD SUBTYPE:
   Post-axial polydactyly in ~25% of JBTS10 males. Oral features (oral hamartomas, tongue nodules)
   are RARE in JBTS10 males but may appear in carrier mothers (OFD1 syndrome). Skeletal survey +
   maternal oral/dental assessment critical in X-linked JBTS families.

Disease OMIM : #300804 — Joubert Syndrome 10 (JBTS10; X-linked)
               #311200 — Oral-Facial-Digital Syndrome Type 1 (OFD1; X-linked dominant, females)
               #300424 — Retinitis Pigmentosa 23 (RP23; X-linked; OFD1 isoform)
               #300209 — Simpson-Golabi-Behmel Syndrome Type 2 (SGBS2; rare OFD1 allele)
Chromosome   : Xp22.2
Inheritance  : X-linked (hemizygous males → JBTS10; heterozygous females → OFD1 syndrome)
Prevalence   : ~1–2% of all Joubert syndrome; ~1/1,500,000–3,000,000 worldwide (JBTS10 phenotype)

Protein Structure — OFD1 (1012 aa; centriolar satellite scaffold)
-----------------------------------------------------------------
Domain 1: LisH domain (aa 31-63)       — homodimerisation / centriolar satellite assembly
           LisH missense hotspot:
             Pro36Leu — LisH core; European; moderate JBTS10
Domain 2: Coiled-coil 1 / CC1 (aa 64-200)  — centriolar satellite targeting; PCM1 interaction
           CC1 truncations: loss of satellite localisation → complete ciliogenesis failure
Domain 3: Coiled-coil 2 / CC2 (aa 200-400) — protein-protein interaction; DZIP1 / CEP164 binding
           CC2 truncations: Arg303* — major pan-ethnic truncating null
           CC2 splice: c.1405+1G>A — intron 12 splice donor null
Domain 4: Coiled-coil 3 / CC3 (aa 400-600) — coiled-coil scaffold; retinal isoform exons 9-11 here
           Key missense: Ala446Thr — hypomorphic; RP23-associated / mild JBTS10
           Key missense: Leu438Pro — South Asian; moderate JBTS10
Domain 5: Coiled-coil 4 / CC4 (aa 600-800) — scaffold extension
           Key missense: Pro247Leu (cc.740C>T) — MENA; JBTS10 moderate
           Truncations in CC4: c.1675C>T → Arg559* — C-terminal truncating null (European)
Domain 6: Coiled-coil 5 / CC5 (aa 800-1012) — C-terminal; additional interaction surface
           Arg554* (c.1660C>T) — CC4-CC5 junction null; European; JBTS10 severe / lethal in utero

Key pathogenic variants (OFD1 / JBTS10):
1. p.Arg559* (c.1675C>T):   CC4 truncating null; European; JBTS10 (hemizygous males)
2. p.Glu303* (c.907G>T):    CC2 truncating null; pan-ethnic; JBTS10 / OFD1 (females)
3. p.Arg554* (c.1660C>T):   CC4-CC5 junction null; European; JBTS10 severe
4. c.1405+1G>A (splice):    Intron 12 splice donor null; European; JBTS10
5. p.Pro247Leu (c.740C>T):  CC3 missense; MENA; JBTS10 moderate
6. p.Ala446Thr (c.1336G>A): CC3 hypomorphic; RP23-associated / mild JBTS10
7. p.Leu438Pro (c.1313T>C): CC3 missense; South Asian; JBTS10 moderate

JBTS10 Phenotype Tier / X-linked Severity Rule:
  Hemizygous null male (survive)               → JBTS10 (MTS + ataxia + high retinal + polydactyly)
  Hemizygous null male (severe allele)          → Lethal in utero (X-dominant lethality mechanism)
  Heterozygous female                           → OFD1 syndrome (oral-facial-digital ± CNS mild)
  Hemizygous hypomorphic male (e.g. Ala446Thr) → JBTS10 mild or RP23 (isolated retinal disease)
  NOTE: Unlike JBTS5-9, NO MKS tier (MKS = autosomal recessive; OFD1 is X-linked)

Original discovery: Coene KL et al., Am J Hum Genet 2009 — OFD1 identified as JBTS10 gene;
  Romio L et al., J Am Soc Nephrol 2004 — OFD1 localisation to basal body/centriolar satellites.
"""

