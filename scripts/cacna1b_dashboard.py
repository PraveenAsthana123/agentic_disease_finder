def get_overview():
    n = len(_PATIENTS)
    n_sz_free   = sum(1 for p in _PATIENTS if p["seizure_free"])
    n_dre       = sum(1 for p in _PATIENTS if not p["seizure_free"] and
                      p["etiology"] in ("GOF-Severe-DEE-IS", "GOF-Moderate-DEE-Hyperkinetic"))
    n_acth      = sum(1 for p in _PATIENTS if p["acth_received"])
    n_spasms    = sum(1 for p in _PATIENTS if p["spasms_present"])
    n_gtcs      = sum(1 for p in _PATIENTS if p["gtcs_present"])
    n_hyper     = sum(1 for p in _PATIENTS if p["hyperkinetic"])
    n_kd        = sum(1 for p in _PATIENTS if p["kd_on"])
    n_vgb       = sum(1 for p in _PATIENTS if p["vgb_received"])
    n_lev       = sum(1 for p in _PATIENTS if p["lev_received"])
    avg_age     = round(sum(p["current_age"] for p in _PATIENTS) / n, 1)

    return {
        "kpis": {
            "n_patients":          n,
            "seizure_free_pct":    round(n_sz_free / n * 100),
            "drug_resistant_pct":  round(n_dre / n * 100),
            "acth_received_n":     n_acth,
            "spasms_n":            n_spasms,
            "gtcs_n":              n_gtcs,
            "hyperkinetic_n":      n_hyper,
            "kd_on_n":             n_kd,
            "vgb_received_n":      n_vgb,
            "lev_received_n":      n_lev,
            "avg_age_years":       avg_age,
        },
        "etiology_distribution": [
            {"category": e["category"], "pct": e["pct"]} for e in ETIOLOGY_CATALOG
        ],
        "seizure_summary": [
            {"type": s["type"], "pct": s["pct"]} for s in SEIZURE_TYPES
        ],
        "treatments_summary": [
            {"drug": t["drug"].split(" — ")[0], "level": t["level"]} for t in TREATMENTS
        ],
        "monitoring_summary": MONITORING[:6],
        "lifecycle":           LIFECYCLE,
        "thresholds":          THRESHOLDS[:6],
        "contraindications_summary": [
            {"drug": c["drug"], "risk": c["risk"][:80]} for c in CONTRAINDICATIONS
        ],
    }


