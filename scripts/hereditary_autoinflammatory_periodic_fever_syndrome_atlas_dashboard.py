def _make_cohort(gene: str, n: int = 40) -> list:
    rng   = random.Random(SEEDS[gene])
    pr    = PROFILES[gene]
    pts   = []
    for i in range(n):
        age_onset = rng.gauss(8, 5) if gene in ("MEFV","NLRP3","MVK","NLRC4") else rng.gauss(12, 8)
        age_onset = max(0.1, round(age_onset, 1))

        serositis       = rng.random() < pr["serositis_pct"] / 100
        colchicine_resp = rng.random() < pr["colchicine_response_pct"] / 100
        aa_amyloid      = rng.random() < pr["aa_amyloid_untreated_pct"] / 100

        # Gene-specific features
        extra = {}
        if gene == "MEFV":
            extra["arthritis"]           = rng.random() < pr["arthritis_pct"] / 100
            extra["erysipelas_erythema"] = rng.random() < pr["erysipelas_erythema_pct"] / 100
            extra["onset_lt20yr"]        = age_onset < 20
            extra["attack_free_interval"]= True
            extra["attack_duration_hr"]  = round(rng.gauss(36, 12), 1)
        elif gene == "NLRP3":
            extra["snhl"]                = rng.random() < pr["snhl_pct"] / 100
            extra["urticaria"]           = True
            extra["canakinumab_resp"]    = rng.random() < pr["canakinumab_response_pct"] / 100
            extra["neonatal_onset"]      = age_onset < 0.5
            extra["attack_free_interval"]= False
        elif gene == "MVK":
            extra["lymphadenopathy"]         = rng.random() < pr["lymphadenopathy_pct"] / 100
            extra["igd_elevated"]            = rng.random() < pr["igd_elevated_pct"] / 100
            extra["urinary_mevalonic_acid"]  = rng.random() < pr["urinary_mevalonic_acid_pct"] / 100
            extra["attack_free_interval"]    = True
            extra["attack_duration_days"]    = round(rng.gauss(5, 1.5), 1)
        elif gene == "TNFRSF1A":
            extra["migratory_myalgia"]   = rng.random() < pr["migratory_myalgia_pct"] / 100
            extra["periorbital_edema"]   = rng.random() < pr["periorbital_edema_pct"] / 100
            extra["reduced_stnfr1"]      = rng.random() < pr["reduced_stnfr1_pct"] / 100
            extra["attack_duration_days"]= round(rng.gauss(14, 5), 1)
            extra["attack_free_interval"]= True
        elif gene == "NLRC4":
            extra["extreme_ferritin"]    = rng.random() < pr["extreme_ferritin_pct"] / 100
            extra["il18_elevated"]       = rng.random() < pr["il18_elevated_pct"] / 100
            extra["enterocolitis"]       = rng.random() < pr["enterocolitis_pct"] / 100
            extra["mas_crisis"]          = rng.random() < pr["mas_crisis_pct"] / 100
            extra["il18bp_response"]     = rng.random() < pr["il18bp_treatment_pct"] / 100
        elif gene == "PSTPIP1":
            extra["sterile_arthritis"]   = rng.random() < pr["arthritis_sterile_pct"] / 100
            extra["pyoderma_gangrenosum"]= rng.random() < pr["pg_pct"] / 100
            extra["severe_acne"]         = rng.random() < pr["acne_severe_pct"] / 100
            extra["anakinra_response"]   = rng.random() < pr["anakinra_response_pct"] / 100
        elif gene == "NOD2":
            extra["granulomatous_arthritis"] = rng.random() < pr["granulomatous_arthritis_pct"] / 100
            extra["uveitis"]             = rng.random() < pr["uveitis_pct"] / 100
            extra["skin_rash"]           = rng.random() < pr["skin_rash_pct"] / 100
            extra["camptodactyly"]       = rng.random() < pr["camptodactyly_pct"] / 100
            extra["vision_loss"]         = rng.random() < pr["vision_loss_risk_pct"] / 100
            extra["tnfi_response"]       = rng.random() < pr["tnfi_response_pct"] / 100
        elif gene == "IL36RN":
            extra["sterile_pustules"]    = True
            extra["hypocalcemia"]        = rng.random() < pr["hypocalcemia_pct"] / 100
            extra["spesolimab_response"] = rng.random() < pr["spesolimab_response_pct"] / 100
            extra["kogoj_microabscess"]  = rng.random() < 0.90

