for eth, frac in ethnicities:
    eth_pool.extend([eth] * round(frac * N))
while len(eth_pool) < N:
    eth_pool.append('European')
eth_pool = eth_pool[:N]
rng.shuffle(eth_pool)

# Allele classes:
#   null/null (~25% — truncating: Trp192*/Glu1236*/c.2261-2A>G/Leu130Pro severe)
#   null/missense (~45% — one null + Arg449Trp/Ala306Thr)
