"""
Nephronophthisis Type 11 (TMEM67/NPHP11) — MKS3 / Joubert Syndrome 6 / COACH Syndrome
========================================================================================
Primary Gene : TMEM67 (*609884) — 8q22.1; 995 aa; Meckelin; type I transmembrane
               glycoprotein; ~114 kDa; also known as MKS3 (Meckel Syndrome 3 protein)
Disease OMIM : #613550 (Nephronophthisis 11 — NPHP11; pure renal-hepatic ciliopathy)
               Also: #607361 (Meckel Syndrome 3 / MKS3 — biallelic null; lethal;
               occipital encephalocele + polydactyly + cystic kidneys)
               Also: #610688 (Joubert Syndrome 6 / JBTS6 — truncating/strong missense;
               molar tooth sign + cerebellar vermis hypoplasia + variable extra-cranial)
               COACH Syndrome: Cerebellar vermis hypoplasia + Oligophrenia + Ataxia +
               Coloboma + Hepatic fibrosis — TMEM67 is the most common COACH gene (>80%
               of all COACH cases worldwide)
Chromosome   : 8q22.1
Inheritance  : Autosomal Recessive (biallelic LOF)
Prevalence   : ~1/200,000–500,000; NPHP11 (pure renal) rarer; JBTS6 more prevalent
               within Joubert spectrum; COACH is exceedingly rare (~100 families total)

Protein Structure — Meckelin (TMEM67, 995 aa)
----------------------------------------------
  • N-terminal signal peptide (aa 1–27): ER targeting and membrane insertion
  • Extracellular domain (aa 28–750): large N-terminal ectodomain; multiple Frizzled-type
    cysteine-rich sub-domains (CRD-like) at aa 75–250; WD40-like β-propeller repeats
    (approximate, aa 300–600); receptor/ligand interaction surface
  • Single-pass transmembrane domain (aa 751–773): anchors Meckelin in the ciliary
    transition-zone membrane (MKS zone / B9 zone boundary)
  • Short cytoplasmic C-terminal tail (aa 774–995): interaction surface for CC2D2A,
    RPGRIP1L (NPHP8), CEP290 (NPHP6), NPHP1, and intracellular signalling scaffold

Molecular Mechanism
-------------------
TMEM67/Meckelin is a core component of the MKS/JBTS/NPHP transition-zone (TZ) complex:
  1. Localises to the membrane-associated MKS zone of the ciliary TZ (between basal body
     and axoneme proper); forms a diffusion barrier preventing lateral movement of
     membrane proteins in and out of the ciliary compartment
  2. Interacts directly with:
       – CC2D2A (JBTS9 / MKS6): scaffolds the TZ membrane-associated plate
       – RPGRIP1L (NPHP8 / JBTS7 / MKS5): bridges NPHP1-4 TZ-module to MKS-zone
       – CEP290 (NPHP6 / JBTS5 / MKS4): Y-link / TZ-matrix anchor
       – NPHP1: innermost Y-link TZ scaffold; direct physical interaction
  3. Loss of TMEM67 → MKS-zone TZ collapse → ciliary gate dysfunction → failure to
     restrict ciliary signalling components (Hedgehog, Wnt) → tubular epithelial cell
     de-differentiation → interstitial nephritis (TIN) → corticomedullary cysts → ESRD
  4. TMEM67 expressed in biliary epithelium → LOF → ductal plate malformation → biliary
     hamartomas → congenital hepatic fibrosis (CHF) → portal hypertension (50–60%)
  5. TMEM67 expressed in developing cerebellum → LOF (truncating alleles) → cerebellar
     vermis hypoplasia → molar tooth sign (Joubert; JBTS6); ataxia; oculomotor apraxia
  6. TMEM67 expressed in developing eye → LOF → retinochoroidal coloboma (~20–25%)
     affecting iris, retina, optic nerve; NOT retinal dystrophy (photoreceptors spared)
  7. TMEM67 NOT expressed in photoreceptor connecting cilium → NO retinal dystrophy
     in pure NPHP11 (critical negative feature distinguishing from NPHP5/6/10)
  8. TMEM67 NOT expressed in nodal cilia at sufficient levels → situs inversus rare (<5%)
  9. TMEM67 NOT expressed in pancreatic ducts → NO pancreatic ductal ectasia (unlike NPHP9)
  10. Allele-severity spectrum: biallelic null (homozygous frameshift/nonsense) → MKS3
      (lethal, encephalocele); truncating + strong missense → JBTS6/COACH; mild missense
      → NPHP11 (pure renal-hepatic without CNS)

HALLMARK FEATURES (distinguishing NPHP11 from all other NPHP subtypes):
  • CONGENITAL HEPATIC FIBROSIS (CHF): 50–60% — most frequent extra-renal feature;
    ductal plate malformation; biliary hamartomas; portal hypertension; may necessitate
    liver transplant BEFORE renal transplant (~10–15%); distinct from NPHP9 CHF pattern
  • JOUBERT SYNDROME 6 (JBTS6): 30–40% — molar tooth sign on brain MRI; cerebellar
    vermis hypoplasia; oculomotor apraxia; ataxia; brain MRI mandatory at diagnosis
  • COACH SYNDROME (~20–25%): Cerebellar vermis hypoplasia + Oligophrenia + Ataxia +
    Coloboma + Hepatic fibrosis; TMEM67 is the causative gene in >80% of COACH cases;
    COACH = severe JBTS6 subset with all five canonical features co-occurring
  • RETINOCHOROIDAL COLOBOMA (~20–25%): COACH/JBTS6 alleles; coloboma of iris, retina,
    optic nerve; NOT retinal dystrophy; low-vision rehabilitation; no effective treatment
  • NO RETINAL DYSTROPHY (pure NPHP11) — TMEM67 absent from photoreceptors; ERG normal;
    critical negative distinguishing feature from NPHP5 (IQCB1), NPHP6 (CEP290), NPHP10 (SDCCAG8)
  • ESRD MEDIAN ~18–22yr — later than NPHP1 (13yr); kidneys small, echogenic; TIN;
    corticomedullary cysts; one of the later-onset NPHP subtypes
  • SITUS INVERSUS: Rare (<5%) — much less than NPHP2/INVS (35%) or NPHP3 (15%)
  • ALLELE SPECTRUM: biallelic null → MKS3 (lethal); truncating → JBTS6/COACH;
    mild missense → NPHP11 pure; explains same gene causing three distinct diseases

Key Differentials:
  NPHP2 (INVS / 9q31.1): Infantile ESRD 3yr; situs 35%; CHF 55%; no Joubert; no coloboma;
    no COACH; INVS inversin compartment protein (not MKS zone)
  NPHP3 (NPHP3 / 3q22.1): Adolescent ESRD 19yr; CHF 45%; situs 15%; no Joubert;
    no coloboma; no COACH; TZ module scaffold
  NPHP8 (RPGRIP1L / 16q12.2): JBTS7; molar tooth 40%; CHF 15–20%; no coloboma;
    no COACH; RPGRIP1L directly binds TMEM67 (NPHP8-NPHP11 interactome partners)
  NPHP9 (NEK8 / 17q11.2): CHF 50%; pancreatic 24% (unique); situs 28%; no Joubert;
    no coloboma; no COACH; mTORC1-BICC1 kinase pathway
  Alagille Syndrome (JAG1/NOTCH2): Bile duct paucity (not CHF/cirrhosis); cholestatic
    (NOT cirrhotic); butterfly vertebrae; pulmonary stenosis; normal kidneys — NO TIN;
    JAG1/NOTCH2 panel tested first if liver dominates → TMEM67 missed

Treatment:
  • Liver transplant: for severe CHF/portal HTN before ESRD in ~10–15%; does NOT prevent
    renal disease progression; renal transplant still required
  • Renal transplant: CURATIVE for renal component; cell-autonomous TZ defect;
    NO recurrence; excellent outcomes; living donor preferred
  • Coloboma: no corrective treatment; low-vision rehabilitation; ophthalmology annually
  • Annual APRI + liver USS for CHF surveillance
  • Brain MRI at diagnosis: mandatory to stratify JBTS6 vs pure NPHP11
  • No disease-modifying therapy 2026; TMEM67 gene therapy and TZ-stabilising strategies
    are pre-clinical; no approved trial as of 2026
"""

