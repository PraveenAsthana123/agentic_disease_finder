def _make_patients():
    r = random.Random(SEED + 1)
    cats = [
        ("GOF-De-Novo-Focal-GGE", 15),
        ("LOF-De-Novo-DEE", 11),
        ("Haploinsufficiency-Inherited-GGE", 7),
        ("GOF-LOF-Uncertain-Compound", 4),
        ("Phenocopy-Panel-Negative", 3),
    ]
    patients = []
    pid = 1
    for cat, n in cats:
        for _ in range(n):
            is_gof = "GOF" in cat and "LOF" not in cat
            is_lof_dee = "LOF-De-Novo-DEE" in cat
            is_haplo = "Haploinsufficiency" in cat
            on_lev = r.random() < (0.88 if not is_lof_dee else 0.75)
            on_vpa = r.random() < (0.65 if is_haplo else 0.50)
            on_ltg = r.random() < (0.42 if is_gof or is_haplo else 0.18)
            on_clb = r.random() < (0.38 if is_lof_dee else 0.28)
            on_cbz = r.random() < (0.28 if is_gof else 0.08)
            polg_done = r.random() < (0.80 if on_vpa else 0.45)
            photosensitive = r.random() < (0.38 if is_gof else 0.25)
            dre = r.random() < (0.55 if is_lof_dee else 0.25)
            lev_resp = on_lev and (r.random() < (0.62 if is_gof else 0.48))
            if is_lof_dee:
                onset = round(r.uniform(0.3, 2.5), 1)
            elif is_haplo:
                onset = r.randint(8, 22)
            elif is_gof:
                onset = r.randint(3, 18)
            else:
                onset = r.randint(1, 25)
            seizure_free = r.random() < (0.12 if is_lof_dee else 0.30)
            is_tab = r.random() < 0.22
            patients.append({
                "id": f"KC2-{pid:03d}",
                "category": cat,
                "onset_years": onset,
                "on_lev": on_lev,
                "lev_responder": lev_resp,
                "on_vpa": on_vpa,
                "on_ltg": on_ltg,
                "on_clb": on_clb,
                "on_cbz": on_cbz,
                "polg_done": polg_done,
                "photosensitive": photosensitive,
                "drug_resistant": dre,
                "seizure_free": seizure_free,
                "is_tab_patient": is_tab,
            })
            pid += 1
    r.shuffle(patients)
    return patients


