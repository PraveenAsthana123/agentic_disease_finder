def _generate_patients(n: int = 40, seed: int = 7) -> list:
    rng = random.Random(seed)
    patients = []
    etiology_pool = []
    for name, pct in _ETIOLOGY_DIST:
        etiology_pool.extend([name] * pct)

    for i in range(n):
        etiology = rng.choice(etiology_pool)
        age = rng.randint(2, 18)
        onset_months = rng.randint(2, 8) if "late" not in etiology else rng.randint(8, 18)
        sex = rng.choice(["Male", "Female", "Female"])
        variant = rng.choice(_SPTAN1_VARIANTS)

        is_dn = "DN-West" in etiology
        is_lof = "LOF-DEE" in etiology
        is_partial = "partial" in etiology
        is_late = "late" in etiology
        is_copy = "phenocopy" in etiology

        seizure_types = ["Infantile Spasms"]
        if is_dn or is_partial or is_late:
            seizure_types.append("Tonic Seizures")
        if not is_copy:
            seizure_types.append("Focal Seizures")
        if is_dn or is_lof:
            seizure_types.append("Atonic / Drop Attacks")
        if rng.random() < 0.35:
            seizure_types.append("Myoclonic Seizures")

        acth_response = rng.random() < (
            0.35 if is_dn else 0.50 if is_partial else 0.30 if is_lof else 0.45 if is_late else 0.60
        )
        on_kd = rng.random() < (0.55 if not is_copy else 0.20)
        on_clb = rng.random() < 0.72
        on_vpa = rng.random() < 0.68
        on_vgb = rng.random() < 0.45
        on_lev = rng.random() < 0.40
        polg_done = rng.random() < 0.92
        erg_done = on_vgb and rng.random() < 0.88
        vppp = on_vpa and sex == "Female" and rng.random() < 0.85
        mri_hypomyelin = rng.random() < (0.85 if not is_copy else 0.30)
        optic_atrophy = rng.random() < (0.42 if not is_copy else 0.10)
        lgs_transition = rng.random() < (0.70 if is_dn else 0.55 if is_lof else 0.40 if is_partial else 0.50 if is_late else 0.10)
        seizure_free = rng.random() < (0.04 if not is_copy else 0.50)
        drug_resistant = not seizure_free and rng.random() < (0.90 if not is_copy else 0.35)
        drop_attacks = "Atonic / Drop Attacks" in seizure_types and lgs_transition
        helmet = drop_attacks
        aed_count = rng.randint(3, 5) if drug_resistant else rng.randint(1, 3)
        cognitive = (
            "Profound ID (IQ<30)" if (is_dn or is_lof) and rng.random() < 0.70 else
            "Severe ID (IQ 30-49)" if not is_copy else
            "Moderate ID (IQ 50-69)" if is_partial else
            "Moderate ID"
        )

        patients.append({
            "id": f"SPTAN1-{i + 1:03d}",
            "age": age,
            "onset_months": onset_months,
            "sex": sex,
            "etiology": etiology,
            "variant": variant,
            "seizure_types": seizure_types,
            "acth_response": acth_response,
            "on_kd": on_kd,
            "on_clb": on_clb,
            "on_vpa": on_vpa,
            "on_vgb": on_vgb,
            "on_lev": on_lev,
            "aed_count": aed_count,
            "polg_done": polg_done,
            "erg_done": erg_done,
            "vppp_enrolled": vppp,
            "mri_hypomyelination": mri_hypomyelin,
            "optic_atrophy": optic_atrophy,
            "lgs_transition": lgs_transition,
            "seizure_free": seizure_free,
            "drug_resistant": drug_resistant,
            "drop_attacks": drop_attacks,
            "helmet": helmet,
            "cognitive": cognitive,
        })
