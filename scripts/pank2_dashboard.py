def _patients():
    """Generate 40 synthetic PKAN patients (seed-517)."""
    pts = []
    etio_pool = (
        ["missense"] * 22 + ["null"] * 10 + ["splice"] * 6 + ["cnv"] * 2
    )
    RNG.shuffle(etio_pool)

    aed_options = ["LEV", "VPA", "CLB", "ZNS", "LTG", "KD"]
    dystonia_tx_options = ["BoNT", "Trihex", "Baclofen", "DBS", "Tetbz"]
    seizure_options = ["focal", "gtcs", "myoclonic", "absence", "status", "tonic"]

    for i in range(N):
        etio = etio_pool[i]
        # Phenotype by etiology
        if etio in ("null", "cnv"):
            classic = True
            onset_yr = round(RNG.uniform(1, 5), 1)
            drug_resistant = RNG.random() < 0.65
            dystonia_severity = RNG.choice(["severe", "severe", "generalised"])
            ambulation_lost = RNG.random() < 0.75
        elif etio == "missense":
            classic = RNG.random() < 0.65
            onset_yr = round(RNG.uniform(2, 8) if classic else RNG.uniform(8, 22), 1)
            drug_resistant = RNG.random() < 0.55
            dystonia_severity = RNG.choice(["moderate", "severe"] if classic else ["focal", "moderate"])
            ambulation_lost = classic and RNG.random() < 0.55
        else:  # splice
            classic = RNG.random() < 0.40
            onset_yr = round(RNG.uniform(5, 18), 1)
            drug_resistant = RNG.random() < 0.45
            dystonia_severity = RNG.choice(["focal", "moderate"])
            ambulation_lost = RNG.random() < 0.30

        # Seizures (40-50%)
        has_seizures = RNG.random() < 0.45
        s_types = []
        if has_seizures:
            for stype in seizure_options:
                probs = {
                    "focal": 0.35, "gtcs": 0.28, "myoclonic": 0.18,
                    "absence": 0.12, "status": 0.10, "tonic": 0.08
                }
                if RNG.random() < probs[stype]:
                    s_types.append(stype)
            if not s_types:
                s_types = ["focal"]

        n_aeds = RNG.randint(2, 5) if (has_seizures and drug_resistant) else (RNG.randint(1, 3) if has_seizures else 0)
        aeds_tried = RNG.sample(aed_options, min(n_aeds, len(aed_options))) if n_aeds > 0 else []

        n_dtx = RNG.randint(1, 3)
        dystonia_tx = RNG.sample(dystonia_tx_options, min(n_dtx, len(dystonia_tx_options)))

        retinal = RNG.random() < (0.68 if classic else 0.30)
        acanthocytes = RNG.random() < (0.50 if classic else 0.30)
        eye_of_tiger = RNG.random() < (0.97 if classic else 0.52)
        polg_tested = RNG.random() < 0.72
        dbs = RNG.random() < (0.20 if classic else 0.08)
        psychiatric = (not classic) and RNG.random() < 0.65
        ocd = psychiatric and RNG.random() < 0.55
        palilalia = (not classic) and RNG.random() < 0.45
        cognitive_decline = RNG.random() < (0.60 if classic else 0.70)
        seizure_free = has_seizures and RNG.random() < 0.30
        current_age = round(RNG.uniform(6, 50), 0)

        pts.append({
            "id": f"PKAN-{i+1:03d}",
            "etiology": etio,
            "classic": classic,
            "onset_yr": onset_yr,
            "dystonia_severity": dystonia_severity,
            "ambulation_lost": ambulation_lost,
            "has_seizures": has_seizures,
            "seizure_types": s_types,
            "drug_resistant": drug_resistant and has_seizures,
            "n_aeds_tried": n_aeds,
            "aeds_tried": aeds_tried,
            "dystonia_tx": dystonia_tx,
            "dbs": dbs,
            "retinal_involvement": retinal,
            "acanthocytes": acanthocytes,
            "eye_of_tiger": eye_of_tiger,
            "polg_tested": polg_tested,
            "psychiatric": psychiatric,
            "ocd": ocd,
            "palilalia": palilalia,
            "cognitive_decline": cognitive_decline,
            "seizure_free": seizure_free,
            "current_age": int(current_age),
        })
    return pts


