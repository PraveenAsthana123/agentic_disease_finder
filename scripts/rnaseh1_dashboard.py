def _build_cohort(rng: random.Random) -> list[dict]:
    """Build the 40-patient RNASEH1-AR-CPEO cohort deterministically (seed 575)."""
    etiology_classes = [
        ("AR-Biallelic-Missense-Catalytic-DEDD-Motif-LOF", 35),
        ("AR-Compound-Heterozygous-Catalytic-plus-MTS-Disruption", 25),
        ("AR-Biallelic-Missense-MTS-Import-Defect", 20),
        ("AR-Biallelic-Frameshift-Null-Severe-Early-Onset", 12),
        ("AR-Phenocopy-RNASEH1-Panel-Negative-mtDNA-Deletions", 8),
    ]
    etiology_pool: list[str] = []
    for name, pct in etiology_classes:
        etiology_pool.extend([name] * pct)

    extraocular_patterns = [
        "Complete-Ophthalmoplegia",
        "Incomplete-Ophthalmoplegia-All-Directions",
        "Limited-Elevation-Primarily",
        "Limited-Abduction-Primarily",
        "No-Ophthalmoplegia-Ptosis-Only",
    ]
    ataxia_types = [
        "Cerebellar-Gait-Ataxia-Predominant",
        "Mixed-Gait-Limb-Ataxia-SARA-above-10",
        "Limb-Ataxia-Finger-Nose-Heel-Shin",
    ]
    misdiagnosis_pool = [
        "Spinocerebellar-Ataxia-SCA-Unspecified",
        "Idiopathic-Late-Onset-Cerebellar-Ataxia-ILOCA",
        "POLG-Related-Cerebellar-Ataxia",
        "Mitochondrial-Myopathy-Unspecified",
        "CPEO-Sporadic-Adult-Onset",
        "Myasthenia-Gravis",
    ]

    patients = []
    for i in range(N_PATIENTS):
        pid = f"RNASEH1-{i+1:03d}"
        etiology = rng.choice(etiology_pool)
        age_onset = round(rng.gauss(38, 11), 0)
        age_onset = max(18, min(62, int(age_onset)))

        cerebellar_ataxia = rng.random() < 0.85
        ataxia_type = rng.choice(ataxia_types) if cerebellar_ataxia else None
        sara_score = round(rng.uniform(4, 24), 1) if cerebellar_ataxia else 0.0
        peo = rng.random() < 0.70
        ptosis_bilateral = peo  # bilateral ptosis = PEO in this series
        oph_pattern = rng.choice(extraocular_patterns) if peo else "No-PEO"
        sensory_neuropathy = rng.random() < 0.60
        proximal_myopathy = rng.random() < 0.45
        cognitive_decline = rng.random() < 0.40
        snhl = rng.random() < 0.25
        dysphagia = rng.random() < 0.22
        seizures = rng.random() < 0.07

        ck_x_uln = round(rng.uniform(0.7, 3.4), 1)
        lactate_mmol = round(rng.uniform(1.0, 3.2), 1)
        deletion_load_pct = round(rng.uniform(18, 68), 0)
        dx_delay_years = round(rng.uniform(3, 15), 1)
        misdiagnosis = rng.choice(misdiagnosis_pool)

        patients.append({
            "id": pid,
            "etiology": etiology,
            "age_onset_years": age_onset,
            "cerebellar_ataxia": cerebellar_ataxia,
            "ataxia_type": ataxia_type,
            "sara_score": sara_score,
            "peo": peo,
            "ptosis_bilateral": ptosis_bilateral,
            "ophthalmoplegia_pattern": oph_pattern,
            "sensory_neuropathy": sensory_neuropathy,
            "proximal_myopathy": proximal_myopathy,
            "cognitive_decline": cognitive_decline,
            "snhl": snhl,
            "dysphagia": dysphagia,
            "seizures": seizures,
            "ck_x_uln": ck_x_uln,
            "lactate_mmol": lactate_mmol,
            "deletion_load_pct": int(deletion_load_pct),
            "dx_delay_years": dx_delay_years,
            "initial_misdiagnosis": misdiagnosis,
        })
    return patients


