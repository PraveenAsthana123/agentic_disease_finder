def _make_patients(gene: str, n: int = 40) -> list[dict]:
    prof = PROFILES[gene]
    rng = random.Random(SEEDS[gene])
    patients = []
    for i in range(n):
        age_min, age_max = prof["age_onset_range"]
        age_onset = round(rng.uniform(age_min, age_max), 1)
        age_current = round(rng.uniform(max(age_onset + 1, age_onset), age_onset + 30), 1)

        # Sex assignment — CTLA4 AD so male+female equally; CD81/CD19 AR so equal
        sex = rng.choice(["M", "F"])

        invasive_bacterial  = rng.random() < prof["invasive_bact_prob"]
        mycobacterial       = rng.random() < prof["mycobacterial_prob"]
        lymphoproliferation = rng.random() < prof["lymphoprolif_prob"]
        autoinflammatory    = rng.random() < prof["autoinflam_prob"]
        viral_severe        = rng.random() < (0.45 if prof["viral_suscept"] else 0.08)
        memory_b_absent     = rng.random() < (0.95 if gene in ["ICOS", "CD19", "CD81"] else
                                               0.70 if gene in ["LRBA", "CTLA4"] else
                                               0.60 if gene == "PIK3CD" else 0.50)
        ivig_dependent      = rng.random() < (0.90 if gene in ["CD19", "CD81", "ICOS"] else
                                               0.85 if gene in ["LRBA"] else
                                               0.75 if gene in ["TNFRSF13B", "PIK3CD"] else
                                               0.65 if gene in ["TNFRSF13C", "CTLA4"] else 0.70)
        abatacept_on        = rng.random() < (0.70 if prof["abatacept"] else 0.0)
