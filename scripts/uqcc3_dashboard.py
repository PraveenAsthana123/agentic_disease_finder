def _gen_patients(n: int, seed: int) -> list:
    rng = random.Random(seed)
    origins = [
        "Lebanese", "Iranian", "Turkish", "Pakistani", "Saudi Arabian",
        "Jordanian", "Egyptian", "Israeli (Arab)", "Italian", "Portuguese",
        "French", "German", "Greek", "Spanish", "British", "Dutch",
        "Japanese", "Korean", "Chinese", "Indian",
    ]
    onset_choices = [
        "Late infancy (3-6 months)", "Early childhood (6-12 months)",
        "Early childhood (12-24 months)", "Early childhood (2-3 years)",
        "Mid-childhood (3-5 years)", "Neonatal",
    ]
    onset_weights = [0.15, 0.30, 0.32, 0.12, 0.06, 0.05]
    mri_patterns = [
        "Normal", "Basal ganglia T2 hyperintensity", "Cerebellar atrophy",
        "White matter changes", "Leigh-like pattern (mild)",
    ]
    mri_weights = [0.25, 0.35, 0.20, 0.12, 0.08]
    outcomes = [
        "Alive — mild disability", "Alive — moderate disability",
        "Alive — severe disability", "Deceased (early childhood)",
        "Alive — near-normal development",
    ]
    outcome_weights = [0.32, 0.28, 0.22, 0.10, 0.08]

    patients = []
    for i in range(n):
        onset = rng.choices(onset_choices, weights=onset_weights)[0]
        mri = rng.choices(mri_patterns, weights=mri_weights)[0]
        outcome = rng.choices(outcomes, weights=outcome_weights)[0]
        v1 = rng.choice(VARIANT_NAMES)
        v2 = rng.choice(VARIANT_NAMES)
        ciii_act = round(rng.uniform(8, 32), 1)
        lactic = round(rng.uniform(3.5, 10.5), 1)
        age_onset_m = rng.randint(2, 36)
        age_dx_m = age_onset_m + rng.randint(3, 18)
        patients.append({
            "id": f"UQCC3-{i+1:03d}",
            "sex": rng.choice(["M", "F"]),
            "age_onset_months": age_onset_m,
            "age_dx_months": age_dx_m,
            "origin": rng.choice(origins),
            "variant_allele1": v1,
            "variant_allele2": v2,
            "onset_category": onset,
            "ciii_activity_pct": ciii_act,
            "lactic_acid_mmolL": lactic,
            "hypotonia": rng.random() < 0.80,
            "exercise_intolerance": rng.random() < 0.75,
            "developmental_delay": rng.random() < 0.70,
            "myopathy": rng.random() < 0.65,
            "seizures": rng.random() < 0.30,
            "feeding_difficulties": rng.random() < 0.55,
            "encephalopathy": rng.random() < 0.50,
            "mri_pattern": mri,
            "outcome": outcome,
            "consanguinity": rng.random() < 0.60,
        })
    return patients


