# ── Patient generator ─────────────────────────────────────────────────────────
def _generate_patients():
    """Generate 40 synthetic WWOX/WOREE patients (deterministic seed)."""
    rng = random.Random(8888)
    etiology_weights = [0.45, 0.30, 0.10, 0.10, 0.05]
    etiology_labels = [
        "WOREE-homozygous-null",
        "WOREE-compound-het",
        "WOREE-FRA16D-deletion",
        "SCAR12-mild-biallelic",
        "WOREE-unclassified",
    ]

    patients = []
    for i in range(40):
        r = rng.random()
        cum = 0
        etiology_idx = 0
        for j, w in enumerate(etiology_weights):
            cum += w
            if r < cum:
                etiology_idx = j
                break

        is_severe = etiology_idx in (0, 2)
        is_mild = etiology_idx == 3  # SCAR12

        age_y = round(rng.uniform(0.3, 22), 1)
        onset_m = rng.randint(1, 4) if is_severe else (rng.randint(3, 12) if not is_mild else rng.randint(6, 24))
        drug_resistant = rng.random() < (0.88 if is_severe else (0.72 if not is_mild else 0.42))
        seizure_free = not drug_resistant and rng.random() < 0.15
        has_is = rng.random() < (0.72 if is_severe else (0.48 if not is_mild else 0.22))
        has_csws = rng.random() < (0.28 if is_severe else 0.15)
        hypomyelination = rng.random() < (0.92 if is_severe else 0.65)
        on_vpa = rng.random() < 0.52
        polg_tested = "Y" if rng.random() < 0.68 else "N"
        erg_done = rng.random() < 0.82 if has_is else rng.random() < 0.38
        on_kd = rng.random() < (0.42 if is_severe else 0.22)
        has_consanguinity = rng.random() < (0.55 if is_severe else 0.35)

        patients.append({
            "id": f"WWOX-{i+1:03d}",
            "etiology": etiology_labels[etiology_idx],
            "age_y": age_y,
            "onset_months": onset_m,
            "drug_resistant": drug_resistant,
            "seizure_free": seizure_free,
            "has_infantile_spasms": has_is,
            "has_csws": has_csws,
            "hypomyelination_mri": hypomyelination,
            "on_vpa": on_vpa,
            "polg_tested": polg_tested,
            "erg_done": erg_done,
            "on_kd": on_kd,
            "consanguinity": has_consanguinity,
        })
    return patients


