"""
ARHGEF9 Hyperekplexia / DEE — Collybistin / Xq11.1
====================================================
40-patient cohort · ARHGEF9 (Xq11.1) · Collybistin · X-linked

ARHGEF9 BIOLOGY:
ARHGEF9 (Xq11.1) encodes Collybistin (also CB, ARHGEF9), a 56-kDa Rho Guanine
Nucleotide Exchange Factor that activates CDC42 (GTPase). It is the RAREST member
of the canonical 5-gene hyperekplexia panel (GLRA1 ~70% · SLC6A5 ~15% · GLRB ~5%
· GPHN ~1-2% · ARHGEF9 <1%), but essential for inhibitory synapse assembly upstream
of GPHN. ARHGEF9 is unique in being X-linked: hemizygous males are severely affected,
heterozygous females show variable/carrier phenotypes governed by X-chromosome
inactivation (XCI) skewing.

COLLYBISTIN — STRUCTURE (480 aa, key isoforms CB2SH3+ and CB3):
  DH-DOMAIN (Dbl Homology, aa 1-200): Catalytic RhoGEF domain; CDC42-GEF activity.
    Activates CDC42 → F-actin polymerisation → membrane anchorage of GPHN.
    W24C, G55A, A119P: DH-domain missense abrogating CDC42 activation → no GPHN
    membrane recruitment.
  PH-DOMAIN (Pleckstrin Homology, aa 205-310): Membrane-targeting domain; PI(3)P
    and PI(3,4,5)P3 binding → recruits GPHN/CB complex to postsynaptic membrane.
    R290H / Y268C: PH-domain missense; PI-binding defect → GPHN stays cytoplasmic.
  SH3-DOMAIN (Src Homology 3, aa 310-370, present in CB2SH3+ isoform only):
    Intramolecular autoinhibitory domain. In the absence of NL2 / GPHN E-domain
    interaction, SH3 domain clamps DH-domain in inactive conformation. NL2 relieves
    autoinhibition → open CB → CDC42 activation → GPHN membrane targeting.
    Isoforms lacking SH3 (CB3) are constitutively active but synaptic distribution
    is broader and less regulated. SH3-domain splice exclusion = gain of CB activity
    but loss of NL2-regulated targeting specificity.
  C-TERMINAL GPHN-BINDING MOTIF (aa 370-480): Direct interaction with GPHN E-domain;
    essential for GPHN membrane translocation. Loss-of-function here → GPHN trapped
    cytoplasmic → iPSD collapse → GlyR + GABA_A R clustering failure.

COLLYBISTIN MECHANISM — INHIBITORY SYNAPSE ASSEMBLY:
  Step 1: NL2 (Neuroligin-2) or neuropilin-2 or GABAAR α1 subunit binds ARHGEF9
          SH3 domain → relieves autoinhibition → CB open conformation.
  Step 2: Active CB (DH-domain) → CDC42-GDP → CDC42-GTP → F-actin polymerisation.
  Step 3: CB PH-domain binds membrane PI(3)P / PI(3,4,5)P3 → CB-GPHN complex docks
          at postsynaptic membrane.
  Step 4: GPHN G-domain trimers + E-domain dimers assemble hexagonal iPSD lattice.
  Step 5: GPHN E-domain captures GlyR (via GLRB intracellular loop) and GABA_A R
          (via β/γ intracellular domains) → GlyR + GABA_A R stabilised at synapse.
  Loss of ARHGEF9 → entire cascade fails upstream → iPSD never assembles correctly
  → both GlyR AND GABA_A R clustering fail (same end-result as GPHN LOF, but
  upstream mechanism: GPHN exists but is cytoplasmic, not membrane-anchored).

PHENOTYPIC SPECTRUM — X-LINKED:
  HEMIZYGOUS MALES (LOF): Most severe; complete absence of functional collybistin.
    GPHN stays cytoplasmic → iPSD collapse → neonatal hyperekplexia (rigid baby,
    exaggerated startle, nose-tap positive, apnoeic episodes) PLUS severe DEE
    (epileptic encephalopathy: infantile spasms / Lennox-Gastaut) PLUS profound ID
    (IQ <40 in most cases). Hyperekplexia component responds to clonazepam;
    epileptic component requires ACTH/VGB (IS) or broad ASM. Behavioural: ASD,
    aggression, hyperactivity in survivors.
  HETEROZYGOUS FEMALES (carrier): Variable — XCI skewing governs phenotype.
    Unfavourable skewing (>70% mutant X expressed) → mild-moderate hyperekplexia
    ± mild ID ± anxiety/ASD traits. Favourable XCI → asymptomatic carrier.
    XCI ANALYSIS MANDATORY for heterozygous females: AR methylation assay or SNP
    array to determine skewing. A carrier female with symptoms needs CLZ trial.
  MALE HYPOMORPHIC / MOSAIC: Partial LOF → mild hyperekplexia ± mild ID;
    phenotype closer to GLRA1 HYPER1 than DEE spectrum.

DISTINGUISHING ARHGEF9 FROM GPHN:
  Both ARHGEF9 and GPHN affect both GlyR AND GABA_A R anchoring (dual inhibitory
  failure). The distinction is:
    GPHN LOF: GPHN scaffold absent → iPSD cannot form. Catastrophic.
    ARHGEF9 LOF: GPHN exists but is cytoplasmic (cannot reach membrane) → iPSD
      cannot form without GPHN membrane anchoring. Equally catastrophic but
      GPHN protein is NORMAL in ARHGEF9-deficient patients.
  Genetic testing is required to distinguish; phenotype alone cannot differentiate.
  GPHN gene sequencing + CNV → if normal, proceed to ARHGEF9 (Xq11.1 analysis,
  MLPA for Xq11 deletions, sequencing of ARHGEF9 coding exons 1-13).

CONTRAINDICATED DRUGS:
  VALPROATE (VPA): POLG check MANDATORY before prescribing. VPA in POLG mutation
    carriers → fatal Alpers-Huttenlocher hepatic failure. This rule applies to all
    5 hyperekplexia genes; ARHGEF9 DEE patients commonly require ASM → VPA risk
    is particularly salient.
  LAMOTRIGINE (LTG): May exacerbate myoclonic component; use with caution.
  CARBAMAZEPINE (CBZ) / OXCARBAZEPINE (OXC): Risk of worsening in DEE subtype
    (Na-channel blockade may aggravate some encephalopathic phenotypes).

VIGEVANO MANOEUVRE (APNOEA EMERGENCY):
  MANDATORY for all hyperekplexia genes. Neonatal reflex apnoea triggered by
  tonic startle episode may be fatal if not terminated immediately. Forward
  flexion of head onto chest interrupts tonic reflex and restores breathing.
  For ARHGEF9 males (severe DEE), apnoeic risk is highest in neonatal period.
  Caregivers, nursing staff, and emergency first responders must be trained.
  Even in females with mild phenotype, manoeuvre training is advisable.

5-GENE PANEL (MANDATORY simultaneous testing):
  Clinical hyperekplexia cannot distinguish the 5 genes phenotypically.
  Simultaneously test: GLRA1 · GLRB · SLC6A5 · GPHN · ARHGEF9.
  For ARHGEF9: males require Xq11.1 MLPA (deletion common) + exon sequencing.
  Females: heterozygous variants; XCI assay to determine clinical significance.

NKH DIFFERENTIAL DIAGNOSIS:
  Nonketotic Hyperglycinemia (NKH) mimics hyperekplexia in neonates (rigid baby,
  myoclonus, apnoea). Plasma glycine is ELEVATED in NKH (>600 µmol/L);
  CSF:plasma glycine ratio >0.08. In ARHGEF9/GPHN/GLRA1/GLRB/SLC6A5 hyperekplexia,
  glycine is NORMAL. NKH metabolic screen (plasma/CSF glycine, CSF:plasma ratio)
  must be performed before or alongside 5-gene panel.
  Biotinidase deficiency is another metabolic mimic (biotin responsive); always
  include biotinidase activity assay in neonatal hyperekplexia workup.
"""

