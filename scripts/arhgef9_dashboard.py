# ── PATIENT COHORT  (40 patients, seed 503) ──────────────────────────────────
def _build_cohort():
    rng = random.Random(503)
    pts = []
    pid = 1
    for ec in ETIOLOGY_CATALOG:
        cat = ec["category"]
        is_severe = "Severe" in cat
        is_hypomorphic = "Hypomorphic" in cat
        is_female = "Female" in cat
        is_phenocopy = "Phenocopy" in cat

        for _ in range(ec["n_target"]):
            # Hyperekplexia features
            is_hyperekplexia = not is_phenocopy or rng.random() < 0.50
            is_dee = is_severe and rng.random() < 0.88

            apnoeic = is_hyperekplexia and rng.random() < (0.85 if is_severe else 0.55 if is_female else 0.50)
            rigid_baby = is_hyperekplexia and rng.random() < (0.90 if is_severe else 0.65 if is_hypomorphic else 0.45)
            epileptic = is_dee and rng.random() < 0.90 or (is_severe and rng.random() < 0.40)
            id_ = not is_phenocopy and rng.random() < (0.95 if is_severe else 0.65 if is_hypomorphic else 0.35 if is_female else 0.20)
            on_clz = is_hyperekplexia and rng.random() < (0.88 if is_severe else 0.80)
            asm_for_seizures = epileptic and rng.random() < 0.90
            manoeuvre = is_hyperekplexia and rng.random() < 0.93
            gene_panel = rng.random() < 0.97
            nose_tap = is_hyperekplexia and rng.random() < (0.85 if is_severe else 0.60)
            xci_tested = is_female and rng.random() < 0.82
            eeg_abnormal = epileptic or (is_severe and rng.random() < 0.85)
            xq11_mlpa = not is_phenocopy and rng.random() < 0.75
            polg_tested = (asm_for_seizures or epileptic) and rng.random() < 0.88
            asd = is_severe and rng.random() < 0.45 or (is_female and rng.random() < 0.15)

            age_onset_wks = (
                rng.randint(0, 2) if is_severe
                else rng.randint(1, 12) if is_hypomorphic
                else rng.randint(2, 24)
            )

            pts.append({
                "id": f"P{pid:03d}",
                "category": cat,
                "age_onset_weeks": age_onset_wks,
                "apnoeic_events": apnoeic,
                "rigid_baby": rigid_baby,
                "epileptic_seizures": epileptic,
                "intellectual_disability": id_,
                "on_clonazepam": on_clz,
                "asm_for_seizures": asm_for_seizures,
                "forward_flexion_trained": manoeuvre,
                "gene_panel_tested": gene_panel,
                "nose_tap_positive": nose_tap,
                "xci_tested": xci_tested,
                "eeg_abnormal": eeg_abnormal,
                "xq11_mlpa_done": xq11_mlpa,
                "polg_tested": polg_tested,
                "asd_diagnosis": asd,
            })
            pid += 1
    return pts


