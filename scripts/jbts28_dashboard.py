    hypotonia = _rng_p.random() < 0.75
    oma       = _rng_p.random() < 0.48
    breath    = _rng_p.random() < 0.45
    retinal   = _rng_p.random() < 0.28   # rod-cone; B9-complex TZ gate; connecting cilia
