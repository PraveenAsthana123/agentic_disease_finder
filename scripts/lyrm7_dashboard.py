def _pick_variants(rng):
    v1 = rng.choices(ALL_VARIANTS, weights=VARIANT_WEIGHTS, k=1)[0]
    v2 = rng.choices(ALL_VARIANTS, weights=VARIANT_WEIGHTS, k=1)[0]
    return v1, v2


def _generate_patients():
    rng = random.Random(SEED)
    patients = []
    for i in range(COHORT_N):
        v1, v2 = _pick_variants(rng)
        sev1 = v1["severity"]
        sev2 = v2["severity"]
        combined_severe = "Severe" in sev1 and "Severe" in sev2

        # CIII activity — LYRM7 has partial residual (15-35%), unlike UQCC1/UQCC2 (<8%)
        if combined_severe:
            ciii_act = round(rng.uniform(7.0, 22.0), 1)
        elif "Intermediate" in sev1 or "Intermediate" in sev2:
            ciii_act = round(rng.uniform(18.0, 38.0), 1)
        else:
            ciii_act = round(rng.uniform(10.0, 28.0), 1)

        # Lactate (moderate: 4-12 mM — milder than UQCC1/UQCC2)
        if combined_severe:
            lac = round(rng.uniform(6.0, 13.0), 1)
        else:
            lac = round(rng.uniform(3.5, 9.5), 1)

        # Onset (months): infantile, NOT neonatal
        if combined_severe:
            onset_mo = rng.choices([0, 1, 2, 3, 4, 6], weights=[3, 18, 28, 25, 16, 10])[0]
        else:
            onset_mo = rng.choices([3, 6, 9, 12, 18, 24], weights=[12, 25, 28, 20, 10, 5])[0]

        dx_delay = rng.randint(1, 4)
        dx_mo = onset_mo + dx_delay

        sex = rng.choice(["M", "F"])
        origin = ORIGINS[i % len(ORIGINS)]

        # Outcome — less severe than UQCC1/UQCC2
        if ciii_act < 12 and lac > 9:
            outcome_choices = ["Deceased 6-18mo", "Deceased 18-36mo",
                               "Alive-severe-disability", "Deceased 6-18mo"]
            outcome = rng.choice(outcome_choices)
        elif ciii_act < 20:
            outcome_choices = ["Alive-severe-disability", "Alive-moderate-disability",
                               "Deceased 18-36mo", "Alive-severe-disability"]
            outcome = rng.choice(outcome_choices)
        else:
            outcome_choices = ["Alive-moderate-disability", "Alive-mild-disability",
                               "Alive-severe-disability"]
            outcome = rng.choice(outcome_choices)

        consanguineous = rng.random() < 0.55
        has_leigh = rng.random() < 0.45
        has_seizures = rng.random() < 0.32
        has_feeding = rng.random() < 0.60

        patients.append({
            "id": f"LYRM7-{i+1:03d}",
            "sex": sex,
            "age_onset_months": onset_mo,
            "age_dx_months": dx_mo,
            "origin": origin,
            "consanguineous": consanguineous,
            "variant_allele1": v1["protein"],
            "variant_allele2": v2["protein"],
            "ciii_activity_pct": ciii_act,
            "lactic_acid_mmolL": lac,
            "leigh_mri": has_leigh,
            "seizures": has_seizures,
            "feeding_difficulties": has_feeding,
            "outcome": outcome,
        })
    return patients


