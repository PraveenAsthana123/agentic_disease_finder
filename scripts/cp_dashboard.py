def _build_patients() -> list:
    patients = []
    for phenotype, count in PHENOTYPES:
        for i in range(count):
            patients.append(_make_patient(len(patients), phenotype))
    return patients


_PATIENTS = _build_patients()


def _pct(pts: list, key: str) -> int:
    if not pts:
        return 0
    count = sum(1 for p in pts if p.get(key))
    return round(count / len(pts) * 100)


def _avg(pts: list, key: str) -> float:
    vals = [p[key] for p in pts if isinstance(p.get(key), (int, float))]
    if not vals:
        return 0.0
    return round(sum(vals) / len(vals), 1)


