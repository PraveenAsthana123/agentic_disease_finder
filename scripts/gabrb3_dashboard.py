"""
GABRB3 Epilepsy — DEE28 (GABA-A Receptor β3 Subunit / West Syndrome → LGS)
===========================================================================
41-patient cohort · GABRB3 (15q12) · GABA-A Receptor Beta-3 (β3) Subunit

GABRB3 / GABA-A RECEPTOR BIOLOGY:
GABRB3 (15q12) encodes the β3 subunit of the GABA-A receptor (GABA type-A receptor), the
principal inhibitory ionotropic receptor in the CNS. GABA-A receptors are pentameric
ligand-gated Cl⁻ channels, most commonly composed of 2α + 2β + 1γ subunits. The β3 subunit
is the predominant β isoform in early brain development (peaking neonatally — expression >β1
and >β2 in fetal/neonatal neocortex, thalamus, limbic structures). GABRB3 mutations cause
DEE28, a severe developmental and epileptic encephalopathy.

GABRB3 / β3-GABA-A PATHOPHYSIOLOGY:
De novo loss-of-function (LOF) GABRB3 variants → reduced β3 subunit expression/function →
impaired GABA-A receptor assembly (β3 required for proper receptor trafficking to membrane) →
reduced GABAergic inhibitory conductance in developing cortex, thalamo-cortical circuits,
and limbic areas → neuronal hyperexcitability → severe neonatal/infantile epilepsy.

KEY DEVELOPMENTAL MECHANISM — WHY β3-LOSS IS CATASTROPHIC IN INFANCY:
β3 subunit expression is HIGHEST during the critical period (0-2 years) when GABA is
paradoxically EXCITATORY (neonatal GABA excitation → inhibition switch occurs at 12-24
months via KCC2 chloride transporter maturation). Before the GABA polarity switch,
GABA-A dysfunction impairs the entire developmental inhibitory framework. After the switch,
β3-LOF → insufficient adult-type GABAergic inhibition. This dual mechanism (neonatal
GABA-excitatory AND adult GABA-inhibitory impairment) explains the severity of GABRB3-DEE28.

GABRB3 SUBUNIT FUNCTION IN RECEPTOR TRAFFICKING:
β3 subunit contains the GABA-binding pocket (shared with α), benzodiazepine-potentiating site
(requires γ2 co-assembly), and the intracellular clustering domain (gephyrin-binding) critical
for synaptic localisation. LOF → receptors fail to traffic to synaptic membrane → functional
GABA-A loss despite mRNA expression. β3 ALSO contributes to tonic inhibition (extrasynaptic
δ-subunit-containing receptors in many brain regions). Thus β3-LOF abolishes both phasic
(synaptic) and tonic (extrasynaptic) inhibition simultaneously — explaining catastrophic
neonatal phenotype and severity of West/LGS transition.

BENZODIAZEPINE SENSITIVITY — CRITICAL CLINICAL IMPLICATION:
Benzodiazepines (diazepam, clonazepam, clobazam, midazolam) act by POTENTIATING GABA-A
receptors at the benzodiazepine-binding site (located between α and γ2 subunits). The BDZ
site requires: α1/α2/α3/α5 subunit (not α4/α6) AND γ2 subunit (not δ). β3 subunit is
REQUIRED for efficient γ2 incorporation during receptor assembly:
  - GABRB3-LOF → fewer β3 subunits → less efficient γ2 incorporation →
    fewer complete α-β-γ2 pentamers (BDZ-sensitive) at synapse →
    REDUCED BENZODIAZEPINE EFFICACY in acute seizure management.
Clinical reality: emergency BDZ rescue (diazepam rectal/buccal midazolam) is LESS effective
in GABRB3-DEE. Studies show ~40% lower seizure termination rate with standard BDZ doses.
Implication: higher BDZ doses needed for SE management; earlier escalation to phenobarbitone
IV or levetiracetam IV when BDZ resistance seen. Document BDZ reduced efficacy in EMR.

GABRB3 AND KETOGENIC DIET — MECHANISM:
KD works upstream of GABRB3: β-hydroxybutyrate → inhibits KATP channels → hyperpolarises
neurons; acetone → directly inhibits sodium channels; ketone bodies → increase GABA synthesis
(acetoacetate → GABA transaminase inhibition → GABA accumulation). Crucially, KD effects do
NOT require functional β3-GABA-A receptor — they bypass the impaired inhibitory synapse
entirely. KD is thus mechanistically sound in GABRB3-DEE even with severe β3-LOF.
KD efficacy in GABRB3-DEE: ~55% ≥50% seizure reduction (comparable to other channelopathies
at this age group); particularly effective for hypnic (sleep-related) spasms.

VIGABATRIN (GABA TRANSAMINASE INHIBITOR) — MECHANISM:
VGB irreversibly inhibits GABA transaminase → increases presynaptic GABA → increased vesicular
GABA release → even with reduced postsynaptic GABA-A (β3-LOF), the high GABA concentration
partially compensates by mass action. VGB is used as first-line for infantile spasms (alongside
ACTH/corticosteroids). In TSC-related spasms VGB is definitively first-line; in GABRB3-DEE it
is a tier-1 option for West syndrome phase. VISUAL FIELD DEFECT: irreversible retinal toxicity
in >30% of patients on long-term VGB — mandatory ERG + visual field testing q6M.

ACTH/CORTICOSTEROIDS — MECHANISM IN GABRB3-DEE:
ACTH → stimulates adrenal cortisol + adrenal androgens → suppresses CRH (corticotropin-
releasing hormone), which is itself a potent convulsant (CRH-R1 activation → GABA-A
phosphorylation → reduced receptor function). ACTH also: (1) promotes β3 subunit SURFACE
EXPRESSION (PKA pathway → β3 phosphorylation → increased synaptic localisation); (2)
increases GABA release in hypothalamic circuits. ACTH is thus mechanistically aligned with
GABRB3-LOF: it partially compensates for impaired β3-mediated GABA-A surface expression.
High-dose ACTH (UK protocol: Acthar 40-80 IU/day IM × 2 weeks + taper) is first-line for
West syndrome in GABRB3-DEE. Oral prednisolone is alternative (non-inferior to ACTH in
UKISS trial for general infantile spasms).

GABRB3-SPECIFIC ABSOLUTE CONTRAINDICATION — LAMOTRIGINE:
LTG in GABRB3-DEE: sodium channel blocker → reduces action potential firing → PARADOXICALLY
WORSENS myoclonic and atonic seizures (characteristic of DEE28 evolving to Lennox-Gastaut
phenotype). Multiple case reports of LTG-induced status epilepticus in GABRB3-LOF DEE with
myoclonic features. LTG should be AVOIDED until seizure type fully characterised and no
myoclonic component confirmed. (Contrast: LTG is often used in LGS for tonic/absence seizures
— but only after excluding myoclonic predominance. In GABRB3-DEE, myoclonic component is
often present early even if not the dominant type.)

GABRB3 AND THE 15q12 LOCUS:
GABRB3 is located at 15q12 alongside GABRA5 (α5 subunit) and GABRG3 (γ3 subunit). Large
15q11-q13 deletions (Angelman spectrum) may involve all three genes → combined α5/β3/γ3
deficiency. Isolated GABRB3 de novo point mutations/small indels → pure β3-LOF. Chromosome
15q duplication → GABRB3 overexpression → autism + epilepsy (different mechanism from LOF).
Key genotype-phenotype rule: de novo heterozygous GABRB3 LOF/dominant-negative → DEE28;
15q12 microdeletion encompassing GABRB3+GABRA5 → more severe (combined α5/β3 loss).

MOST COMMON GABRB3 VARIANTS (ACMG/ILAE):
  p.Ala305Val   (c.914C>T)  — transmembrane domain 3 (TM3); dominant-negative via subunit
                               sequestration; most common missense in DEE28 cohorts
  p.Pro11Ser    (c.31C>T)   — signal peptide: impaired ER entry, reduces surface expression
  p.Glu177Ala   (c.530A>C)  — extracellular domain, GABA-binding region; severe phenotype
  Exon 1-9 deletion          — detected by MLPA; ~8% of GABRB3-DEE cases
  c.825+1G>A    (splice donor) — exon 6 loss; PTC → NMD → complete haploinsufficiency
  p.Asn328Ser   (c.983A>G)  — TM3-TM4 linker; reduced single-channel conductance

KEY SAFETY PEARLS:
• LAMOTRIGINE AVOID in myoclonic-predominant GABRB3-DEE — Na-channel blockade → myoclonic
  worsening and LGS pseudo-exacerbation. Document as CAUTIONARY in EMR.
• CARBAMAZEPINE/OXCARBAZEPINE AVOID — Na-channel blockers worsen myoclonic-atonic seizures
  (if present in evolving LGS phenotype). Also: CBZ aggravates typical absence in DEE.
• BDZ REDUCED EFFICACY — use higher doses than standard for acute SE rescue; document
  reduced BDZ sensitivity; escalate earlier to IV LEV/phenobarbitone.
• VIGABATRIN VISUAL TOXICITY — mandatory ERG + visual fields q6M; document cumulative
  VGB dose; plan weaning after infantile spasms controlled (typically by 12-18M of age).
• KETOGENIC DIET DOES NOT REQUIRE β3 FUNCTION — mechanistically bypasses impaired GABA-A;
  consider early (after ACTH + VGB failure in West phase, or directly in LGS phase).
• DIETARY CONSISTENCY ON KD — even one high-carbohydrate meal can precipitate spasm cluster
  in GABRB3-DEE (less KD metabolic buffering than in GLUT1-DS). Strict 4:1 ratio required.
"""

