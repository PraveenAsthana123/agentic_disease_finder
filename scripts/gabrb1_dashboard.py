"""
GABRB1 Epilepsy — DEE (GABA-A Receptor β1 Subunit / Limbic-Hippocampal / GEFS+ / 4p12)
========================================================================================
40-patient cohort · GABRB1 (4p12) · GABA-A Receptor Beta-1 (β1) Subunit

GABRB1 / GABA-A β1 SUBUNIT BIOLOGY:
GABRB1 (4p12) encodes the β1 subunit of the GABA-A receptor (GABA type-A receptor), the
principal inhibitory ionotropic receptor in the CNS. GABA-A receptors are pentameric ligand-
gated Cl⁻ channels, most commonly composed of 2α + 2β + 1γ subunits. While β2 is the
dominant cortical isoform and β3 is the dominant fetal/neonatal isoform, β1 has a distinct
regional specialisation: HIGHEST EXPRESSION in limbic structures — hippocampus (CA1/CA3/
dentate gyrus), amygdala, septum, piriform cortex, and entorhinal cortex. This limbic
distribution has direct clinical consequences: GABRB1 mutations produce epilepsy with
prominent temporal lobe and limbic features.

GABRB1 β1 SUBUNIT — MOLECULAR FUNCTION:
β1 preferentially assembles with α5 subunits to form α5β1γ2 pentamers at extrasynaptic
locations in hippocampal pyramidal cells. These receptors mediate TONIC INHIBITION —
persistent, low-level Cl⁻ conductance that sets the background membrane excitability of
hippocampal neurons and controls the threshold for seizure initiation. α5β1γ2 is the
DOMINANT TONIC INHIBITORY RECEPTOR in hippocampus CA1:
  - α5 subunit contributes the GABA binding pocket and is insensitive to standard
    benzodiazepines (requires α1/2/3 for BDZ sensitivity)
  - β1 subunit contributes to receptor assembly, trafficking (gephyrin-independent
    extrasynaptic clustering via GABARAP/GABARAPL1), and desensitisation kinetics
  - γ2 subunit enables some benzodiazepine potentiation of the larger phasic fraction
β1-LOF → loss of hippocampal extrasynaptic tonic inhibition → lowered seizure threshold
→ limbic hyperexcitability → temporal lobe epilepsy + DEE spectrum.

GABRB1 ALLELIC DISORDER SPECTRUM:
  1. De novo LOF (Severe DEE):
     - Truncating, frameshift, or severe missense variants → haploinsufficiency
     - Phenotype: infantile spasms (West syndrome) → DEE with regression
     - MRI: may show hippocampal signal change or subtle FCD in limbic areas
     - Onset: 3–12 months
  2. De novo GOF (DEE, limbic-predominant):
     - Gain-of-function missense → altered β1 gating → excess tonic Cl⁻ conductance
       in early development (when GABA is depolarising, before KCC2 maturation) →
       paradoxical neonatal excitation (GABA polarity not yet inverted) → early
       infantile seizures transitioning to temporal lobe pattern after polarity switch
     - Onset: neonatal to early infantile
  3. Familial AD LOF (GEFS+ spectrum):
     - Mild missense → reduced β1 surface expression → FS+ phenotype with variable
       afebrile seizures (absence, myoclonic, GTCS); penetrance 60–75%
     - Onset: 6 months to 6 years (febrile seizures onset)
  4. De Novo/AD — focal temporal lobe epilepsy:
     - Moderate missense → partial β1 dysfunction in limbic tissue → focal temporal
       lobe epilepsy with déjà vu, epigastric aura, oral automatisms, hippocampal MRI
       changes; no DEE; good prognosis with AED control

BENZODIAZEPINE PARTIAL HYPOSENSITIVITY IN GABRB1:
β1-containing receptors are primarily extrasynaptic (α5β1γ2). Standard benzodiazepines
(diazepam, lorazepam, midazolam) potentiate at the α-γ2 interface of α1/2/3-containing
GABA-A receptors. α5-containing receptors show REDUCED benzodiazepine potentiation
compared with α1/2/3 receptors. β1-LOF → further reduction in functional α5β1γ2 extrasynaptic
pools → BDZ rescue LESS EFFECTIVE for status epilepticus in GABRB1-DEE.
Clinical implication:
  - Standard IV diazepam/lorazepam may fail at typical doses in acute SE
  - Use HIGHER BDZ doses or escalate earlier to IV LEV/VPA/PB for SE management
  - CLONAZEPAM shows RELATIVE ADVANTAGE: clonazepam has higher potency at α5-containing
    extrasynaptic receptors (CZP EC50 lower for α5β1γ2 than DZP) → preferred for
    maintenance; still reduced from normal but better relative efficacy than diazepam

PERAMPANEL (AMPA RECEPTOR ANTAGONIST) — MECHANISTIC RATIONALE:
When postsynaptic GABA-A inhibition is impaired (β1-LOF → reduced tonic inhibition in
hippocampus), seizure initiation is driven by AMPA-receptor-mediated excitatory
glutamate currents overcoming the impaired inhibitory brake. Perampanel (AMPA-type
glutamate receptor antagonist) blocks this excitatory drive at its source:
  - Non-competitive AMPA blocker: reduces glutamate EPSP amplitude in hippocampal pyramids
  - Works UPSTREAM of GABA-A: does not require functional β1 receptor
  - Particularly effective when the primary seizure mechanism is limbic/hippocampal
    hyperexcitability (the β1-LOF signature)
  - Level C evidence in GABRB1 (case series); Level A evidence in focal epilepsy generally
  - Dose: 2–12 mg/day titrated slowly; psychiatric monitoring (aggression/irritability)
  - Mechanism complementary to VPA (which increases GABA synthesis) and LEV (SV2A)

ACTH AND CORTICOSTEROIDS — β1-SPECIFIC MECHANISM:
ACTH stimulates adrenal cortisol production which:
  1. Suppresses CRH (corticotropin-releasing hormone), a potent pro-convulsant that
     directly inhibits GABA-A receptor function via CRH-R1 signalling
  2. Promotes GABRB1 (β1) subunit PHOSPHORYLATION via PKA pathway (Ser408/409
     equivalent sites) → increased β1 receptor trafficking to extrasynaptic membrane
     → partially compensates for LOF haploinsufficiency
This mechanism is shared with GABRB3 (β3 PKA phosphorylation) but less studied for β1.
High-dose ACTH first-line for West syndrome in GABRB1-DEE (40-80 IU/day IM × 2 weeks).

KETOGENIC DIET — β1-BYPASS MECHANISM:
β-hydroxybutyrate and acetoacetate bypass the impaired β1-GABA-A tonic inhibition:
  - BHB inhibits KATP channels → neuronal hyperpolarisation
  - Acetoacetate inhibits vesicular glutamate transporter → reduced presynaptic glutamate
  - Ketone bodies enhance GABA synthesis (GABA transaminase competitive inhibition → GABA
    accumulation in presynaptic terminals → increased phasic GABA release compensates for
    reduced tonic inhibition)
  - KD does NOT require functional β1 extrasynaptic GABA-A receptor
KD is strongly indicated in GABRB1-DEE as a precision mechanism bypass therapy.

LAMOTRIGINE — CONTRAINDICATION IN DEE/MYOCLONIC COMPONENT:
LTG (Na-channel blocker) → can paradoxically worsen myoclonic and atonic seizures in DEE.
In GABRB1-DEE with myoclonic features (common in the West syndrome→DEE transition):
  - LTG blocks sodium channels → reduces action potential firing → normally antiepileptic
  - BUT in Lennox-Gastaut-spectrum DEE: LTG specifically worsens tonic/myoclonic/atonic
    seizures in ~25% of patients — especially myoclonic atonic epilepsy (Doose syndrome)
  - GABRB1-DEE with myoclonic component: LTG HIGH RISK — avoid or use only with close
    monitoring for myoclonic worsening
  - Exception: GEFS+ or focal temporal lobe phenotype WITHOUT myoclonic component —
    LTG may be considered (monitor EEG for myoclonic activation)

VPA AND POLG1 SCREENING — ABSOLUTE REQUIREMENT:
VPA is first-line for generalised myoclonic component in GABRB1 epilepsy. However:
  - POLG (polymerase gamma, mitochondrial DNA replication enzyme) mutations cause Alpers-
    Huttenlocher syndrome with features overlapping DEE: regression, liver dysfunction,
    seizures including CSWS/DE
  - VPA in POLG mutation carriers → fatal hepatic failure via mitochondrial toxicity
  - GABRB1-DEE and Alpers can both present with infantile-onset regression + seizures
  - POLG panel sequencing (POLG1 full gene ± POLG2) MANDATORY before starting VPA in
    any infant/young child with DEE presentation
  - If POLG positive: avoid VPA; use LEV + CLB + KD instead

KEY DISTINCTION FROM GABRB2 AND GABRB3:
  GABRB2 (5q34): dominant cortical/thalamic isoform → thalamo-cortical 3 Hz oscillations
    (CAE, JME, GEFS+); generalized phenotype; ethosuximide relevant for absence
  GABRB3 (15q12): dominant FETAL/NEONATAL isoform → neonatal onset West→LGS; BDZ
    severely reduced (β3 required for phasic synaptic BDZ-sensitive assembly in neonate)
  GABRB1 (4p12): dominant LIMBIC/HIPPOCAMPAL isoform → temporal lobe + limbic features;
    BDZ PARTIALLY reduced (extrasynaptic α5β1 BDZ-hyposensitive); perampanel AMPA rationale;
    clonazepam preferred BDZ; GEFS+ familial phenotype has temporal lobe predominance
"""

