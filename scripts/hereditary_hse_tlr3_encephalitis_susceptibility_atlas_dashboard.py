# ─── Patient cohort generator ────────────────────────────────────────────────────
def _make_cohort(gene: str, n: int = 40) -> list[dict]:
    rng = random.Random(SEEDS[gene])
    pr = PROFILES[gene]
    patients = []
    for i in range(1, n + 1):
        temporal_lobe = rng.random() < pr["hse_temporal_lobe_pct"] / 100
        acyclovir_resp = rng.random() < pr["acyclovir_response_pct"] / 100
        recurrence = rng.random() < pr["recurrence_pct"] / 100
        sequelae = rng.random() < pr["neurological_sequelae_pct"] / 100
        ifn_reduced = rng.random() < pr["ifn_beta_reduced_pct"] / 100
        pleds = rng.random() < pr["pleds_on_eeg_pct"] / 100
        hsv_pcr = rng.random() < pr["csf_hsv_pcr_positive_pct"] / 100
        brainstem = rng.random() < pr["brainstem_pct"] / 100
        vzv_cns = rng.random() < pr["vzv_cns_pct"] / 100

        # IFNAR1-specific
        live_vax_enceph = False
        if gene == "IFNAR1":
            live_vax_enceph = rng.random() < pr.get("measles_vaccine_encephalitis_pct", 0) / 100

        # DBR1-specific
        resp_failure = False
        cn_palsy = False
        if gene == "DBR1":
            resp_failure = rng.random() < pr.get("respiratory_failure_pct", 0) / 100
            cn_palsy = rng.random() < pr.get("cranial_nerve_palsy_pct", 0) / 100

        # TBK1-specific
        als_family = False
        if gene == "TBK1":
            als_family = rng.random() < pr.get("als_risk_family_pct", 0) / 100

        # TRAF3-specific
        ebv_cns = False
        if gene == "TRAF3":
            ebv_cns = rng.random() < pr.get("ebv_cns_pct", 0) / 100

        age_onset = max(0.5, rng.gauss(4.5, 3.0))  # childhood onset, mean ~4.5yr
        # MRI severity score 1-10
        mri_severity = round(rng.gauss(7.5, 1.5), 1) if temporal_lobe else round(rng.gauss(5.0, 2.0), 1)
        mri_severity = max(1.0, min(10.0, mri_severity))
        # Days to treatment from symptom onset
        days_to_acyclovir = max(1, int(rng.gauss(3.5, 2.0)))
        patients.append({
            "patient_id":             f"{gene}-{i:03d}",
            "seed":                   SEEDS[gene],
            "age_onset_yr":           round(age_onset, 1),
            "temporal_lobe_hse":      temporal_lobe,
            "brainstem_encephalitis": brainstem,
            "acyclovir_response":     acyclovir_resp,
            "recurrence":             recurrence,
            "neurological_sequelae":  sequelae,
            "ifn_beta_reduced":       ifn_reduced,
            "pleds_on_eeg":           pleds,
            "csf_hsv_pcr_positive":   hsv_pcr,
            "vzv_cns_disease":        vzv_cns,
            "mri_severity_score":     mri_severity,
            "days_to_acyclovir":      days_to_acyclovir,
            "live_vaccine_encephalitis": live_vax_enceph,
            "respiratory_failure":    resp_failure,
            "cranial_nerve_palsy":    cn_palsy,
            "als_family_history":     als_family,
            "ebv_cns_disease":        ebv_cns,
        })
    return patients


