def _pick(items, weights, r):
    cumulative = 0
    for item, w in zip(items, weights):
        cumulative += w
        if r < cumulative:
            return item
    return items[-1][0] if isinstance(items[-1], tuple) else items[-1]

def _pick_ac(r):
    return _pick([a[0] for a in _ALLELE_CLASSES],
                 [a[1] for a in _ALLELE_CLASSES], r.random())

def _pick_eth(r):
    return _pick([e[0] for e in _ETHNICITIES],
                 [e[1] for e in _ETHNICITIES], r.random())

