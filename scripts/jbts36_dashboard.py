# Elongated cilia → distorted Hh gradient (not ablated) → cerebellar strong
_P_ATAXIA    = 0.76   # cerebellar ataxia (MTS-driven; high penetrance)
_P_HYPOTONIA = 0.70   # neonatal hypotonia
_P_OMA       = 0.42   # oculomotor apraxia
_P_BREATH    = 0.32   # breathing dysregulation (episodic neonatal; moderate)
_P_RETINAL   = 0.28   # rod-cone dystrophy (photoreceptor connecting cilia elongated)
_P_RENAL     = 0.22   # NPHP-like (tubular primary cilia elongated; higher than CP110 subtypes)
_P_HEPATIC   = 0.08   # cholangiocyte dysfunction (biliary cilia elongated; mild)
_P_POLY      = 0.14   # postaxial polydactyly (GLI3-activator shift; above JBTS35)
_P_ID        = 0.62   # intellectual disability (mild-moderate)
_P_ESRD      = 0.09   # ESRD by adulthood (renal mild-moderate trajectory)

# ── Generate patient cohort ──────────────────────────────────────────────────
_rng_p = random.Random(SEED + 1)

patients = []
for i in range(N):
    eth = _pick_eth(_rng_p)
    ac  = _pick_ac(_rng_p)
