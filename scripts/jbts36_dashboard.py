"""
CCRK / ICK-Activating Kinase — Joubert Syndrome Type 36 (JBTS36) — Autosomal Recessive / CCRK / Cell Cycle-Related Kinase / Ciliary Tip IFT-B Turnaround Regulator (via ICK T-loop Phosphorylation) / No MKS Tier / No SRTD / 14q23.2
===================================================================================================================================================================================================================================================================================
Primary Gene : CCRK (Cell Cycle-Related Kinase; also CCT-2 / PNQLRE; *609478) — 14q23.2;
               ~456 aa; CMGC-family kinase (CDK/MAPK super-family); the master upstream
               activating kinase for ICK (Intestinal Cell Kinase / MAK-related kinase).
               CCRK phosphorylates ICK at Thr157 within the T-loop (activation segment),
               the essential priming step for ICK to regulate IFT-B anterograde-to-retrograde
               switching at the cilia distal tip.

               CCRK protein domain architecture (~456 aa):
               - N-lobe β-sheet and glycine-rich loop (Gly-x-Gly-x-x-Gly; aa 12–17):
                 Classic kinase ATP binding (phosphate-anchoring) loop. Gly14 and Gly17
                 are invariant. Leu78 (N-lobe hydrophobic core) and Ile82 (β3 strand) form
                 hydrophobic contacts with ATP adenine ring. JBTS36 missense Leu78Pro disrupts
                 the N-lobe β-sheet geometry → ATP binding affinity reduced ~70% WT. A-loop
                 phosphorylation at Thr161 (CCRK self-phosphorylation, activating) is
                 disrupted indirectly when N-lobe collapses. Leu78Pro → CCRK kinase activity
                 ~20% WT → ICK Thr157 phosphorylation severely reduced → elongated cilia.

               - Catalytic loop and DFG motif (aa 141–160; DFG Asp141):
                 DFG motif (Asp141-Phe142-Gly143) coordinates Mg²⁺ for ATP γ-phosphate
                 transfer. Arg141 (one position N-terminal to DFG): the invariant catalytic
                 arginine from the catalytic HRD motif (His136-Arg141 in CCRK numbering)
                 positions the substrate Thr157 (ICK T-loop) for phospho-transfer. Arg141Gln
                 (MENA regional cluster, most recurrent JBTS36 variant): eliminates the
                 guanidinium-substrate contact → ICK Thr157 not phosphorylated → ICK inactive
                 → IFT-B anterograde continues without retrograde switch at tip → cilia
                 hyperelongated (~200–400% WT in patient fibroblasts). Moderate-severe JBTS36.

               - Activation segment / T-loop (aa 161–188):
                 Thr161 is the CCRK autophosphorylation site (activating). Biallelic LOF
                 at the activation segment prevents CCRK self-activation. The activation
                 segment also contributes to ICK Thr157 substrate recognition: CCRK DFG
                 docking on ICK activation loop. Asp178His (activation segment mid-loop,
                 South Asian cluster): disrupts substrate-binding geometry → ICK Thr157
                 phosphorylation reduced ~50% WT → moderate JBTS36 with hypomorphic residual.

               - C-terminal regulatory extension (aa 325–456):
                 CCRK lacks a CKS/Cyclin-binding domain (unlike canonical CDKs) but carries
                 a C-terminal disordered extension (aa 325–456) that regulates CCRK nuclear
                 vs. ciliary localisation. The extension contains a ciliary targeting signal
                 (CTS) at aa 380–410 (RVSP motif, aa 393–396) that localises CCRK to the
                 basal body periciliary region. Phe338Val (European): disrupts hydrophobic
                 packing between the kinase core C-lobe (aa 290–325) and the extension linker
                 → CCRK mislocalises from basal body to cytoplasm → ICK at cilia base not
                 phosphorylated → localisation-dependent loss-of-function. Moderate JBTS36.
                 Glu216Lys (pan-ethnic): DFG+2 glycine-proximal, adjacent to activation
                 segment → partial DFG distortion → CCRK activity ~40% WT. Moderate JBTS36.

               CCRK LOF pathway (JBTS36 hypomorphic):
               CCRK biallelic hypomorphic LOF → (1) ICK T-loop (Thr157) not phosphorylated →
               ICK kinase under-activated → (2) Kinesin-II (KIF3A) not phosphorylated at
               ciliary tip by ICK → anterograde IFT-B particles continue reaching tip without
               retrograde switch signal → (3) IFT-B accumulates at cilia tip → cilia
               hyperelongated (~200–400% WT) rather than the normal controlled length (~3–8 µm).
               (4) Hyperelongated cilia: PTCH1 enters and cycles through elongated axoneme →
               GLI2/GLI3 processing shifted toward activator (insufficient conversion to
               GLIR) → SMO-independent partial Hh activation in non-Hh-stimulated cells.
               Net: cerebellar EGL SHH gradient distorted → granule cell migration impaired
               → Molar Tooth Sign (MTS). (5) Connecting cilia of photoreceptors hyperelongated
               → outer segment disk stacking disrupted → rod-cone dystrophy (higher penetrance
               than TZ-gate subtypes, ~28%). (6) Renal tubular primary cilia elongated →
               tubular epithelial cell planar polarity disrupted → nephronophthisis-like (~22%).
               Liver: Biliary primary cilia elongated → cholangiocyte dysfunction mild (~8%).

⚠ NO MKS TIER — ALL JBTS36 LIVEBORN:
   CCRK is a kinase that activates ICK; it does NOT reside in or regulate the transition
   zone (TZ) diffusion barrier (B9-complex, TMEM proteins, nephrocystin module). Biallelic
   null CCRK has not been reported in Meckel-Gruber Syndrome (perinatal lethal). All
   described JBTS36 patients are liveborn with the Molar Tooth Sign. Counselling: 25%
   recurrence risk is JBTS36 (liveborn ciliopathy), NOT the perinatal lethal MKS outcome.
   Distinguishes JBTS36 from JBTS5/CEP290, JBTS28/MKS1, JBTS34/B9D2 (MKS-tier subtypes).

⚠ CILIA HYPERELONGATED (NOT ABSENT, NOT SHORT) — CRITICAL DDx:
   JBTS36/CCRK cilia are HYPERELONGATED (~200–400% WT in patient fibroblasts; ARL13B+
   elongated axoneme on IF). This is mechanistically opposite to:
   - JBTS35/KIAA0753: cilia ABSENT (CP110 cap retained, initiation blocked)
   - JBTS33/CPLANE1: cilia SHORT (~50–70% WT), misoriented
   - JBTS5/CEP290: cilia PRESENT, normal length but cargo leaky (ARL13B+ normal length)
   Elongated cilia on IF (ARL13B staining shows extended red signal beyond normal 3-8 µm)
   are an independent biomarker for CCRK/JBTS36 or ICK-pathway ciliopathy.
   Key DDx co-panel: CCRK + ICK (MAK) — ICK direct LOF produces similar elongated cilia
   (ICK biallelic null → similar to CCRK but with higher retinal penetrance, ~60%).

⚠ CCRK vs ICK — UPSTREAM vs DOWNSTREAM:
   CCRK activates ICK (phosphorylates Thr157 T-loop). Biallelic LOF in either gene produces
   IFT-B accumulation at cilia tips and cilia elongation, but:
   - CCRK (JBTS36): Upstream; ICK protein present but not T-loop–phosphorylated (pT157-ICK
     absent by IF). Mild residual ICK activity may persist (10–20% WT from basal kinase
     activity). Retinal penetrance ~28%, renal ~22%.
   - ICK (MAK; no established JBTS number, but MAK LOF → retinitis pigmentosa dominant
     inheritance for some alleles, AR for others): Downstream; no ICK protein / non-functional
     ICK; higher retinal penetrance (~60%). Co-sequencing CCRK + ICK is recommended.
   Functional test: pT157-ICK immunofluorescence — negative in JBTS36/CCRK, also negative
   in ICK LOF; distinguishes by ICK protein level (present in CCRK LOF, absent in ICK LOF).

⚠ CILIA-LENGTH BIOMARKER — ELONGATED AXONEME ON ARL13B IF:
   Measurement of ARL13B+ cilia length in patient-derived fibroblasts (serum-starved 48h)
   is the diagnostic cellular assay for JBTS36: length >10 µm (vs. WT 3–8 µm) with
   IFT-B tip accumulation (IFT88 or IFT172 IF puncta at distal tips). Complementary:
   anti-pT157-ICK (phospho-ICK activation loop) IF — absent in JBTS36 (CCRK LOF). This
   combination (elongated ARL13B+ cilia + absent pT157-ICK) is pathognomonic for the
   CCRK/ICK pathway. Contrasts with TOGARAM1/JBTS29 (reduced GT335 polyglutamylation,
   short cilia) — an independent turnaround mechanism at a different molecular node.

⚠ GLI3 AND HH GRADIENT DISTORTED (NOT ABOLISHED):
   Unlike JBTS subtypes with absent cilia (JBTS35/KIAA0753) where SHH signalling is
   completely abrogated, CCRK/JBTS36 produces DISTORTED (not abolished) Hh gradient:
   hyperelongated cilia extend PTCH1 cycling and shift GLI3 processing toward activator.
   This explains the higher polydactyly rate (~14%; GLI3 activator excess → limb field
   digit specification) compared with complete Hh-null subtypes (which paradoxically show
   less polydactyly because PCP/hedgehog gradient is so disrupted it fails to specify extra
   digits). Contrast: JBTS35/KIAA0753 polydactyly ~8%; JBTS36/CCRK ~14% (GLI3-activator
   shift). This mechanistic nuance is important for genetic counselling of digit outcomes.
"""

