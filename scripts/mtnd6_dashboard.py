# ── Patient-cohort generator ──────────────────────────────────────────────────
def _make_patients(n=N_PATIENTS, seed=SEED):
    rng = random.Random(seed)
    patients = []

    phenotype_distribution = [
        ("LHON (subacute optic atrophy, near-homoplasmic)", 0.65),
        ("LHON + Dystonia (m.14459G>A dual phenotype)", 0.10),
        ("Leigh Syndrome (isolated CI deficiency, high heteroplasmy)", 0.15),
        ("CPEO + Proximal Myopathy (adult, large deletion)", 0.05),
        ("Oligosymptomatic maternal carrier", 0.05),
    ]

    outcomes = [
        ("Deceased < 2 years (Leigh neonatal)", 0.05),
        ("Deceased 2–10 years (Leigh / LHON+dystonia severe)", 0.07),
        ("Alive — severe visual loss, light perception only (LHON)", 0.20),
        ("Alive — moderate visual loss, legally blind (LHON)", 0.18),
        ("Alive — partial visual recovery ≥20/200 (idebenone / spontaneous)", 0.22),
        ("Alive — near-complete recovery (m.14484T>C spontaneous 50%)", 0.10),
        ("Alive — severe disability, dystonia + visual loss (LHON+dystonia)", 0.08),
        ("Alive — CPEO only, minimal systemic impact (large deletion)", 0.05),
        ("Oligosymptomatic carrier, asymptomatic (surveillance)", 0.05),
    ]

    for i in range(n):
        v_idx = rng.choices(range(len(VARIANTS)), weights=VARIANT_WEIGHTS)[0]
        variant = VARIANTS[v_idx]

        is_lhon = variant["phenotype"].startswith("LHON") and "dystonia" not in variant["phenotype"].lower()
        is_dual = "dystonia" in variant["phenotype"].lower()
        is_leigh = "Leigh" in variant["phenotype"]
        is_deletion = "deletion" in variant["hgvs_mtdna"]
        is_modifier = variant["severity"].startswith("Mild")

        # Heteroplasmy — LHON near-homoplasmic, Leigh high, modifier/deletion variable
        if is_lhon or is_modifier:
            heteroplasmy_blood_pct = round(rng.uniform(88, 100), 1)
        elif is_dual:
            heteroplasmy_blood_pct = round(rng.uniform(60, 95), 1)
        elif is_leigh:
            heteroplasmy_blood_pct = round(rng.uniform(80, 98), 1)
        elif is_deletion:
            heteroplasmy_blood_pct = round(rng.uniform(25, 70), 1)
        else:
            heteroplasmy_blood_pct = round(rng.uniform(50, 95), 1)

        # Phenotype driven by variant + heteroplasmy
        if is_deletion:
            pheno_label = rng.choices(
                ["Pearson Syndrome", "Kearns-Sayre Syndrome (KSS)", "CPEO (adult)"],
                weights=[0.25, 0.45, 0.30],
            )[0]
        elif is_dual:
            pheno_label = rng.choices(
                ["LHON + Dystonia (m.14459G>A dual phenotype)",
                 "Leigh Syndrome (isolated CI deficiency, high heteroplasmy)"],
                weights=[0.70, 0.30],
            )[0]
        elif is_leigh:
            pheno_label = "Leigh Syndrome (isolated CI deficiency, high heteroplasmy)"
        elif is_modifier and heteroplasmy_blood_pct < 92:
            pheno_label = "Oligosymptomatic maternal carrier"
        elif is_lhon or is_modifier:
            pheno_label = "LHON (subacute optic atrophy, near-homoplasmic)"
        else:
            pheno_label = rng.choices(
                [p[0] for p in phenotype_distribution],
                weights=[p[1] for p in phenotype_distribution],
            )[0]

        # CI activity — ND6-LHON has milder CI reduction (unique L-strand topology)
        if "LHON" in pheno_label and "dystonia" not in pheno_label.lower():
            # LHON-specific: partial CI reduction, not severe loss
            ci_activity_pct = round(rng.uniform(55, 78), 1)
        elif "LHON + Dystonia" in pheno_label:
            ci_activity_pct = round(rng.uniform(10, 30), 1)
        elif "Leigh" in pheno_label:
            ci_activity_pct = round(rng.uniform(5, 20), 1)
        elif "CPEO" in pheno_label or "KSS" in pheno_label:
            ci_activity_pct = round(rng.uniform(20, 45), 1)
        elif "Pearson" in pheno_label:
            ci_activity_pct = round(rng.uniform(8, 25), 1)
        else:
            ci_activity_pct = round(rng.uniform(45, 75), 1)

        # Lactic acid — LHON typically normal/mildly elevated; Leigh elevated
        if "LHON" in pheno_label and "dystonia" not in pheno_label.lower():
            lactic_acid = round(rng.uniform(1.2, 3.5), 1)
        elif "Leigh" in pheno_label or "LHON + Dystonia" in pheno_label:
            lactic_acid = round(rng.uniform(5.0, 18.0), 1)
        elif "CPEO" in pheno_label or "KSS" in pheno_label:
            lactic_acid = round(rng.uniform(2.5, 7.0), 1)
        else:
            lactic_acid = round(rng.uniform(1.0, 3.0), 1)

        # LHON-specific features
        optic_atrophy = rng.random() < (
            0.98 if "LHON" in pheno_label else
            0.60 if "LHON + Dystonia" in pheno_label else 0.10
        )
        sequential_bilateral = rng.random() < (0.97 if optic_atrophy else 0.05)
        peripapillary_telangiectasia = rng.random() < (0.88 if "LHON" in pheno_label and optic_atrophy else 0.10)
        spontaneous_recovery = (
            variant["hgvs_mtdna"] == "m.14484T>C"
            and rng.random() < 0.50
        )
        male_sex = rng.random() < (0.85 if "LHON" in pheno_label else 0.50)
        red_green_color_loss = rng.random() < (0.95 if optic_atrophy else 0.05)

        # Neurological features (Leigh / dystonia)
        dystonia = rng.random() < (
            0.85 if "Dystonia" in pheno_label else
            0.12 if "Leigh" in pheno_label else 0.03
        )
        leigh_mri = rng.random() < (
            0.85 if "Leigh" in pheno_label else
            0.60 if "LHON + Dystonia" in pheno_label else 0.05
        )
        lactic_acidosis = rng.random() < (
            0.95 if "Leigh" in pheno_label else
            0.70 if "LHON + Dystonia" in pheno_label else
            0.08  # LHON - typically normal lactate
        )
        hypotonia = rng.random() < (0.90 if "Leigh" in pheno_label else 0.12)
        dev_delay = rng.random() < (0.92 if "Leigh" in pheno_label else 0.08)
        seizures = rng.random() < (
            0.45 if "Leigh" in pheno_label else
            0.25 if "LHON + Dystonia" in pheno_label else 0.05
        )
        cardiomyopathy = rng.random() < (
            0.35 if "KSS" in pheno_label else
            0.18 if "Leigh" in pheno_label else 0.05
        )
        cpeo = rng.random() < (
            0.65 if "CPEO" in pheno_label or "KSS" in pheno_label else
            0.08 if "LHON" in pheno_label else 0.05
        )
        exercise_intolerance = rng.random() < (
            0.80 if "CPEO" in pheno_label or "KSS" in pheno_label else
            0.35 if "LHON" in pheno_label else 0.25
        )
        rrfs = rng.random() < (
            0.65 if "CPEO" in pheno_label or "KSS" in pheno_label else
            0.12 if "Leigh" in pheno_label else 0.05
        )
        respiratory = rng.random() < (0.58 if "Leigh" in pheno_label else 0.08)
        encephalopathy = rng.random() < (
            0.88 if "Leigh" in pheno_label else
            0.50 if "LHON + Dystonia" in pheno_label else 0.05
        )

        outcome_label = rng.choices(
            [o[0] for o in outcomes], weights=[o[1] for o in outcomes]
        )[0]

        # Onset age: LHON youngest of 3 primary genes (teens); Leigh infantile; CPEO adult
        if "Leigh" in pheno_label:
            onset_weeks = rng.randint(0, 52)
        elif "LHON + Dystonia" in pheno_label:
            onset_weeks = rng.randint(26, 520)
        elif "LHON" in pheno_label:
            # m.14484T>C: youngest onset of 3 primary LHON genes (teens)
            onset_weeks = rng.randint(260, 1040)   # ~5–20 years
        elif "CPEO" in pheno_label or "KSS" in pheno_label or "Pearson" in pheno_label:
            onset_weeks = rng.randint(260, 1560)
        else:
            onset_weeks = rng.randint(1040, 2600)  # oligosymptomatic carrier

        patients.append({
            "patient_id": f"MTND6-{i+1:03d}",
            "phenotype": pheno_label,
            "variant": variant["hgvs_mtdna"],
            "protein_change": variant["protein"],
            "heteroplasmy_blood_pct": heteroplasmy_blood_pct,
            "ci_activity_pct": ci_activity_pct,
            "lactic_acid_mmolL": lactic_acid,
            "onset_weeks": onset_weeks,
            "male_sex": male_sex,
            "optic_atrophy": optic_atrophy,
            "sequential_bilateral": sequential_bilateral,
            "peripapillary_telangiectasia": peripapillary_telangiectasia,
            "red_green_color_loss": red_green_color_loss,
            "spontaneous_visual_recovery": spontaneous_recovery,
            "dystonia": dystonia,
            "leigh_mri": leigh_mri,
            "lactic_acidosis": lactic_acidosis,
            "hypotonia": hypotonia,
            "developmental_delay": dev_delay,
            "seizures": seizures,
            "cardiomyopathy": cardiomyopathy,
            "cpeo": cpeo,
            "exercise_intolerance": exercise_intolerance,
            "ragged_red_fibres": rrfs,
            "respiratory_failure": respiratory,
            "encephalopathy": encephalopathy,
            "outcome": outcome_label,
        })

    return patients


# ── Cohort statistics ─────────────────────────────────────────────────────────
def _cohort_stats(patients):
    n = len(patients)
    pct = lambda key: round(100 * sum(1 for p in patients if p.get(key, False)) / n, 1)
    avg = lambda key: round(sum(p[key] for p in patients) / n, 1)
    lhon_patients = [p for p in patients if "LHON" in p["phenotype"]]
    lhon_n = len(lhon_patients)
    return {
        "optic_atrophy_pct":            pct("optic_atrophy"),
        "sequential_bilateral_pct":     pct("sequential_bilateral"),
        "peripapillary_telangiectasia_pct": pct("peripapillary_telangiectasia"),
        "red_green_color_loss_pct":     pct("red_green_color_loss"),
        "spontaneous_visual_recovery_pct": pct("spontaneous_visual_recovery"),
        "lhon_phenotype_pct":           round(100 * lhon_n / n, 1),
        "dystonia_pct":                 pct("dystonia"),
        "leigh_mri_pct":                pct("leigh_mri"),
        "lactic_acidosis_pct":          pct("lactic_acidosis"),
        "hypotonia_pct":                pct("hypotonia"),
        "developmental_delay_pct":      pct("developmental_delay"),
        "seizures_pct":                 pct("seizures"),
        "cardiomyopathy_pct":           pct("cardiomyopathy"),
        "cpeo_pct":                     pct("cpeo"),
        "exercise_intolerance_pct":     pct("exercise_intolerance"),
        "ragged_red_fibres_pct":        pct("ragged_red_fibres"),
        "respiratory_failure_pct":      pct("respiratory_failure"),
        "encephalopathy_pct":           pct("encephalopathy"),
        "avg_ci_activity_pct":          avg("ci_activity_pct"),
        "avg_lactic_acid_mmolL":        avg("lactic_acid_mmolL"),
        "avg_heteroplasmy_blood_pct":   avg("heteroplasmy_blood_pct"),
        "deceased_pct": round(
            100 * sum(1 for p in patients if "Deceased" in p["outcome"]) / n, 1
        ),
    }


