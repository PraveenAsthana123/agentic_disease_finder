"""
Alström Syndrome (ALMS1)
================================================================================
Gene       : ALMS1 (Alström Syndrome Protein 1)
Chromosome : 2p13.1
OMIM Gene  : *606844
OMIM Dis.  : #203800 (Alström Syndrome)
Inheritance: Autosomal Recessive — biallelic loss-of-function (LOF); consanguinity
             common; ~1/1,000,000 prevalence worldwide; rare panethnic ciliopathy

Mechanism
---------
ALMS1 encodes a 4169-amino-acid large centrosomal/basal body protein that localises
to primary cilia and centrosomes and is expressed in photoreceptors, cochlear hair
cells, cardiomyocytes, adipocytes, renal tubular cells, and hepatocytes.

ALMS1 protein function:
  • Structural component of the ciliary basal body and centrosome
  • Regulates primary cilia formation, trafficking, and signalling
  • Critical for ciliary-mediated signal transduction:
    hedgehog pathway, IGF-1 receptor, leptin receptor, insulin receptor
  • Maintains photoreceptor outer segment structure
  • Required for cochlear hair cell ciliary integrity

ALMS1 biallelic LOF → ciliary dysfunction / ciliopathy →
  • Photoreceptors: cone-rod dystrophy → nyctalopia → progressive blindness
    (NOT optic atrophy — distinguishes from Wolfram)
  • Cochlear hair cells: sensorineural hearing loss (progressive)
  • Cardiomyocytes: dilated cardiomyopathy (DCM) — infantile/childhood onset
    (life-threatening; 60% infantile; some resolve; recurrence possible)
  • Adipocytes: hyperphagia + leptin resistance + insulin resistance → truncal obesity
  • Pancreatic beta-cells: insulin resistance (NOT beta-cell apoptosis);
    C-peptide PRESERVED/HIGH (hyperinsulinism) — contrasts with Wolfram/MODY10
  • Renal tubules: progressive nephropathy / CKD (tubular dysfunction)
  • Hepatocytes: NASH/NAFLD → hepatic fibrosis → cirrhosis (30–40%)
  • Pulmonary: interstitial fibrosis (30% adults)
  • Gonadal: male azoospermia (testicular atrophy); female PCOS / irregular menses
  • Growth: short stature (GH insensitivity via ciliary IGF-1 receptor signalling)
  • Skeletal: scoliosis; kyphosis

This makes Alström a ciliopathy: the SAME primary cilia dysfunction simultaneously
damages MULTIPLE organ systems with characteristic temporal onset patterns.

Multi-organ Temporal Pattern (approximate)
-------------------------------------------
1. Dilated Cardiomyopathy (DCM): ~0.3–2 yr (infant; life-threatening; some resolve)
2. Nyctalopia / cone-rod dystrophy: early infancy (nystagmus; photophobia; <2 yr)
3. Sensorineural Hearing Loss (SNHL): childhood (< 10 yr; bilateral; progressive)
4. Obesity / hyperphagia: early childhood (truncal; marked; leptin resistance)
5. Hyperinsulinism / impaired fasting glucose: childhood/adolescence
6. Type 2-like diabetes: adolescence–adult (mean ~16 yr; insulin resistance)
7. Renal nephropathy / CKD: adult (progressive; ESRD 30s–40s)
8. Hepatic NAFLD/NASH / fibrosis: adult (30–40%; cirrhosis possible)
9. Pulmonary fibrosis: adult (30%)
10. Hypertriglyceridaemia (> 5 mmol/L): adolescence onward

Key Clinical Features
---------------------
• Retinal: cone-rod dystrophy (nystagmus + photophobia < 2 yr); ERG flat early;
  progressive blindness by 2nd decade; NOT optic atrophy (distinguishes from Wolfram)
• SNHL: bilateral sensorineural; cochlear hair cell ciliary dysfunction; progressive
• DCM: infantile-onset (60%); life-threatening; some episodes resolve with recurrence
• Obesity: truncal hyperphagia; BMI 30–52; leptin resistance; adipose ciliopathy
• Diabetes: T2D-like insulin resistance; C-peptide HIGH (hyperinsulinism); NOT autoimmune;
  metformin + GLP-1RA appropriate (NOT SU as primary — secretory defect absent)
• Renal: tubular nephropathy → CKD → ESRD (30s–40s) in severe cases
• Hepatic: NAFLD/NASH common (35%); fibrosis (22%); cirrhosis (11%)
• Pulmonary: interstitial fibrosis (30% adults)
• Hypertriglyceridaemia: > 5 mmol/L; atherogenic dyslipidaemia
• Male infertility: azoospermia (testicular atrophy; primary hypogonadism)
• Female: PCOS; oligomenorrhoea; polycystic ovaries (hormonal imaging)
• Short stature: GH insensitivity (ciliary IGF-1 signalling impaired)
• Scoliosis: structural spinal deformity in majority

Key Mutations (ALMS1 biallelic LOF)
-------------------------------------
* p.Arg3444* (c.10330C>T): truncating; common European; exon 16 — most frequent European
* p.Gln2051* (c.6151C>T): truncating; exon 8; British/European founder
* p.Ala2172Ser (c.6514G>A): missense; ciliary targeting domain; European
* c.10775+1G>A: splice site; intron 16; European
* p.Leu1521fs (c.4561delC): frameshift; exon 8; pan-ethnic
* p.Gly3461Arg (c.10381G>A): missense; C-terminal; North African
* Compound_heterozygous_ALMS1: most common European pattern (one truncating + one missense)
* Exon16_splice_compound: splice site + frameshift compound heterozygous

Diagnostics
-----------
• ALMS1 biallelic sequencing: full coding region; all 23 exons; hotspot exons 8 + 16
• CNV array / MLPA: for large deletions/duplications
• ERG (electroretinogram): cone-rod dystrophy pattern — cone amplitude reduced early
• Echocardiography: DCM screening in infancy + annually; EF < 50% = persistent DCM
• Audiometry: pure-tone audiometry (progressive bilateral SNHL)
• Renal: urine microalbumin; serum creatinine; eGFR; renal USS
• Liver: LFTs; GGT; USS + FibroScan (hepatic steatosis/fibrosis grading)
• Metabolic: fasting glucose; HbA1c; fasting insulin; C-peptide (HIGH); OGTT; TG
• Hormonal: IGF-1 (low); testosterone/FSH/LH (male); pelvic USS (female PCOS)
• Pulmonary: spirometry; HRCT chest (interstitial fibrosis screening in adults)

Management (multi-system; no disease-modifying Rx as of 2026)
--------------------------------------------------------------
• DCM: standard HF therapy (ACE-I/ARB, beta-blocker, diuretics); cardiology review
• Retinal: ERG + visual acuity annually; low-vision aids; orientation/mobility training
• SNHL: hearing aids; cochlear implant considered (MRI compatibility check first)
• Diabetes: metformin first-line; GLP-1RA (addresses insulin resistance + weight);
  SGLT2i (renal/hepatic benefits); insulin if late-stage beta-cell exhaustion
• Obesity: multidisciplinary obesity management; bariatric surgery data limited
• Renal: nephropathy monitoring; BP control (ACE-I/ARB); dialysis/transplant for ESRD
• Hepatic: NAFLD management; alcohol abstinence; fibroscan surveillance
• Pulmonary: spirometry annually; pulmonary fibrosis — antifibrotic agents (pirfenidone)
• Hypertriglyceridaemia: fibrates; omega-3; statin (if hepatic function allows)
• Genetic counselling: AR — 25% sibling risk; consanguinity counselling
• Registry: Alström Syndrome International (ASI) registry — critical for natural history

Comparison with Wolfram Syndrome (WFS1): see get_definitions()

Cohort: 40 patients, seed=331.
"""

