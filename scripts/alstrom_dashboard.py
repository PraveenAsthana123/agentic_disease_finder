# ---------------------------------------------------------------------------
# Cohort builder
# ---------------------------------------------------------------------------

def _build_cohort() -> list:
    rng = random.Random(_SEED)

    def wchoice(choices, weights):
        return rng.choices(choices, weights=weights, k=1)[0]

    cohort = []
    for i in range(_COHORT_SIZE):
        mutation = wchoice(_MUTATIONS, _MUTATION_WEIGHTS)
        ethnicity = wchoice(_ETHNICITIES, _ETHNICITY_WEIGHTS)
        cardiac = wchoice(_CARDIAC_STATUS, _CARDIAC_WEIGHTS)
        retinal = wchoice(_RETINAL_STATUS, _RETINAL_WEIGHTS)
        hearing = wchoice(_HEARING_STATUS, _HEARING_WEIGHTS)
        diabetes_status = wchoice(_DIABETES_STATUS, _DIABETES_WEIGHTS)
        renal = wchoice(_RENAL_STATUS, _RENAL_WEIGHTS)
        hepatic = wchoice(_HEPATIC_STATUS, _HEPATIC_WEIGHTS)
        prior_misdiag = wchoice(_MISDIAGNOSES, _MISDIAG_WEIGHTS)

        # Diabetes onset: mean ~16 yr (range 6–35 yr); insulin resistance T2D-like
        dm_onset = round(rng.gauss(16.0, 5.5), 1)
        dm_onset = max(6.0, min(35.0, dm_onset))
        has_dm = diabetes_status != "Hyperinsulinism only (pre-DM; impaired fasting glucose)"

        # Cardiomyopathy onset: mean ~1.5 yr (range 0.3–10 yr)
        has_dcm = cardiac != "No DCM (ever)"
        dcm_onset = None
        if has_dcm:
            dcm_onset = round(rng.gauss(1.5, 1.8), 1)
            dcm_onset = max(0.3, min(10.0, dcm_onset))

        # HbA1c: T2D-like insulin resistance; mean ~8.5%, range 6.5–13.5%
        if has_dm:
            hba1c = round(rng.gauss(8.5, 1.4), 1)
            hba1c = max(6.5, min(13.5, hba1c))
        else:
            hba1c = round(rng.gauss(6.0, 0.3), 1)
            hba1c = max(5.5, min(6.4, hba1c))

        # C-peptide: PRESERVED/HIGH (hyperinsulinism / insulin resistance)
        # Mean ~1.8 nmol/L; much higher than Wolfram (<0.35) or MODY10 (<0.5)
        c_pep = round(rng.gauss(1.8, 0.5), 2)
        c_pep = max(0.9, min(3.8, c_pep))
        # Slightly lower if long-duration DM (some beta-cell exhaustion)
        if diabetes_status == "Type 2-like DM requiring insulin (long-duration, beta-cell exhaustion)":
            c_pep = round(max(0.6, c_pep - rng.gauss(0.4, 0.15)), 2)

        # BMI: obese truncal; mean ~34 kg/m² (range 25–52)
        bmi = round(rng.gauss(34.0, 5.0), 1)
        bmi = max(25.0, min(52.0, bmi))

        # Current age
        disease_dur = round(rng.gauss(10.0, 5.5), 1)
        disease_dur = max(0.5, min(35.0, disease_dur))
        current_age = round(max(5.0, dm_onset + disease_dur + rng.gauss(0, 1.5)), 1)
        current_age = min(55.0, current_age)

        # Triglycerides (mmol/L): hypertriglyceridaemia common
        tg = round(rng.gauss(6.2, 2.0), 1)
        tg = max(1.5, min(15.0, tg))

        # Pulmonary fibrosis (30% adults)
        pulmonary_fibrosis = rng.random() < 0.30

        # Male infertility / Female PCOS (assign sex randomly; ~50/50)
        is_male = rng.random() < 0.50
        azoospermia = is_male and rng.random() < 0.70
        pcos = (not is_male) and rng.random() < 0.65

        # Consanguinity (AR; common in Alström)
        consanguinity = rng.random() < 0.32

        # Family history (sibling or relative with Alström)
        family_hx = rng.random() < 0.22

        # DKA at DM diagnosis: RARE (insulin resistance pattern)
        dka_at_dx = rng.random() < 0.06

        # Short stature
        short_stature = rng.random() < 0.68

        # Scoliosis
        scoliosis = rng.random() < 0.45

        cohort.append({
            "id": i + 1,
            "mutation": mutation,
            "ethnicity": ethnicity,
            "cardiac_status": cardiac,
            "retinal_status": retinal,
            "hearing_status": hearing,
            "diabetes_status": diabetes_status,
            "renal_status": renal,
            "hepatic_status": hepatic,
            "prior_misdiagnosis": prior_misdiag,
            "dm_onset_yr": dm_onset,
            "dcm_onset_yr": dcm_onset,
            "has_dcm": has_dcm,
            "has_dm": has_dm,
            "hba1c": hba1c,
            "c_peptide_nmol_L": c_pep,
            "c_peptide_label": "Preserved/High (hyperinsulinism / insulin resistance)",
            "bmi": bmi,
            "triglycerides_mmol_L": tg,
            "disease_duration_yr": disease_dur,
            "current_age_yr": current_age,
            "pulmonary_fibrosis": pulmonary_fibrosis,
            "is_male": is_male,
            "azoospermia": azoospermia,
            "pcos": pcos,
            "consanguinity": consanguinity,
            "family_hx": family_hx,
            "dka_at_dx": dka_at_dx,
            "short_stature": short_stature,
            "scoliosis": scoliosis,
            "antibody_negative": True,  # always — not autoimmune
        })
    return cohort


