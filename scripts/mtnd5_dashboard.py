# ── Patient-cohort generator ──────────────────────────────────────────────────
def _make_patients(n=40, seed=SEED):
    rng = random.Random(seed)
    patients = []

    phenotype_distribution = [
        ("Neonatal Leigh (severe CI deficiency, >90% heteroplasmy)", 0.18),
        ("Infantile Leigh Syndrome", 0.30),
        ("Leigh/MELAS Overlap (stroke-like episodes)", 0.25),
        ("CPEO + Proximal Myopathy (adult-onset)", 0.15),
        ("Oligosymptomatic / Maternal carrier", 0.12),
    ]

    outcomes = [
        ("Deceased < 2 years", 0.12),
        ("Deceased 2–5 years", 0.10),
        ("Alive — severe disability, ventilator-dependent", 0.18),
        ("Alive — moderate disability, ambulatory with aids", 0.25),
        ("Alive — mild disability, independent", 0.20),
        ("Alive — CPEO only, minimal systemic impact", 0.15),
    ]

    for i in range(n):
        v_idx = rng.choices(range(len(VARIANTS)), weights=VARIANT_WEIGHTS)[0]
        variant = VARIANTS[v_idx]

        # Heteroplasmy (blood; muscle may be 10–20 ppts higher)
        if variant["severity"] == "Mild–Moderate":
            heteroplasmy_blood_pct = round(rng.uniform(35, 65), 1)
        elif variant["severity"] == "Moderate–Severe":
            heteroplasmy_blood_pct = round(rng.uniform(60, 88), 1)
        elif variant["severity"] == "Variable":
            heteroplasmy_blood_pct = round(rng.uniform(25, 75), 1)
        else:  # Severe / Neonatal lethal
            heteroplasmy_blood_pct = round(rng.uniform(78, 98), 1)

        # Phenotype driven by heteroplasmy + variant
        if variant["phenotype"] == "CPEO + myopathy (adult-onset)":
            pheno_label = "CPEO + Proximal Myopathy (adult-onset)"
        elif variant["phenotype"] == "Pearson / KSS / CPEO":
            pheno_label = rng.choices(
                ["Pearson Syndrome", "Kearns-Sayre Syndrome", "CPEO (adult)"],
                weights=[0.3, 0.4, 0.3],
            )[0]
        elif heteroplasmy_blood_pct > 85:
            pheno_label = rng.choices(
                [p[0] for p in phenotype_distribution[:3]],
                weights=[0.40, 0.40, 0.20],
            )[0]
        elif heteroplasmy_blood_pct > 65:
            pheno_label = rng.choices(
                [p[0] for p in phenotype_distribution[1:4]],
                weights=[0.40, 0.40, 0.20],
            )[0]
        else:
            pheno_label = rng.choices(
                [p[0] for p in phenotype_distribution[2:]],
                weights=[0.30, 0.35, 0.35],
            )[0]

        # CI activity (% of normal reference)
        if "CPEO" in pheno_label or "Oligosymptomatic" in pheno_label:
            ci_activity_pct = round(rng.uniform(18, 42), 1)
        elif "Overlap" in pheno_label:
            ci_activity_pct = round(rng.uniform(8, 22), 1)
        elif "Neonatal" in pheno_label:
            ci_activity_pct = round(rng.uniform(3, 10), 1)
        else:
            ci_activity_pct = round(rng.uniform(6, 20), 1)

        lactic_acid = (
            round(rng.uniform(7.0, 22.0), 1) if ci_activity_pct < 12
            else round(rng.uniform(3.5, 12.0), 1)
        )

        # Phenotype flags
        leigh_mri = rng.random() < (0.88 if "Leigh" in pheno_label else
                                     0.45 if "Overlap" in pheno_label else 0.08)
        stroke_like = rng.random() < (0.42 if "Overlap" in pheno_label else 0.05)
        lactic_acidosis = rng.random() < (0.95 if "Leigh" in pheno_label or "Neonatal" in pheno_label
                                           else 0.65)
        hypotonia = rng.random() < (0.92 if "Leigh" in pheno_label or "Neonatal" in pheno_label
                                     else 0.40)
        dev_delay = rng.random() < (0.95 if "Leigh" in pheno_label or "Neonatal" in pheno_label
                                     else 0.30)
        seizures = rng.random() < (0.55 if "Overlap" in pheno_label
                                    else 0.45 if "Leigh" in pheno_label else 0.12)
        cpeo = rng.random() < (0.60 if "CPEO" in pheno_label or "KSS" in pheno_label
                                else 0.12 if "Overlap" in pheno_label else 0.05)
        ptosis = rng.random() < (0.75 if cpeo else 0.08)
        exercise_intolerance = rng.random() < (0.80 if "CPEO" in pheno_label
                                                else 0.65 if "Overlap" in pheno_label else 0.30)
        hearing_loss = rng.random() < (0.55 if "Overlap" in pheno_label
                                        else 0.40 if "CPEO" in pheno_label else 0.18)
        cardiomyopathy = rng.random() < (0.35 if "KSS" in pheno_label
                                          else 0.22 if "Leigh" in pheno_label else 0.08)
        respiratory = rng.random() < (0.62 if "Neonatal" in pheno_label or "Leigh" in pheno_label
                                       else 0.15)
        rrfs = rng.random() < (0.65 if "CPEO" in pheno_label or "KSS" in pheno_label
                                else 0.30 if "Overlap" in pheno_label else 0.08)
        encephalopathy = rng.random() < (0.85 if "Leigh" in pheno_label or "Overlap" in pheno_label
                                          else 0.12)
        spasticity = rng.random() < (0.38 if "Leigh" in pheno_label else 0.05)

        outcome_label = rng.choices(
            [o[0] for o in outcomes], weights=[o[1] for o in outcomes]
        )[0]

        # Onset age
        if "Neonatal" in pheno_label:
            onset_weeks = rng.randint(0, 3)
        elif "Infantile Leigh" in pheno_label:
            onset_weeks = rng.randint(4, 52)
        elif "Overlap" in pheno_label:
            onset_weeks = rng.randint(52, 260)
        elif "CPEO" in pheno_label or "KSS" in pheno_label:
            onset_weeks = rng.randint(260, 1040)
        else:
            onset_weeks = rng.randint(520, 2080)

        patients.append({
            "patient_id": f"MTND5-{i+1:03d}",
            "phenotype": pheno_label,
            "variant": variant["hgvs_mtdna"],
            "protein_change": variant["protein"],
            "heteroplasmy_blood_pct": heteroplasmy_blood_pct,
            "ci_activity_pct": ci_activity_pct,
            "lactic_acid_mmolL": lactic_acid,
            "onset_weeks": onset_weeks,
            "leigh_mri": leigh_mri,
            "stroke_like_episodes": stroke_like,
            "lactic_acidosis": lactic_acidosis,
            "hypotonia": hypotonia,
            "developmental_delay": dev_delay,
            "seizures": seizures,
            "cpeo": cpeo,
            "ptosis": ptosis,
            "exercise_intolerance": exercise_intolerance,
            "sensorineural_hearing_loss": hearing_loss,
            "cardiomyopathy": cardiomyopathy,
            "respiratory_failure": respiratory,
            "ragged_red_fibres": rrfs,
            "encephalopathy": encephalopathy,
            "spasticity": spasticity,
            "outcome": outcome_label,
        })

    return patients


# ── Cohort statistics ─────────────────────────────────────────────────────────
def _cohort_stats(patients):
    n = len(patients)
    pct = lambda key: round(100 * sum(1 for p in patients if p.get(key, False)) / n, 1)
    avg = lambda key: round(sum(p[key] for p in patients) / n, 1)
    return {
        "leigh_mri_pct":               pct("leigh_mri"),
        "stroke_like_pct":             pct("stroke_like_episodes"),
        "lactic_acidosis_pct":         pct("lactic_acidosis"),
        "hypotonia_pct":               pct("hypotonia"),
        "developmental_delay_pct":     pct("developmental_delay"),
        "seizures_pct":                pct("seizures"),
        "cpeo_pct":                    pct("cpeo"),
        "ptosis_pct":                  pct("ptosis"),
        "exercise_intolerance_pct":    pct("exercise_intolerance"),
        "hearing_loss_pct":            pct("sensorineural_hearing_loss"),
        "cardiomyopathy_pct":          pct("cardiomyopathy"),
        "respiratory_failure_pct":     pct("respiratory_failure"),
        "ragged_red_fibres_pct":       pct("ragged_red_fibres"),
        "encephalopathy_pct":          pct("encephalopathy"),
        "spasticity_pct":              pct("spasticity"),
        "avg_ci_activity_pct":         avg("ci_activity_pct"),
        "avg_lactic_acid_mmolL":       avg("lactic_acid_mmolL"),
        "avg_heteroplasmy_blood_pct":  avg("heteroplasmy_blood_pct"),
        "deceased_pct": round(
            100 * sum(1 for p in patients if "Deceased" in p["outcome"]) / n, 1
        ),
    }


