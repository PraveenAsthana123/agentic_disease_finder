# ── Patient-cohort generator ──────────────────────────────────────────────────
def _make_patients(n=N_PATIENTS, seed=SEED):
    rng = random.Random(seed)
    patients = []

    phenotype_distribution = [
        ("Leigh Syndrome (isolated CI deficiency, high heteroplasmy)", 0.38),
        ("Leigh/MELAS-like Overlap (high heteroplasmy, stroke-like episodes)", 0.27),
        ("Exercise Intolerance Myopathy (moderate CI, adult onset)", 0.18),
        ("KSS/CPEO (large deletion syndrome)", 0.10),
        ("Pearson Syndrome (infantile deletion)", 0.07),
    ]

    outcomes = [
        ("Deceased < 2 years (Leigh neonatal severe)", 0.10),
        ("Deceased 2–10 years (Leigh / Leigh-MELAS severe)", 0.10),
        ("Alive — Leigh active, severe disability (Leigh/MELAS)", 0.14),
        ("Alive — Leigh stable, supported (Leigh/MELAS)", 0.12),
        ("Alive — MELAS-like, episodic, managed", 0.10),
        ("Alive — exercise intolerance, managed (moderate CI)", 0.18),
        ("Alive — CPEO only, minimal systemic impact (large deletion)", 0.12),
        ("Alive — KSS, pacemaker, managed", 0.08),
        ("Alive — Pearson, transfusion-dependent or remission", 0.06),
    ]

    for i in range(n):
        v_idx = rng.choices(range(len(VARIANTS)), weights=VARIANT_WEIGHTS)[0]
        variant = VARIANTS[v_idx]

        is_ser45pro = variant["hgvs_mtdna"] == "m.10191T>C"
        is_ala47thr = variant["hgvs_mtdna"] == "m.10197G>A"
        is_gly36ser = variant["hgvs_mtdna"] == "m.10158T>C"
        is_exercise = variant["hgvs_mtdna"] == "m.10218T>C"
        is_deletion = "deletion" in variant["hgvs_mtdna"]

        # Heteroplasmy — Leigh high, Exercise moderate, Deletion variable
        if is_exercise:
            heteroplasmy_blood_pct = round(rng.uniform(48, 75), 1)
        elif is_ser45pro or is_ala47thr:
            heteroplasmy_blood_pct = round(rng.uniform(68, 99), 1)
        elif is_gly36ser:
            heteroplasmy_blood_pct = round(rng.uniform(75, 100), 1)
        elif is_deletion:
            heteroplasmy_blood_pct = round(rng.uniform(18, 62), 1)
        else:
            heteroplasmy_blood_pct = round(rng.uniform(55, 95), 1)

        # Phenotype label
        if is_deletion:
            pheno_label = rng.choices(
                ["Pearson Syndrome (infantile deletion)",
                 "Kearns-Sayre Syndrome (KSS)",
                 "CPEO (adult onset)"],
                weights=[0.20, 0.50, 0.30],
            )[0]
        elif is_ser45pro:
            pheno_label = rng.choices(
                ["Leigh/MELAS-like Overlap (high heteroplasmy, stroke-like episodes)",
                 "Leigh Syndrome (isolated CI deficiency, high heteroplasmy)"],
                weights=[0.65, 0.35],
            )[0]
        elif is_ala47thr:
            pheno_label = rng.choices(
                ["Leigh Syndrome (isolated CI deficiency, high heteroplasmy)",
                 "Leigh/MELAS-like Overlap (high heteroplasmy, stroke-like episodes)"],
                weights=[0.55, 0.45],
            )[0]
        elif is_gly36ser:
            pheno_label = "Leigh Syndrome (isolated CI deficiency, high heteroplasmy)"
        elif is_exercise and heteroplasmy_blood_pct > 73:
            pheno_label = rng.choices(
                ["Leigh Syndrome (isolated CI deficiency, high heteroplasmy)",
                 "Exercise Intolerance Myopathy (moderate CI, adult onset)"],
                weights=[0.30, 0.70],
            )[0]
        elif is_exercise:
            pheno_label = "Exercise Intolerance Myopathy (moderate CI, adult onset)"
        else:
            pheno_label = rng.choices(
                [p[0] for p in phenotype_distribution],
                weights=[p[1] for p in phenotype_distribution],
            )[0]

        # CI activity
        if "Leigh" in pheno_label and "MELAS" not in pheno_label:
            ci_activity_pct = round(rng.uniform(5, 22), 1)
        elif "MELAS" in pheno_label or "Overlap" in pheno_label:
            ci_activity_pct = round(rng.uniform(8, 26), 1)
        elif "CPEO" in pheno_label or "KSS" in pheno_label:
            ci_activity_pct = round(rng.uniform(22, 48), 1)
        elif "Pearson" in pheno_label:
            ci_activity_pct = round(rng.uniform(10, 32), 1)
