# ── Patient generator ─────────────────────────────────────────────────────────
def _generate_patients(n: int = 40, seed: int = 81) -> list:
    random.seed(seed)
    etiology_choices = [
        ("ADLTE-familial-LRR-missense", "ADLTE-missense", 0.40),
        ("ADLTE-familial-truncating", "ADLTE-truncating", 0.30),
        ("ADLTE-exon-deletion/splice", "ADLTE-deletion", 0.15),
        ("ADLTE-incomplete-penetrance", "ADLTE-non-penetrant", 0.10),
        ("Phenocopy-MTLE-negative-LGI1", "phenocopy", 0.05),
    ]
    pts = []
    for i in range(1, n + 1):
        r = random.random()
        cumulative = 0
        etiology_label = etiology_choices[-1][0]
        etiology_cat = etiology_choices[-1][1]
        for label, cat, prob in etiology_choices:
            cumulative += prob
            if r < cumulative:
                etiology_label = label
                etiology_cat = cat
                break

        is_non_penetrant = etiology_cat == "ADLTE-non-penetrant"
        age_onset = (
            None if is_non_penetrant
            else random.choices(
                [random.randint(5, 10), random.randint(10, 20),
                 random.randint(20, 40), random.randint(40, 60)],
                weights=[0.10, 0.30, 0.50, 0.10],
            )[0]
        )
        seizure_types_present = []
        if not is_non_penetrant:
            if random.random() < 0.80:
                seizure_types_present.append("Focal Aware Auditory")
            if random.random() < 0.50:
                seizure_types_present.append("Focal Impaired Awareness")
            if random.random() < 0.40:
                seizure_types_present.append("FBTCS")
            if random.random() < 0.20:
                seizure_types_present.append("Focal Aware Visual")
            if random.random() < 0.30:
                seizure_types_present.append("Nocturnal Focal")

        seizure_free = (
            True if is_non_penetrant
            else random.random() < 0.68
        )
        drug_resistant = (
            False if is_non_penetrant or seizure_free
            else random.random() < 0.15
        )
        aed_list_options = [
            ["CBZ XR"], ["OXC XR"], ["LTG"], ["LEV"],
            ["CBZ XR", "LEV"], ["OXC XR", "LTG"], ["LTG", "LEV"],
            ["CBZ XR", "LCM"], ["OXC XR", "LEV", "LTG"],
        ]
        aed_list = ["None (non-penetrant)" if is_non_penetrant else random.choice(aed_list_options)]

        hla_b1502_tested = random.random() < 0.82
        hla_b1502_pos = hla_b1502_tested and random.random() < 0.07  # ~7% Asian ancestry in cohort
        polg_done = random.random() < 0.75
        siadh_event = not is_non_penetrant and random.random() < 0.12  # ~12% SIADH on CBZ/OXC

        sex = random.choice(["M", "F"])
        vppp_enrolled = sex == "F" and any("VPA" in str(a) for a in aed_list) and random.random() < 0.90
        catamenial = sex == "F" and not is_non_penetrant and random.random() < 0.20
        family_history = random.random() < 0.85
        auditory_trigger = not is_non_penetrant and random.random() < 0.75
        fbtcs = "FBTCS" in seizure_types_present
        mri_normal = random.random() < 0.90

        pts.append({
            "id": f"LGI1-{i:03d}",
            "etiology": etiology_label,
            "etiology_cat": etiology_cat,
            "age_onset": age_onset,
            "sex": sex,
            "seizure_free": seizure_free,
            "drug_resistant": drug_resistant,
            "seizure_types": seizure_types_present,
            "aed_current": aed_list[0],
            "hla_b1502_tested": hla_b1502_tested,
            "hla_b1502_pos": hla_b1502_pos,
            "polg_done": polg_done,
            "siadh_event": siadh_event,
            "vppp_enrolled": vppp_enrolled,
            "catamenial": catamenial,
            "family_history": family_history,
            "auditory_trigger": auditory_trigger,
            "fbtcs": fbtcs,
            "mri_normal": mri_normal,
            "non_penetrant": is_non_penetrant,
        })
    return pts


