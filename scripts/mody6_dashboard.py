    patients = _generate_cohort()

    # Variant distribution
    var_dist: dict = {}
    for p in patients:
        var_dist[p["variant"]] = var_dist.get(p["variant"], 0) + 1

    # HbA1c tiers
    hba1c_tiers = {"<6.5%": 0, "6.5–7.4%": 0, "7.5–8.4%": 0, "≥8.5%": 0}
    for p in patients:
        h = p["hba1c_percent"]
        if h < 6.5:
            hba1c_tiers["<6.5%"] += 1
        elif h < 7.5:
            hba1c_tiers["6.5–7.4%"] += 1
        elif h < 8.5:
            hba1c_tiers["7.5–8.4%"] += 1
        else:
            hba1c_tiers["≥8.5%"] += 1

