"""
MODY6 — NEUROD1-MODY / BETA2-MODY (Maturity-Onset Diabetes of the Young Type 6)
==================================================================================
Gene       : NEUROD1 (Neurogenic Differentiation 1) — alias BETA2
Chromosome : 2q31.3
OMIM Gene  : *601724
OMIM Dis.  : #606394  (MODY6)
Inheritance: Autosomal Dominant (heterozygous LOF → MODY6)
Prevalence : ~1–2% of all MODY (rare; underdiagnosed; not in oldest MODY panels)

Mechanism
---------
NEUROD1/BETA2 is a basic helix-loop-helix (bHLH) transcription factor.
It dimerizes with ubiquitous E-proteins (E12/E47) and binds E-box elements
(CANNTG) in the insulin gene promoter and other beta-cell gene promoters.

Key transcriptional role:
  - Binds insulin promoter E1 (CANNTG) E-box elements
  - Cooperates with PDX1 (MODY4) and MafA to achieve full INS transcription
  - Also drives: GLP1R, SLC30A8 (ZnT8), and neuronal survival genes
  - Required for cerebellar granule neuron survival and inner ear hair cell
    development (explains neurological spectrum in severe/homozygous cases)

Heterozygous LOF → MODY6: single NEUROD1 copy insufficient for full beta-cell
INS transcription → impaired GSIS (glucose-stimulated insulin secretion) →
progressive adult-onset diabetes.

MODY6-UNIQUE Features (critical differentiators)
-------------------------------------------------
1. NEUROD1/BETA2 IS A bHLH E-BOX TRANSCRIPTION FACTOR — COOPERATES WITH PDX1:
     PDX1 (MODY4) binds A-box elements; NEUROD1 (MODY6) binds E-box elements —
     they act synergistically on the same insulin promoter. MODY4 and MODY6 are
     mechanistically complementary: both impair INS transcription, but via distinct
     TF families (homeodomain vs bHLH). Identifying the gene distinction is
     diagnostic: MODY4 → PDX1; MODY6 → NEUROD1.

2. NEUROLOGICAL SPECTRUM — UNIQUE AMONG COMMON MODY TYPES:
     NEUROD1 is expressed in the brain (cerebellum, hippocampus, inner ear).
     Heterozygous LOF → pure MODY6 (no neurological features in most).
     Severe LOF or biallelic/compound-het mutations → cerebellar ataxia +
     sensorineural deafness (NEUROD1 required for cerebellar granule neuron
     differentiation and cochlear hair cell development). Screen neurology
     in families with unexplained ataxia + diabetes.

3. R111L — THE FOUNDING MODY6 MUTATION (bHLH DOMAIN MISSENSE):
     Arg111Leu (R111L) missense in the bHLH DNA-binding domain — first reported
     by Malecki MT et al. (Nat Genet 1999). R111 makes direct contact with the
     E-box CANNTG motif. R111L → reduced E-box DNA binding → reduced INS/GCK
     transcription. Also reported in Japanese, Korean, Pacific Island populations
     (founder effect in some Pacific Island families of Asian descent).

4. SULFONYLUREA RESPONSIVE (first-line, like MODY1/MODY3/MODY4):
     MODY6 beta-cells are functionally impaired but PRESENT (unlike MODY5 structural
     atrophy). SU closes K-ATP channels → depolarization → Ca²⁺ influx → insulin
     exocytosis → bypasses transcriptional deficit. ~80–85% response rate.

5. NO RENAL, PANCREATIC, OR EXOCRINE FEATURES:
     NEUROD1 is not expressed in the kidney tubule or pancreatic acini.
     No renal cysts (vs MODY5), no pancreatic atrophy (vs MODY5), no exocrine
     insufficiency (vs MODY5), no renal glycosuria (vs MODY3).

6. NOT IN EARLIEST MODY PANELS — UNDERDIAGNOSED:
     Original MODY panels (pre-2010) targeted HNF1A, HNF4A, GCK, HNF1B.
     NEUROD1 was added to expanded NGS panels later → many MODY6 families
     labelled T1D (antibody-negative) or T2D (older relatives) for years.

7. AUTOANTIBODIES ALWAYS NEGATIVE:
     GADA, ZnT8, IA-2 — all negative. Mandatory pre-requisite: positive
     autoantibodies argue against MODY6 and suggest T1D.

8. PROGRESSIVE HbA1c (NOT STABLE LIKE MODY2):
     Beta-cell failure progresses with duration; HbA1c rises over years.
     Unlike MODY2 (GCK-MODY) where HbA1c is stable at 5.6–7.6% over decades.

9. C-PEPTIDE PRESERVED AT DIAGNOSIS (like MODY1/MODY3/MODY4):
     Functional secretory defect; C-peptide maintained early but falls with
     duration (same pattern as MODY1/MODY3/MODY4, unlike MODY5 where C-pep
     is low/falling at diagnosis due to structural atrophy).

10. ONSET LATE TEENS TO 50s (variable; overlaps MODY1/MODY3/MODY4):
     Slightly later mean onset than MODY3 (mean ~24 yr); overlaps MODY4 (~35 yr).
     Variable penetrance/expressivity within families — some members present >50 yr.

Key Clinical Hallmarks
-----------------------
* Young–adult-onset diabetes (late teens to 50s)
* Strong family history (~75–85% first-degree relative affected)
* Autoantibodies NEGATIVE (GADA, ZnT8, IA-2) — T1D excluded
* C-peptide PRESERVED at diagnosis; falls progressively
* Sulfonylurea first-line: good response (~80–85%), same mechanism as MODY1/3/4
* NO renal cysts, NO pancreatic atrophy, NO renal glycosuria, NO macrosomia
* Neurological alert: rare severe cases → cerebellar ataxia + sensorineural deafness
* R111L (bHLH domain) most common variant; also missense/frameshift throughout gene
* Misdiagnosis: T1D (antibody-negative, young) and T2D (older relatives)
* Progressive beta-cell failure → insulin requirement if disease duration >10–15 yr

Diagnostic Strategy
--------------------
* Suspect MODY6 when: young DM + family history + antibody-negative + C-pep preserved
* HbA1c progressive (not stable → excludes MODY2/GCK)
* No renal cysts/pancreatic atrophy/exocrine features → excludes MODY5
* No renal glycosuria (in most) → MODY3 less likely (though only 50% MODY3 positive)
* No macrosomia/neonatal hyperinsulinism → excludes MODY1
* Neurological features (ataxia + deafness) in family → screen NEUROD1 first
* MODY NGS panel: NEUROD1 must be included (expanded panel, not the oldest 4-gene panel)
* Functional assay: E-box binding (research) — confirms pathogenicity of missense variants

Treatment
----------
* SULFONYLUREA FIRST-LINE (as for MODY1/MODY3/MODY4): ~80–85% response
  - Glibenclamide 2.5–5 mg/day; titrate slowly; hypoglycaemia risk
  - Gliclazide 40–80 mg/day (alternative)
* Diet / lifestyle: adequate in some mild-onset cases
* Insulin: for advanced beta-cell failure or pregnancy
* Pregnancy: switch to insulin (SU crosses placenta)
* Neurological monitoring: annual cerebellar exam if neurological features in family

Comparison: MODY6 vs Other MODY Types
---------------------------------------
Feature              | MODY6 (NEUROD1)       | MODY3 (HNF1A)         | MODY4 (PDX1)
---------------------|------------------------|------------------------|--------------------
Gene                 | NEUROD1 2q31.3         | HNF1A 12q24           | PDX1 13q12.2
TF family            | bHLH (E-box)           | Homeodomain           | Homeodomain
Renal glycosuria     | ABSENT                | PRESENT (50%)         | ABSENT
Renal cysts          | ABSENT                | ABSENT                | ABSENT
Pancreatic atrophy   | ABSENT                | ABSENT                | ABSENT
SU response          | YES (~80–85%)         | YES (85–90%)          | YES (85–90%)
Neurological         | POSSIBLE (severe LOF) | NONE                  | NONE
De-novo              | Rare                  | Rare (<5%)            | Rare
Family history       | ~75–85%               | ~90%                  | ~80–90%
MODY frequency       | ~1–2%                 | ~35%                  | ~1%
Founder variant      | R111L (bHLH domain)   | P291fsinsC            | P63fsdelC

Cohort: 40 patients, seed=313.
"""

import random
import statistics

