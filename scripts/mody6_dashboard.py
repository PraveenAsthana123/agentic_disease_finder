# Internal helpers
# ---------------------------------------------------------------------------

_SEED = 313
_COHORT_SIZE = 40

# NEUROD1 variants — bHLH domain missense + frameshift + splice-site
_VARIANTS = [
    "R111L",                # founding mutation — Malecki 1999, bHLH domain
    "A206V",                # missense — transactivation domain
    "R103W",                # missense — bHLH DNA-binding
    "Q92X",                 # nonsense — bHLH domain
    "G42D",                 # missense — N-terminal activation
    "IVS1+1G>T",            # splice-site (intron 1)
    "L154P",                # missense — helix 2
    "Y242H",                # missense — C-terminal
    "Other_frameshift",     # novel frameshift
    "Other_missense",       # novel missense
    "Splice_other",         # other splice-site
]
_VARIANT_WEIGHTS = [0.25, 0.10, 0.10, 0.08, 0.08, 0.07, 0.07, 0.07, 0.08, 0.06, 0.04]

# Treatment: SU-first, similar to MODY1/MODY3/MODY4
_TREATMENTS = [
    "Sulfonylurea (glibenclamide)",
    "Sulfonylurea (gliclazide)",
    "Diet/lifestyle only",
    "Insulin (basal-bolus)",
    "Insulin (basal-only)",
    "Metformin (adjunct)",
]
_TREATMENT_WEIGHTS = [0.32, 0.22, 0.15, 0.13, 0.09, 0.09]

_MISDIAGNOSES = ["T1D", "T2D", "Prediabetes", "None"]
_MISDIAGNOSIS_WEIGHTS = [0.28, 0.28, 0.14, 0.30]

_SEXES = ["M", "F"]


def _make_patient(seed_val: int) -> dict:
    rng = random.Random(seed_val)
    sex = rng.choices(_SEXES, [0.48, 0.52])[0]
    age = rng.randint(22, 62)
    # MODY6 onset: late teens to 50s; mean ~35 yr (overlaps MODY4)
    dx_age = rng.randint(17, min(age, 54))
    duration = age - dx_age

    # HbA1c: progressive; moderate range; SU-responsive
    hba1c = round(rng.uniform(5.9, 9.8), 1)

    # Fasting glucose: moderate elevation
    fg = round(rng.uniform(5.5, 12.0), 1)

    # C-peptide: PRESERVED early but falls with duration
    baseline_cp = round(rng.uniform(0.48, 1.55), 2)
    duration_penalty = min(duration * 0.021, 0.62)
    c_pep = max(round(baseline_cp - duration_penalty, 2), 0.07)

    variant = rng.choices(_VARIANTS, _VARIANT_WEIGHTS)[0]
    treatment = rng.choices(_TREATMENTS, _TREATMENT_WEIGHTS)[0]
    misdiagnosis = rng.choices(_MISDIAGNOSES, _MISDIAGNOSIS_WEIGHTS)[0]

    # Autoantibodies always negative
    gada = False
    znt8 = False
    ia2 = False

    # Family history: ~80%
    fam_hx = rng.random() < 0.80

    # On SU: check hypoglycaemia episodes
    on_su = "Sulfonylurea" in treatment
    hypo_episodes = rng.randint(0, 3) if on_su else 0

    # SU response: ~82% on SU
    su_responder = on_su and rng.random() < 0.82

    # Neurological features (rare — only in severe LOF families)
    neuro_features = rng.random() < 0.08  # ~8% have cerebellar/hearing features

    return {
        "patient_id": f"MODY6-{seed_val:04d}",
        "age": age,
        "sex": sex,
        "age_at_diagnosis": dx_age,
        "duration_years": duration,
        "hba1c_percent": hba1c,
        "fasting_glucose_mmol": fg,
        "c_peptide_nmol_L": c_pep,
        "variant": variant,
        "current_treatment": treatment,
        "prior_misdiagnosis": misdiagnosis,
        "family_history_positive": fam_hx,
        "gada_positive": gada,
        "znt8_positive": znt8,
        "ia2_positive": ia2,
        "on_sulfonylurea": on_su,
        "su_hypoglycaemia_episodes_last_yr": hypo_episodes,
        "su_responder": su_responder,
        "neurological_features": neuro_features,
        "renal_cysts": False,
        "pancreatic_atrophy_on_imaging": False,
        "exocrine_insufficiency": False,
        "renal_glycosuria": False,
        "macrosomia_at_birth": False,
        "neonatal_hyperinsulinism_history": False,
    }


def _generate_cohort() -> list:
    rng = random.Random(_SEED)
    seeds = [rng.randint(10000, 99999) for _ in range(_COHORT_SIZE)]
    return [_make_patient(s) for s in seeds]


