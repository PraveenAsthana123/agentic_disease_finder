# ── Patient cohort generator (40 patients, seed 715) ──────────────────────────
def _gen_patients(n: int = 40, seed: int = 715) -> list:
    """Generate n realistic TTC19 patients — seeded RNG for reproducibility."""
    local_rng = random.Random(seed)
    phenotypes = [
        ("Spinocerebellar ataxia (SCA-like)", 0.50),
        ("Encephalomyopathy", 0.22),
        ("Psychiatric-predominant", 0.15),
        ("Ovario-leukodystrophy", 0.05),
        ("Neonatal-onset severe", 0.08),
    ]
    sexes = [("M", 0.50), ("F", 0.50)]
    populations = [
        ("European (Italian/Spanish)", 0.45),
        ("Portuguese/Brazilian", 0.15),
        ("South Asian", 0.12),
        ("Middle Eastern", 0.12),
        ("North African", 0.08),
        ("East Asian", 0.04),
        ("Other", 0.04),
    ]
    variants_list = [v["protein"] for v in VARIANTS]
    severity_map = {v["protein"]: v["severity"] for v in VARIANTS}

    patients = []
    for i in range(n):
        local_rng.seed(seed + i * 23 + 7)

        def pick(choices):
            r = local_rng.random()
            cum = 0
            for val, p in choices:
                cum += p
                if r < cum:
                    return val
            return choices[-1][0]

        phenotype = pick(phenotypes)
        sex = pick(sexes)
        population = pick(populations)

        # Age of onset depends on phenotype
        if phenotype == "Neonatal-onset severe":
            onset = local_rng.randint(0, 3)
        elif phenotype == "Psychiatric-predominant":
            onset = local_rng.randint(12, 35)
        elif phenotype == "Ovario-leukodystrophy":
            onset = local_rng.randint(8, 25)
        else:
            onset = local_rng.randint(4, 40)

        # Current age
        progression = local_rng.randint(3, 20)
        current_age = onset + progression

        # CIII activity
        if phenotype == "Neonatal-onset severe":
            ciii_pct = local_rng.randint(1, 7)
        elif phenotype == "Ovario-leukodystrophy":
            ciii_pct = local_rng.randint(5, 20)
        elif phenotype == "Psychiatric-predominant":
            ciii_pct = local_rng.randint(8, 22)
