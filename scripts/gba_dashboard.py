import random

random.seed(42)   # reproducible cohort


# ── cohort generator ───────────────────────────────────────────────────────────

def _patients():
    """Generate a reproducible 40-patient GBA Type 3 cohort.
    Type 3 presents in late infancy / childhood; broad phenotype from 3a (seizure-dominant)
    to 3b (visceral-dominant) to 3c (cardiac-dominant D409H)."""
    subtypes = [
        ("Type 3a (Myoclonic Epilepsy + Dementia)", 0.40, (1.5, 8.0)),
        ("Type 3a (Oculomotor + Mild Seizures)", 0.18, (2.0, 10.0)),
        ("Type 3b (Hepatosplenic-dominant, minimal seizures)", 0.22, (1.0, 6.0)),
        ("Type 3c (D409H Cardiac + Oculomotor)", 0.10, (4.0, 18.0)),
        ("Type 3 Atypical / Unclassified", 0.10, (1.0, 15.0)),
    ]
    counts = [16, 7, 9, 4, 4]   # sums to 40
    patients = []
    pid = 1
    for (sname, _, age_range), cnt in zip(subtypes, counts):
        for _ in range(cnt):
            age = round(random.uniform(*age_range), 1)
            is_3a = "Myoclonic" in sname or "Oculomotor" in sname
            is_3c = "3c" in sname
            seizure = (random.random() < 0.82) if is_3a else (
                random.random() < 0.30 if is_3c else random.random() < 0.55
            )
            patients.append({
                "id": pid,
                "subtype": sname,
                "onset_age": age,
                "seizure": seizure,
                "action_myoclonus": random.random() < 0.75 if is_3a else random.random() < 0.15,
                "horizontal_saccade_palsy": random.random() < 0.88,
                "hepatosplenomegaly": random.random() < (0.55 if is_3c else 0.95),
                "cardiac_valve": random.random() < (0.90 if is_3c else 0.05),
                "drug_resistant": random.random() < 0.55 if seizure else False,
                "on_ert": random.random() < 0.95,
                "on_vpa": random.random() < 0.65 if seizure else False,
                "on_lev": random.random() < 0.52 if seizure else False,
                "on_clonazepam": random.random() < 0.48 if seizure else False,
                "on_ambroxol": random.random() < 0.42,
                "on_miglustat": random.random() < 0.25,
            })
            pid += 1
    return patients


_COHORT = _patients()


