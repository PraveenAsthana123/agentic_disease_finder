# ── HELPERS ───────────────────────────────────────────────────────────────────
def _pct(pts, key):
    n = len(pts)
    if n == 0:
        return 0
    return round(100 * sum(1 for p in pts if p.get(key)) / n)


def _mean(pts, key):
    vals = [p[key] for p in pts if isinstance(p.get(key), (int, float))]
    if not vals:
        return 0
    return round(sum(vals) / len(vals), 1)


