allele_classes = (
    ['null/null'] * 10 +
    ['null/missense (moderate)'] * 18 +
    ['missense/missense (mild)'] * 8 +
    ['hypomorphic (Ala298Val)'] * 4
)
rng.shuffle(allele_classes)

for i in range(N):
    eth  = eth_pool[i]
    acls = allele_classes[i]
    age_dx = rng.randint(1, 36) if acls != 'hypomorphic (Ala298Val)' else rng.randint(3, 72)

    # Phenotype probabilities by allele class
    if acls == 'null/null':
        p_ataxia  = 0.95; p_hypo = 0.95; p_oma = 0.65; p_breath = 0.70
        p_ret = 0.50; p_poly = 0.20; p_renal = 0.45; p_hepatic = 0.20; p_id = 0.85; p_breath2 = 0.70
    elif acls == 'null/missense (moderate)':
        p_ataxia  = 0.88; p_hypo = 0.85; p_oma = 0.55; p_breath = 0.57
        p_ret = 0.35; p_poly = 0.15; p_renal = 0.28; p_hepatic = 0.12; p_id = 0.72; p_breath2 = 0.57
    elif acls == 'missense/missense (mild)':
        p_ataxia  = 0.75; p_hypo = 0.70; p_oma = 0.40; p_breath = 0.40
        p_ret = 0.22; p_poly = 0.10; p_renal = 0.18; p_hepatic = 0.05; p_id = 0.55; p_breath2 = 0.40
    else:  # hypomorphic
        p_ataxia  = 0.60; p_hypo = 0.55; p_oma = 0.25; p_breath = 0.25
        p_ret = 0.15; p_poly = 0.05; p_renal = 0.10; p_hepatic = 0.02; p_id = 0.40; p_breath2 = 0.25

    # Specific allele by ethnicity + class
    if acls == 'null/null':
        if eth == 'European':
            allele = 'Trp623*/Arg847* or c.1430+1G>A'
        else:
            allele = 'Arg847*/Trp623*'
    elif acls == 'null/missense (moderate)':
        if eth in ('Middle Eastern / MENA',):
            allele = 'Arg339Cys/null'
        elif eth == 'South Asian':
            allele = 'Leu506Pro/null'
        else:
            allele = 'Gly347Arg/null'
    elif acls == 'missense/missense (mild)':
        allele = 'Arg339Cys/Gly347Arg or Tyr1112Cys/Leu506Pro'
    else:
        allele = 'Ala298Val/Ala298Val (founder)'

    esrd_age = rng.randint(16, 32) if rng.random() < p_renal else None

    patients.append({
        "id":           f"JBTS11-{i+1:03d}",
        "sex":          rng.choice(["M", "M", "F"]),   # equal sex ratio (AR)
        "ethnicity":    eth,
        "allele_class": acls,
        "allele":       allele,
        "age_dx_yr":    round(age_dx / 12, 1),
        "ataxia":       rng.random() < p_ataxia,
        "hypotonia":    rng.random() < p_hypo,
        "oma":          rng.random() < p_oma,
        "retinal":      rng.random() < p_ret,
        "polydactyly":  rng.random() < p_poly,
        "renal":        rng.random() < p_renal,
        "esrd_age":     esrd_age,
        "hepatic":      rng.random() < p_hepatic,
        "id_":          rng.random() < p_id,
        "breathing":    rng.random() < p_breath2,
    })

# ── aggregate phenotype counts ────────────────────────────────────────────────
