"""
Nephronophthisis Type 15
========================
Primary Gene : CEP164 (*614848) — 11q23.3; 1,460 aa; centrosomal protein at distal
               appendages (transition fibers) of the mother centriole; required for
               ciliogenesis initiation via vesicle docking; phosphorylated by TTBK2
Disease OMIM : #614845 (Nephronophthisis 15 — NPHP15; renal ciliopathy ± Senior-Løken)
Chromosome   : 11q23.3
Inheritance  : Autosomal Recessive (biallelic LOF — truncating and/or missense)
Prevalence   : ~1/300,000–600,000; ~80–100 published families as of 2026

Protein Structure — CEP164 (1,460 aa; distal appendage scaffold protein)
------------------------------------------------------------------------
  • N-terminal coiled-coil region (aa 1–220): oligomerisation; nuclear export signal;
    recruits RABIN8/RAB3IP for Rab8a vesicle priming
  • Distal appendage domain — DAP-I (aa 221–560): SCLT1 interaction; CEP83 binding;
    TTBK2 phosphorylation site (Ser172) for ciliogenesis initiation
  • Central WW-like domain (aa 561–820): NPHP1 and NPHP4 direct interaction;
    bridges distal appendage platform to transition zone NPHP scaffold
  • Distal appendage domain — DAP-II (aa 821–1120): FBF1 interaction; vesicle docking
    surface; Rab8a-GTP recruitment; CP110 removal coordination
  • C-terminal coiled-coil (aa 1121–1460): LRRC45 binding; RPGRIP1L (NPHP8) interaction;
    structural scaffold of the 9-fold symmetric DAP ring

Molecular Mechanism
-------------------
CEP164 is located at the distal appendages (= transition fibers) of the mother centriole —
the innermost ring of the DAP structure closest to the ciliary membrane transition zone:
  1. At G0/G1, TTBK2 phosphorylates CEP164 at Ser172 (DAP-I domain) → activates CEP164
     as a scaffold hub for vesicle-docking machinery
  2. CEP164 recruits RABIN8 (RAB3IP), a Rab8a GEF, to the distal appendage →
     Rab8a-GTP-positive vesicles dock at the CEP164-studded DAP ring
  3. Docked vesicles fuse with the plasma membrane at the ciliary pit →
     CP110/CEP97 capping complex is displaced → basal body uncapping → axoneme elongation
  4. CEP164 also directly binds NPHP1 and NPHP4 (TZ scaffold proteins) at its central
     WW-like domain, physically linking the DAP platform to the TZ gate assembly
  5. CEP164 loss → vesicle-docking arrest → CP110 persists on mother centriole →
     no axoneme nucleation → NPHP15 TIN + corticomedullary cysts → ESRD
  6. CEP164 IS expressed in photoreceptor connecting cilia (unlike ZNF423/NPHP14) →
     retinal dystrophy (rod-cone degeneration) in 35–40% → Senior-Løken Syndrome
  7. CEP164 NOT in nodal cilia at disease-relevant threshold → NO situs inversus
  8. CEP164 NOT in biliary epithelium → NO congenital hepatic fibrosis
  9. Mechanistically DISTINCT from TZ-scaffold NPHP genes (NPHP1/4/8) and DDR-NPHP (NPHP14);
     CEP164 = distal appendage initiator, not a TZ structural component

HALLMARK FEATURES (distinguishing NPHP15 from other NPHP subtypes):
  • DISTAL APPENDAGE (TRANSITION FIBER) NPHP — unique localisation at mother centriole
    distal appendages; ciliogenesis arrest at vesicle-docking / CP110-uncapping step;
    distinct from TZ-scaffold NPHP (NPHP1/4/8/9) and DDR-NPHP (NPHP14).
  • SENIOR-LØKEN SYNDROME (SLS) IN 35–40%: Retinal dystrophy (rod-cone degeneration) +
    NPHP15. ERG flat/extinguished; nystagmus; photophobia; visual loss from infancy/childhood.
    CEP164 expressed in photoreceptor connecting cilia → retinal involvement (unlike NPHP14).
    SLS with LCA-like retinal is the commonest extra-renal feature of NPHP15.
  • NO JOUBERT SYNDROME: CEP164 is NOT a Joubert gene. No Molar Tooth Sign. No cerebellar
    vermis hypoplasia. This is the critical DDx from CEP290 (NPHP6, 40% Joubert) and
    RPGRIP1L (NPHP8, 40% Joubert). Pure renal + retinal = NPHP15 phenotype.
  • NO INTELLECTUAL DISABILITY: CEP164 not expressed in brain neurons at disease threshold.
    Cognitive development normal in NPHP15 — unlike NPHP14/JBTS19 (25–35% ID).
  • NO CHF, NO SITUS: CEP164 absent in biliary epithelium (no CHF), nodal cilia (no situs).
  • ESRD MEDIAN ~13–15yr: TIN + corticomedullary cysts + concentrating defect (polyuria first).
    Small echogenic kidneys on USS. Similar to NPHP1 (~13yr); earlier than NPHP14 (~13–18yr).
  • RENAL TRANSPLANT CURATIVE — NO RECURRENCE: Cell-autonomous distal appendage defect;
    transplanted kidney has normal CEP164 → ciliogenesis normal → no recurrence. Excellent.
  • RETINAL DOES NOT IMPROVE POST-TRANSPLANT: CEP164 defect in photoreceptors is
    cell-autonomous; retinal dystrophy progresses independently of renal outcome.
  • TTBK2 PHOSPHORYLATION TARGET: CEP164 Ser172 is the key TTBK2 substrate at the DAP;
    the only NPHP gene product directly phosphorylated by TTBK2 for ciliogenesis initiation.
  • NPHP1 DIRECT BINDING PARTNER: CEP164 WW-like domain binds NPHP1 directly at the DAP-TZ
    interface; always co-sequence NPHP1 when CEP164 found (digenic CEP164+NPHP1 possible).

Key Differentials:
  NPHP1 (2q13 deletion): NPHP1 MLPA first-line — does NOT detect CEP164 11q23.3.
    NPHP1 has NO retinal involvement (unlike NPHP15 SLS 35–40%). No DAP mechanism.
    ESRD ~13yr (similar to NPHP15 ~13–15yr). NPHP1 deletion most common misdiagnosis.
  SDCCAG8/NPHP10: Similar retinal (rod-cone, 50–60%) + NPHP. NPHP10 has BBS16 overlap
    (obesity, cognitive; ABSENT in NPHP15). NPHP10 is centrosomal/subdistal appendage
    (not transition fiber DAP like NPHP15). No BBS features in NPHP15.
  IQCB1/NPHP5: SLS in ~90% (highest SLS rate among NPHP genes; ABSENT Joubert).
    NPHP5 retinal earlier and more severe than NPHP15. NPHP5 is TZ scaffold not DAP.
    IQCB1 interacts with CEP164 via NPHP1 — NPHP5 on same panel.
  CEP290/NPHP6: Joubert 40% + retinal (LCA-like, 65%) — BOTH absent in NPHP15.
    CEP290 first test on JBTS panels; NPHP15 missed if no Joubert on CEP290-panel.
    No CHF in NPHP15 (unlike TMEM67/NPHP11). No MTS in NPHP15 (unlike CEP290).
  RPGRIP1L/NPHP8: Joubert 40–45% (ABSENT NPHP15), retinal 25–35%, CHF 15–20%. TZ scaffold.
  LCA (non-NPHP genes): GUCY2D, RPE65, AIPL1 — retinal only, NO renal involvement.
    NPHP15 SLS is frequently misdiagnosed as pure LCA when renal not yet symptomatic.
    Annual renal USS + urine osmolality mandatory in ALL LCA patients (rule out SLS/NPHP15).

Treatment:
  • Renal transplant: CURATIVE for NPHP15 renal component; cell-autonomous DAP defect;
    NO recurrence; excellent outcomes; early paediatric nephrology referral mandatory.
  • Conservative CKD: hydration (concentrating defect); EPO; ACEi/ARB; avoid nephrotoxins.
  • Retinal / SLS: Low-vision support; dark adaptation aids; genetic counselling;
    annual ophthalmology ERG; no proven retinal rescue therapy as of 2026.
  • No disease-modifying therapy 2026: TTBK2 kinase activator / CEP164 DAP-stabiliser
    are pre-clinical (zebrafish/mouse models).
"""

