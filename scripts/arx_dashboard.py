def _generate_patients():
    pts = []
    pid = 1
    for etiology, pct in _ETIOLOGY_DIST:
        n = round(40 * pct / 100)
        for i in range(n):
            is_female = ("carrier-female" in etiology or "phenocopy" in etiology) and i == 0
            if is_female:
                name = _FEMALE_NAMES[pid % len(_FEMALE_NAMES)]
                sex = "F"
            else:
                name = _MALE_NAMES[pid % len(_MALE_NAMES)]
                sex = "M"

            ohtahara = "Ohtahara" in etiology or "XLAG" in etiology
            west = "West" in etiology or "ISSX" in etiology
            partington = "Partington" in etiology
            xlag = "XLAG" in etiology
            phenocopy = "phenocopy" in etiology

            onset_months = (
                random.randint(0, 1) if ohtahara or xlag else
                random.randint(3, 12) if west else
                random.randint(6, 36) if partington else
                random.randint(0, 12)
            )
            dre = random.random() < (0.85 if ohtahara or xlag else 0.65 if west else 0.30 if partington else 0.50)
            on_acth = random.random() < (0.70 if west else 0.20)
            on_vgb = random.random() < (0.60 if west else 0.10)
            on_vpa = random.random() < (0.65 if not phenocopy else 0.50)
            on_clb = random.random() < (0.55 if dre else 0.20)
            on_kd = dre and random.random() < 0.45
            polg_tested = "Y" if random.random() < 0.78 else "N"
            day14_eeg = random.random() < 0.72 if (on_acth and west) else None
            spasm_free = (day14_eeg is True) and random.random() < 0.60
            erg_done = "Y" if on_vgb else ("Y" if random.random() < 0.3 else "N")
            lissencephaly = xlag
            agenesis_cc = random.random() < (0.20 if ohtahara else 0.05)
            hyperglycemia_neonatal = xlag and random.random() < 0.70
            hand_dystonia = partington
            genetic_counselling = random.random() < 0.80
            family_carrier_tested = random.random() < 0.65

            pts.append({
                "id": f"ARX-{pid:03d}",
                "name": name,
                "sex": sex,
                "age_y": round(onset_months / 12 + random.uniform(1, 8), 1),
                "onset_months": onset_months,
                "etiology": etiology,
                "ohtahara": ohtahara,
                "west_syndrome": west,
                "partington": partington,
                "xlag": xlag,
                "phenocopy": phenocopy,
                "drug_resistant": dre,
                "on_acth": on_acth,
                "on_vgb": on_vgb,
                "on_vpa": on_vpa,
                "on_clb": on_clb,
                "on_kd": on_kd,
                "polg_tested": polg_tested,
                "day14_eeg_resolved": day14_eeg,
                "spasm_free": spasm_free,
                "erg_done": erg_done,
                "lissencephaly": lissencephaly,
                "agenesis_cc": agenesis_cc,
                "hyperglycemia_neonatal": hyperglycemia_neonatal,
                "hand_dystonia": hand_dystonia,
                "genetic_counselling": genetic_counselling,
                "family_carrier_tested": family_carrier_tested,
                "current_aeds": random.sample(_AEDS, random.randint(1, 3)),
            })
            pid += 1
    return pts


