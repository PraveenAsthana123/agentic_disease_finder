"""
ARX Epilepsy — X-linked DEE / Ohtahara Syndrome / West Syndrome / XLAG / Partington Syndrome
==============================================================================================
40-patient cohort · ARX (Xp21.3) · X-linked hemizygous males (de novo or familial)

ARX BIOLOGY:
ARX (Aristaless-Related Homeobox, Xp21.3) encodes a paired-type homeodomain transcription
factor that is the master regulator of GABAergic interneuron specification and tangential
cortical migration. ARX is critical for:

  (a) Interneuron specification and migration: ARX drives the tangential migration of cortical
      interneurons from the medial ganglionic eminence (MGE) and caudal ganglionic eminence
      (CGE) into the neocortex. LOF → failed tangential migration → interneuron deficit in
      neocortex and hippocampus → severely reduced cortical GABAergic inhibition →
      hyperexcitable cortical networks → neonatal/infantile catastrophic epilepsy.
  (b) Interneuron subtype diversification: ARX is required for differentiation of parvalbumin-
      positive (PV+) fast-spiking interneurons (soma-targeting), calretinin interneurons, and
      neuropeptide Y (NPY) interneurons. These interneurons provide the dominant perisomatic
      inhibitory drive. ARX LOF → selective interneuron loss → failure of feedback and
      feedforward inhibition → synchronous ictal bursting (Ohtahara suppression-burst pattern).
  (c) Pancreatic development (XLAG): ARX is also expressed in pancreatic alpha-cells. XLAG
      (X-linked lissencephaly with ambiguous genitalia) involves ARX truncating variants in or
      before the homeodomain → combined brain malformation (lissencephaly) + genital abnormality
      (ambiguous genitalia in 46,XY males) + severe neonatal epilepsy (Ohtahara-like pattern).
      Neonatal hyperglycemia (pancreatic alpha-cell ARX dependency) is a distinguishing feature.
  (d) Poly-Ala expansions: The most common ARX pathogenic mechanism is polyalanine (poly-Ala)
      tract expansion. ARX protein contains two poly-Ala tracts (Tract 1 at positions 100-112,
      Tract 2 at positions 144-155). Expansion of Tract 1 by ≥4 alanines → West syndrome/ISSX
      (infantile spasm syndrome X-linked); Tract 2 expansion → Partington syndrome (X-linked
      intellectual disability + dystonic hand movements + Moro reflex). Poly-Ala expansions
      cause protein aggregation and nuclear inclusions (distinct from LOF mechanism).

ARX ALLELIC DISORDER SPECTRUM (5 clinical entities):
  1. Ohtahara Syndrome / Severe DEE (25%): Truncating or missense variants in the homeodomain
     of ARX. Neonatal onset suppression-burst EEG → tonic seizures → West syndrome evolution.
     Lissencephaly may or may not be present (XLAG spectrum). Severe NDD, minimal development.
  2. West Syndrome / ISSX — Poly-Ala Tract 1 Expansion (30%): Most common ARX allele.
     GGC repeat expansion → poly-Ala Tract 1 ≥116 alanines. Infantile spasms onset 3-12 months.
     Hypsarrhythmia on EEG. Often transitions to Lennox-Gastaut. Moderate-severe NDD.
  3. XLAG — X-linked Lissencephaly with Abnormal Genitalia (15%): Truncating ARX variants
     (stopgain, frameshift) in or before homeodomain. Males: smooth brain (lissencephaly),
     ambiguous genitalia, neonatal hyperglycemia, severe epilepsy (Ohtahara). Near-universal
     early death in severe XLAG. Carrier females usually unaffected (random X-inactivation).
  4. Partington Syndrome — Poly-Ala Tract 2 Expansion (20%): GGC expansion → poly-Ala Tract 2
     ≥159 alanines. X-linked intellectual disability + dystonic hand movements (athetoid/
     choreoathetoid) + exaggerated Moro reflex + mild-moderate epilepsy (focal/GTCS).
     Better cognitive outcome than Ohtahara/XLAG. X-linked inheritance — maternal carrier females.
  5. Phenocopy / Carrier Female (10%): STXBP1/KCNQ2/SCN1A or other gene causing Ohtahara/West.
     ARX negative on panel; or rare symptomatic female carrier (skewed X-inactivation).

ARX EPILEPSY MECHANISM:
  - ARX LOF → failed MGE tangential interneuron migration → severe cortical interneuron deficit
    → loss of perisomatic GABAergic inhibition → synchronous thalamocortical bursting →
    suppression-burst EEG pattern (Ohtahara) or hypsarrhythmia (West syndrome).
  - Poly-Ala Tract 1 expansion → ARX protein aggregation → nuclear inclusions in interneurons
    → selective interneuron dysfunction (not complete LOF) → West syndrome / ISSX phenotype.
  - Temperature sensitivity: ARX-related interneuron deficits show fever sensitivity in some
    West syndrome patients. Fever threshold 37.5°C action plan relevant (not as prominent as
    SCN1A/SCN1B but documented fever-triggered spasm clusters in ARX-West patients).

X-LINKAGE AND CARRIER FEMALES:
  - ARX is on the X chromosome (Xp21.3). Males are hemizygous — one ARX copy → full expression.
  - Carrier females: heterozygous, usually unaffected due to random X-inactivation. Rarely,
    skewed X-inactivation → symptomatic carrier female with mild epilepsy, agenesis of corpus
    callosum (ACC), intellectual disability. Penetrance in females ~5-15% for neurological features.
  - Inheritance: De novo (majority of severe ARX DEE / XLAG) OR X-linked familial (mother carrier
    → affected sons and carrier daughters, Partington syndrome families). CRITICAL: if mother is
    carrier, 50% of sons will be affected. Genetic counselling MANDATORY for all ARX families.
  - Males: if ARX LOF → almost universally affected (hemizygous). No unaffected hemizygous male
    with pathogenic ARX variant has been reported for severe alleles.

CRITICAL SAFETY RULES:
  1. POLG SCREEN MANDATORY before ANY valproate use (POLG depletion → Alpers-Huttenlocher
     fulminant hepatic failure; not specific to ARX but essential before VPA in any DEE).
  2. TIAGABINE ABSOLUTE CONTRAINDICATION: GAT-1 inhibition in immature/dysmature cortex →
     GABA accumulates extrasynaptically → tonic GABA-A activation → NCSE / absence SE →
     catastrophic in ARX dysmature cortex (interneuron deficit amplifies GAT-1 NCSE risk).
  3. CBZ/OXC/PHT HIGH RISK in West / Ohtahara: NaV1.1 blockade in residual PV-interneurons
     (already reduced in ARX) → further disinhibition → infantile spasm aggravation (identical
     mechanism to Dravet syndrome NaV-blocker paradoxical worsening).
  4. VGB ≤16 weeks for West syndrome only (SHARE REMS mandatory): VGB causes irreversible
     concentric visual field constriction (30-40% of patients with prolonged use). ERG q6M.
     VGB long-term in ARX-West is HIGH RISK — only as short-term (≤16 weeks) spasm treatment.
  5. LTG HIGH RISK if myoclonic component: lamotrigine NaV1.1 block → myoclonus aggravation
     (same Dravet mechanism) — avoid if myoclonic seizures present in ARX-West evolution.
  6. ACTH Day 14 EEG MANDATORY: hypsarrhythmia resolution at Day 14 predicts 1-year spasm-
     free rate (UK-ISSS, UKISS trial endpoint). No Day 14 EEG response → switch/add therapy.
"""

