for i in range(N):
    eth  = eth_pool[i]
    allele = allele_pool[i]
    age_dx = age_dx_pool[i]
    is_mild = ('mild' in allele and 'mild-moderate' not in allele) or ('Val1065Met / p.Pro1195Ser' in allele)
    is_hepato_renal = 'Arg548Trp' in allele or 'Val1065Met' in allele
    # phenotype flags
    mts         = True                                  # 100% — MTS pathognomonic
    ataxia      = rng.random() < 0.87
    hypotonia   = rng.random() < 0.82
    oma         = rng.random() < 0.55
    retinal     = rng.random() < (0.25 if is_mild else 0.42)
    hepatic     = rng.random() < (0.12 if is_mild else 0.28)   # CHF ~25% overall
    renal       = rng.random() < (0.22 if is_mild else 0.42)   # ~38% overall
