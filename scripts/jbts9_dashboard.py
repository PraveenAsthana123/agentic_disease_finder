"""
CC2D2A Joubert Syndrome Type 9 (JBTS9) — TZ Scaffold / MKS6 Tier / COACH / Hepato-Renal
=========================================================================================
Primary Gene : CC2D2A (*612013) — 4p15.33; 1620 aa; Coiled-Coil and C2 Domain-Containing
               Protein 2A (also JBTS9-scaffold; formerly KIAA1345).
               CC2D2A is a TRANSITION ZONE (TZ) SCAFFOLD protein — part of the MKS
               (Meckelin-Schneider-Kishimoto) module, the TZ membrane gate complex.
               CC2D2A contains: N-terminal coiled-coil (CC1, aa 1–350), second coiled-coil
               (CC2, aa 350–600), central linker (aa 600–950), C2 domain (aa 950–1350;
               membrane-binding / lipid sensing), C-terminal coiled-coil (aa 1350–1620).
               CC2D2A directly binds TMEM67 (via CC1/CC2), RPGRIP1L (via CC2), CEP290,
               NPHP1, B9D1, B9D2, MKS1 — anchoring the MKS TZ complex to the ciliary gate.
               CC2D2A loss → TZ Y-link scaffold disassembly → GPCRs (SMOOTHENED, SSTR3)
               excluded from neuronal cilia → Hedgehog failure → Molar Tooth Sign (MTS),
               cerebellar vermis hypoplasia (Dandy-Walker variant spectrum).

⚠ KEY DIAGNOSTIC FEATURE — ALLELE-CLASS TIER RULE (CC2D2A):
   Biallelic null variants → MKS6 (Meckel-Gruber Syndrome 6; OMIM #612284):
     perinatal lethal — occipital encephalocele, post-axial polydactyly, cystic kidneys.
   One null + one hypomorphic missense → JBTS9 (live birth, MTS).
   Biallelic hypomorphic missense → JBTS9 (mild–moderate) or pure NPHP (very rare).
   This tier rule is identical to RPGRIP1L (JBTS7/MKS5) and TMEM67 (JBTS6/MKS3):
   allele class GOVERNS outcome — biallelic null = lethal.

⚠ COACH SYNDROME — CC2D2A IS THE SECOND MOST COMMON COACH GENE (after TMEM67):
   COACH = Cerebellar vermis hypoplasia + Oligophrenia + Ataxia + Coloboma + Hepatic fibrosis.
   CC2D2A causes ~15% of COACH syndrome (TMEM67 causes ~80%). CC2D2A-COACH features:
   MTS + congenital hepatic fibrosis (CHF; ~25%) + oculo-renal involvement. CHF in CC2D2A
   is typically milder than TMEM67-CHF; portal hypertension and varices occur but are less
   severe. Retinochoroidal coloboma (~15%) is more frequent in CC2D2A than TMEM67 COACH.
   DIAGNOSTIC TRAP: CC2D2A-COACH may present as isolated CHF or isolated renal disease
   before neurological features are recognised — MRI for MTS is mandatory in unexplained CHF.

⚠ POLYDACTYLY — JSOFD (Joubert Syndrome with Orofaciodigital Features) — ~20%:
   CC2D2A, KIF7, TCTN1-3 subtypes produce post-axial polydactyly (hands ± feet) ±
   orofacial features (macroglossia, gingival hamartomas, accessory frenulae). Skeletal
   survey + orofacial assessment mandatory for any JBTS9 patient with polydactyly.

Disease OMIM : #612285 — Joubert Syndrome 9 (JBTS9)
               #612284 — Meckel-Gruber Syndrome 6 (MKS6) — biallelic null alleles
Chromosome   : 4p15.33
Inheritance  : Autosomal Recessive — biallelic LOF; allele class governs phenotype tier
Prevalence   : ~3–5% of all Joubert syndrome cases
               ~1/600,000–1,000,000 worldwide (JBTS9 phenotype)

Protein Structure — CC2D2A (1620 aa; TZ MKS-module scaffold)
-------------------------------------------------------------
Domain 1: N-terminal coiled-coil CC1 (aa 1–350)   — TMEM67 binding / MKS complex docking
           CC1–CC2 junction (aa ~540–600):
             Arg548Trp — CC2 junction; MENA; pathogenic JBTS9 moderate-severe (hepato-renal)
Domain 2: Second coiled-coil CC2 (aa 350–600)      — RPGRIP1L binding / MKS scaffold
           Splice: c.3336+1G>A — splice donor intron 22 → null; European JBTS9/MKS6
Domain 3: Central linker (aa 600–950)              — flexible; NPHP1/B9 interaction
Domain 4: C2 domain (aa 950–1350)                  — calcium-dependent membrane binding
           C2 proximal (aa ~1065):
             Val1065Met — C2-proximal; South Asian; JBTS9 moderate
           C2 core (aa ~1195):
             Pro1195Ser — C2 core; hypomorphic; mild JBTS9 (±hepatic; low retinal)
           C2 core truncating:
             Trp1182* (c.3546G>A) — C2 domain null; pan-ethnic; MKS6 biallelic null
           C2 C-terminal (aa ~1257):
             Leu1257Pro — C2 C-terminal; pan-ethnic; JBTS9 moderate
Domain 5: C-terminal coiled-coil (aa 1350–1620)   — CEP290 / B9D1 interaction
           C-terminal truncating:
             Arg1564* (c.4690C>T) — CC C-terminal; European; MKS6/JBTS9 null

Key pathogenic variants (CC2D2A / JBTS9):
1. p.Arg1564* (c.4690C>T):   C-terminal null; European; MKS6 if biallelic null
2. p.Trp1182* (c.3546G>A):   C2 domain null; pan-ethnic; MKS6 if biallelic null
3. p.Arg548Trp (c.1642C>T):  CC1-CC2 junction; MENA; JBTS9 moderate-severe (hepato-renal)
4. p.Val1065Met (c.3193G>A): C2-proximal; South Asian; JBTS9 moderate
5. c.3336+1G>A (splice):     Intron 22 splice donor null; European; JBTS9/MKS6
6. p.Pro1195Ser (c.3583C>T): C2 core hypomorphic; mild JBTS9 (low retinal/hepatic risk)
7. p.Leu1257Pro (c.3770T>C): C2 C-terminal; pan-ethnic; JBTS9 moderate

JBTS9 Allele-Phenotype Tier Rule:
  Biallelic null/null                  → MKS6 (perinatal lethal: encephalocele + polydactyly + PKD)
  Null + hypomorphic missense           → JBTS9 (MTS + ataxia ± renal ± retinal ± hepatic)
  Biallelic missense (moderate)         → JBTS9 (MTS + ataxia + variable extra-neurological)
  Biallelic missense (one hypomorphic)  → JBTS9 mild or NPHP-like (pure renal, rare)
  NOTE: Unlike ARL13B (JBTS8), CC2D2A DOES have an MKS6 lethal tier.

Original discovery: Gorden NT et al., AJHG 2008 — CC2D2A identified in JBTS9 cohort;
  Noor A et al., Nat Genet 2008 — confirmed MKS6 allele class.
"""

