    VARIANT_WEIGHTS = [0.35, 0.20, 0.15, 0.12, 0.07, 0.05, 0.03, 0.03]

    OPH_PATTERNS = [
        "Bilateral-Complete-Ptosis-Ophthalmoplegia",
        "Bilateral-Partial-Ptosis-Restricted-Gaze",
        "Unilateral-Ptosis-Bilateral-Ophthalmoplegia",
        "Bilateral-Ptosis-Downgaze-Affected-First",
    ]
    OPH_WEIGHTS = [0.50, 0.28, 0.12, 0.10]

    patients = []
    for i in range(N_PATIENTS):
        # PEO: 100% cardinal
        peo = True
        # Exercise intolerance ~75%
        exercise_intol = rng.random() < 0.75
        # Proximal myopathy ~65%
        myopathy = rng.random() < 0.65
        # SNHL ~30%
        snhl = rng.random() < 0.30
        # Ataxia ~35%
        ataxia = rng.random() < 0.35
        # Dysphagia ~28%
        dysphagia = rng.random() < 0.28
        # Sensory neuropathy ~25%
        neuropathy = rng.random() < 0.25
        # Depression ~22%
        depression = rng.random() < 0.22
        # Parkinsonism ~12%
        parkinsonism = rng.random() < 0.12
        # Cardiomyopathy ~5% (rare)
        cardiomyopathy = rng.random() < 0.05
        # Epilepsy ~8% (rare)
        epilepsy = rng.random() < 0.08

        onset = round(rng.gauss(35, 9), 1)
        onset = max(18, min(65, onset))
        dx_delay = round(rng.gauss(6.5, 2.8), 1)
        dx_delay = max(1.0, min(14.0, dx_delay))

        ck_uln = round(rng.gauss(1.8, 0.6), 1)
        ck_uln = max(0.8, min(4.5, ck_uln))
        lactate = round(rng.gauss(2.8, 0.6), 1)
        lactate = max(1.6, min(5.5, lactate))
        deletion_pct = round(rng.gauss(28, 10), 0)
        deletion_pct = max(5, min(70, int(deletion_pct)))

        variant = rng.choices(VARIANT_POOL, weights=VARIANT_WEIGHTS, k=1)[0]
        oph_pattern = rng.choices(OPH_PATTERNS, weights=OPH_WEIGHTS, k=1)[0]

        patients.append({
            "id": f"TWNK-P{i+1:02d}",
            "age_onset_years": onset,
            "dx_delay_yr": dx_delay,
            "peo": peo,
            "oph_pattern": oph_pattern,
            "exercise_intolerance": exercise_intol,
            "proximal_myopathy": myopathy,
            "snhl": snhl,
            "ataxia": ataxia,
            "dysphagia": dysphagia,
            "sensory_neuropathy": neuropathy,
            "depression": depression,
            "parkinsonism": parkinsonism,
            "cardiomyopathy": cardiomyopathy,
            "epilepsy": epilepsy,
            "ck_x_uln": ck_uln,
            "lactate": lactate,
            "deletion_load_pct": deletion_pct,
            "variant": variant,
        })
    return patients


